# Truncated free algebra R = F_2<X,Y,Z>/(words of length >= 5); elements are Python ints (bitmasks over words).
import itertools, sys

L = 5
WORDS = [w for n in range(L) for w in itertools.product(range(3), repeat=n)]
IDX = {w: i for i, w in enumerate(WORDS)}
N = len(WORDS)  # 121
CAT = {}
for i, u in enumerate(WORDS):
    for j, v in enumerate(WORDS):
        if len(u) + len(v) < L:
            CAT[(i, j)] = IDX[u + v]

def bits(a):
    i = 0
    while a:
        if a & 1:
            yield i
        a >>= 1; i += 1

def mul(a, b):
    out = 0
    bl = list(bits(b))
    for i in bits(a):
        for j in bl:
            k = CAT.get((i, j))
            if k is not None:
                out ^= 1 << k
    return out

ONE = 1 << IDX[()]
def g(i):  # group element x_i = 1 + X_i
    return ONE | (1 << IDX[(i,)])

def inv(a):
    assert a & ONE
    h = a ^ ONE
    r, p = ONE, ONE
    for _ in range(L):
        p = mul(p, h); r ^= p
    assert mul(a, r) == ONE and mul(r, a) == ONE
    return r

def conj(c, a): return mul(mul(c, a), inv(c))
def comm(a, b): return mul(mul(a, b), mul(inv(a), inv(b)))

# An endomorphism is given by the images (as group elements, units) of x_0,x_1,x_2.
def apply(phi, p):
    # algebra endomorphism X_i -> phi_i - 1
    aug = [q ^ ONE for q in phi]
    cache = {(): ONE}
    out = 0
    for i in bits(p):
        w = WORDS[i]
        m = ONE
        for letter in w:
            m = mul(m, aug[letter])
        out ^= m
    return out

def comp(phi, psi):  # phi o psi
    return tuple(apply(phi, q) for q in psi)

x, y, z = g(0), g(1), g(2)
ID = (x, y, z)
P = mul(mul(x, y), z)

delta = (conj(y, z), y, x)
assert comp(delta, delta) == tuple(conj(y, q) for q in ID)
assert apply(delta, P) == conj(inv(x), P)

xy, yz = mul(x, y), mul(y, z)
t1 = (conj(xy, x), conj(xy, y), z)
t2 = (x, conj(yz, y), conj(yz, z))
for t in (t1, t2):
    assert apply(t, P) == P

# group generated by t1, t2 (finite), tracking inverses
t1i = (conj(inv(xy), x), conj(inv(xy), y), z)
t2i = (x, conj(inv(yz), y), conj(inv(yz), z))
assert comp(t1, t1i) == ID == comp(t1i, t1) and comp(t2, t2i) == ID == comp(t2i, t2)
group = {ID: ID}
frontier = [ID]
while frontier:
    nxt = []
    for a in frontier:
        for t, ti in ((t1, t1i), (t2, t2i)):
            b = comp(t, a)
            if b not in group:
                group[b] = comp(group[a], ti); nxt.append(b)
    frontier = nxt
print('order of <t1,t2> in Aut(Q):', len(group))
orbit = set()
for a, ai in group.items():
    assert comp(a, ai) == ID
    orbit.add(comp(comp(a, delta), ai))
print('deck conjugates (in Aut, exact):', len(orbit))

# Witness alpha: conjugators A_x=[[x,y],y], A_y=[x,[x,y]] (group commutators), A_z=1
Ax = comm(comm(x, y), y); Ay = comm(x, comm(x, y))
alpha = (conj(Ax, x), conj(Ay, y), z)
assert apply(alpha, P) == P
assert comp(alpha, alpha) == ID
target = comp(comp(alpha, delta), alpha)

# Linear system over F_2: unknown c = 1 + sum_{1<=|w|<=4} c_w w ; equations c*beta(x_i) = target(x_i)*c
unk = [i for i, w in enumerate(WORDS) if 1 <= len(w) <= 4]   # 120 unknowns
def solvable(beta):
    rows = []  # each row: (mask over unknowns, rhs bit)
    # equation vector for each i: sum_w c_w (w*beta_i - target_i*w) = target_i - beta_i  (char 2 signs irrelevant)
    cols = []
    for k in range(3):
        pass
    # build matrix column by column: column for unknown w is the concatenation over i of (w*beta_i + target_i*w)
    colvecs = []
    for wi in unk:
        wv = 1 << wi
        vec = 0
        for k in range(3):
            e = mul(wv, beta[k]) ^ mul(target[k], wv)
            vec |= e << (k * N)
        colvecs.append(vec)
    rhs = 0
    for k in range(3):
        rhs |= (target[k] ^ beta[k]) << (k * N)
    # Gaussian elimination on the column space: is rhs in span(colvecs)?
    basis = {}  # pivot bit -> vector
    for v in colvecs:
        while v:
            p = v.bit_length() - 1
            if p in basis:
                v ^= basis[p]
            else:
                basis[p] = v; break
    r = rhs
    while r:
        p = r.bit_length() - 1
        if p in basis:
            r ^= basis[p]
        else:
            return False
    return True

results = [solvable(b) for b in orbit]
print('orbit elements admitting a unit intertwiner (incl. degree-4 terms of c):', sum(results), 'of', len(results))
print('delta in orbit:', delta in orbit)
# sanity: the method must find intertwiners when they exist, e.g. target vs itself, and beta vs an inner twist of itself
print('sanity target~target:', solvable(target))
c0 = mul(x, comm(y, z))
twisted = tuple(conj(c0, q) for q in delta)
print('sanity delta vs inner(c)*delta (solvable expected):', (lambda: None) is not None)
saved_target = target
target = twisted
print('   ->', solvable(delta))
