"""Diagnostic exact source algebra on the actual six-dimensional H1 quotient.

This computes the F_p algebra generated by the eleven F23 source matrices
after the explicit principal-line quotient. It tests whether that algebra
contains all scalar matrices from the ambient scalar field. Only the
listed finite characters are tested; no universal algebra theorem is made.
"""
from pathlib import Path
from hashlib import sha256
from collections import deque
import json
import numpy as np
import affine_trace_prime_base_stage as ff


def one_field(data, p, m, modulus, character_list):
    digits, weights, mul, add, powers, trace = ff.finite_field(p, m, modulus)
    q = p**m
    minus = ((-digits) % p)@weights
    inverse = np.array([0]+[next(j for j in range(1, q) if mul[i, j] == 1)
                            for i in range(1, q)], dtype=np.int16)
    chars = np.array(character_list, dtype=np.int16)
    n = len(chars)
    cache = {}

    def monomial(exponent):
        key = tuple(exponent)
        if key not in cache:
            value = np.ones(n, dtype=np.int16)
            for j, power in enumerate(key):
                value = mul[value, powers[chars[:, j], power % (q-1)]]
            cache[key] = value
        return cache[key]

    def polynomial(poly):
        result = np.zeros((n, m), dtype=np.int32)
        for coefficient, exponent in poly:
            result += (coefficient % p)*digits[monomial(exponent)]
        return (result % p)@weights

    old = [r for r in data['records'] if r['index'] < 11]
    matrices = np.zeros((n, 11, 7, 7), dtype=np.int16)
    for i, record in enumerate(old):
        for j, row in enumerate(record['action_matrix']):
            for k, poly in enumerate(row):
                matrices[:, i, j, k] = polynomial(poly)

    def matrix_mul(a, b):
        result = np.zeros((6, 6), dtype=np.int16)
        for j in range(6):
            result = add[result, mul[a[:, j, None], b[j, None, :]]]
        return result

    inverse_prime = np.array([0]+[pow(i, -1, p) for i in range(1, p)], dtype=np.int16)
    results = []
    for index, character in enumerate(chars):
        delta = add[character, minus[1]]
        j = next(i for i in range(3, 7) if delta[i] != 0)
        keep = [i for i in range(7) if i != j]
        factors = mul[delta[keep], inverse[delta[j]]]
        source = []
        for matrix in matrices[index]:
            principal_image = np.zeros(7, dtype=np.int16)
            for r in range(7):
                principal_image = add[principal_image, mul[matrix[:, r], delta[r]]]
            assert np.array_equal(principal_image, delta)
            quotient = add[matrix[np.ix_(keep, keep)],
                           minus[mul[factors[:, None], matrix[j, keep][None, :]]]]
            source.append(quotient)
        basis = {}
        queue = deque()
        operations = []

        def vector(matrix):
            return digits[matrix.reshape(-1)].reshape(-1).copy()

        def back(v):
            return (v.reshape(36, m)@weights).reshape(6, 6).astype(np.int16)

        def remainder(v):
            v = v.copy()
            for pivot in sorted(basis):
                if v[pivot]:
                    v = (v-v[pivot]*basis[pivot]) % p
            return v

        def insert(matrix, origin):
            v = remainder(vector(matrix))
            nz = np.flatnonzero(v)
            if not len(nz):
                return
            pivot = int(nz[0])
            v = v*inverse_prime[v[pivot]] % p
            basis[pivot] = v
            queue.append(pivot)
            operations.append({'pivot': pivot, 'origin': origin})

        identity = np.eye(6, dtype=np.int16)
        insert(identity, ['identity'])
        products = 0
        while queue:
            pivot = queue.popleft()
            matrix = back(basis[pivot])
            for i, generator in enumerate(source):
                insert(matrix_mul(matrix, generator), ['right_product', pivot, i])
                products += 1
        scalars = []
        for r in range(m):
            candidate = p**r*identity
            residue = remainder(vector(candidate))
            scalars.append({'scalar': p**r, 'contained': not bool(np.any(residue)),
                            'residue': residue.tolist()})
        total = 1
        for value in character:
            total = int(mul[total, value])
        result = {'characters': character.tolist(), 'quotient_pivot': j+1,
                  'total_character_product': total, 'algebra_dimension_over_prime_field': len(basis),
                  'right_products_checked': products, 'scalar_basis_checks': scalars,
                  'contains_full_scalar_field': all(x['contained'] for x in scalars),
                  'basis_pivots': sorted(basis), 'basis_vectors': [basis[v].tolist() for v in sorted(basis)],
                  'basis_production': operations}
        results.append(result)
        print(json.dumps({'field': q, 'characters': character.tolist(), 'total': total,
                          'dimension': len(basis), 'full_scalars': result['contains_full_scalar_field']}), flush=True)
    return {'prime': p, 'extension_degree': m, 'field_order': q,
            'modulus_coefficients': modulus, 'results': results}


def main():
    producer = Path(__file__).resolve()
    source = producer.with_name('affine_obstruction_stage_output.json')
    data = json.loads(source.read_text())
    f9 = json.loads(producer.with_name('affine_f9_translation_obstruction_stage_output.json').read_text())
    other = json.loads(producer.with_name('affine_trace_prime_base_stage_output.json').read_text())
    choices9 = f9['deficient_characters'][:8]
    specifications = [(3, 2, [1, 0], choices9)]
    for record in other['results']:
        specifications.append((record['prime'], record['extension_degree'],
                               record['modulus_coefficients'], record['character_tuples'][:8]))
    results = []
    target = producer.with_name('affine_source_algebra_stage_output.json')
    for specification in specifications:
        results.append(one_field(data, *specification))
        output = {'status': 'UNREGISTERED_EXACT_SOURCE_ALGEBRA_DIAGNOSTICS',
                  'producer_sha256': sha256(producer.read_bytes()).hexdigest(),
                  'source_sha256': sha256(source.read_bytes()).hexdigest(), 'results': results,
                  'scope': 'Only the recorded characters and exact principal-line quotient are tested. Each algebra is generated by the actual eleven old-source matrices. No image theorem for the full pure braid group is substituted.'}
        target.write_text(json.dumps(output, separators=(',', ':'))+'\n')
    print(json.dumps({'status': output['status'],
                      'all_full_scalars': all(r['contains_full_scalar_field'] for x in results for r in x['results']),
                      'output_sha256': sha256(target.read_bytes()).hexdigest()}, indent=2))


if __name__ == '__main__':
    main()
