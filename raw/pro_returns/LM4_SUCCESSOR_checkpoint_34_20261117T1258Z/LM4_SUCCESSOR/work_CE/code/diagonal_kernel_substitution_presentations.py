#!/usr/bin/env python3
"""Literal old-B6 substitution presentations of the eight diagonal kernels.

The substitutions are auxiliary free-group automorphisms, not asserted
to be geometric monodromies of the full deleted surface.
"""
from pathlib import Path
import json,hashlib,time

ROOT=Path(__file__).resolve().parents[2]
P=ROOT/'work_CE/next_symmetric_nodes'
IN=P/'all_diagonal_section_transports.json'
STATIC=ROOT/'work_DE/next_marginal_source/old_lassos_far_cut_conversion.json'
REF=P/'retained_section_kernel_braids.json'
j=json.loads(IN.read_text());st=json.loads(STATIC.read_text());ref=json.loads(REF.read_text())

def red(w):
    a=[]
    for x in w:
        if a and a[-1]==-x:a.pop()
        else:a.append(x)
    return tuple(a)
def inv(w):return tuple(-x for x in reversed(w))
def sub(w,A):return red(x for y in w for x in (A[y] if y>0 else inv(A[-y])))
def maps(d):return {int(k):tuple(v) for k,v in d.items()}

old_to_cut=maps(st['forward_old_to_far']);cut_to_old=maps(st['inverse_far_to_old'])
reference_operators={r['name']:maps(r['geometric_push']) for r in ref['loops'] if r['name'] in ('v0','v1')}
delta={1:(1,),2:(2,),3:(),4:(),5:(),6:()}
start=time.monotonic();results=[]
for row in j['rows']:
    filling=maps(row['six_cut_filling']);to_reference=maps(row['old_to_reference_four'])
    active={v[0]:k for k,v in filling.items() if v}
    inactive=[k for k,v in filling.items() if not v]
    assert len(active)==4 and len(inactive)==2
    section={i:(active[i],) for i in range(1,5)}
    inactive_old=[cut_to_old[k] for k in inactive]
    r=tuple(row['transported_node_relator_old'])
    assert sub(r,to_reference)==(3,4,-3,-4)
    substitutions={}
    for name,ops in row['transported_retained_operators'].items():
        actual={}
        for key in ('push','pullback'):
            op=maps(ops[key]);cut_op={k:(sub(op[v[0]],section) if v else (k,)) for k,v in filling.items()}
            old_op={i:sub(sub(old_to_cut[i],cut_op),cut_to_old) for i in range(1,7)}
            for w in inactive_old:assert sub(w,old_op)==w
            for i in range(1,7):assert sub(old_op[i],delta)==delta[i]
            actual[key]=old_op
        for i in range(1,7):
            assert sub(actual['push'][i],actual['pullback'])==(i,)
            assert sub(actual['pullback'][i],actual['push'])==(i,)
            assert sub(actual['push'][i],to_reference)==sub(to_reference[i],reference_operators[name])
        substitutions[name]=actual
    result={'u_exponent':row['u_exponent'],
        'inactive_far_cut_indices':inactive,'inactive_meridians_in_old_basis':inactive_old,
        'iterated_relator_in_old_basis':r,'old_to_reference_four':to_reference,
        'signed_substitution_automorphisms_on_old_B6':substitutions,
        'kernel_formula':'normalclosure_B6(inactive_meridians union {Phi(r):Phi in the group generated by the two substitutions and inverses})',
        'both_actual_diagonal_rows':row['two_actual_diagonal_rows']}
    results.append(result)
    print('PASS exponent',row['u_exponent'],'inactive',list(map(list,inactive_old)),
          'relator length',len(r),'two B6 automorphisms and inverses; all factor diagrams',flush=True)

out={'scope':__doc__,'input_sha256':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in (IN,STATIC,REF)},
     'producer_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
     'presentations':results,'elapsed_seconds':time.monotonic()-start,
     'claims_excluded':['substitutions are full-surface geometric monodromies','finite ordinary presentation','full-column stabilization','kappa vanishing']}
(P/'diagonal_kernel_substitution_presentations.json').write_text(json.dumps(out,indent=2)+'\n')
print('PASS four literal finite substitution presentations for all eight diagonal stabilizers.',flush=True)
