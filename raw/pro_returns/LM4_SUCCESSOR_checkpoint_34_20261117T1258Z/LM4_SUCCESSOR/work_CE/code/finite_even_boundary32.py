FULL=P/'actual_full21_Fox.json';OTHER=P/'full21_opposite_sheet_nodes.json'
D=json.loads(FULL.read_text());O=json.loads(OTHER.read_text())
T=[tuple(x) for x in D['retained_word_DAG']]
R=[tuple(x) for x in D['R_word_DAG']]
gens=[None]+[tuple(x) for x in D['common_R_generators'][1:]]
G=[tuple(x) for x in D['group_elements']]
Tindex={(p,x):i for i,(p,x,n) in enumerate(T) if i}
Rindex={(p,x):i for i,(p,x,n) in enumerate(R) if i}
gen_index={x:i for i,x in enumerate(gens) if i}
Gindex={x:i for i,x in enumerate(G)}
base_sizes={'T':len(T),'R':len(R),'R_generators':len(gens),'G':len(G)}
retained={j:i+1 for i,j in enumerate(D['retained_paired_indices'])}
beta={int(k):v[0] for k,v in D['retained_involution'].items()}
beta_ids={0:0}


def append(nodes,index,p,x):
    if p and nodes[p][1]==-x:return nodes[p][0]
    k=(p,x)
    if k not in index:index[k]=len(nodes);nodes.append((p,x,nodes[p][2]+1))
    return index[k]


def t_word(w):
    p=0
    for x in w:p=append(T,Tindex,p,x)
    return p


def r_word(w):
    p=0
    for x in w:p=append(R,Rindex,p,x)
    return p


def bet(t):
    if t not in beta_ids:
        trail=[];p=t
        while p not in beta_ids:trail.append(p);p=T[p][0]
        for p in reversed(trail):
            a,x,n=T[p]
            beta_ids[p]=append(T,Tindex,beta_ids[a],(1 if x>0 else-1)*beta[abs(x)])
    return beta_ids[t]


def gen(t,i):
    k=(t,i)
    if k not in gen_index:gen_index[k]=len(gens);gens.append(k)
    return gen_index[k]


def group(g):
    if g not in Gindex:Gindex[g]=len(G);G.append(g)
    return Gindex[g]


def right(g,x):
    a,b,t=G[g];j=abs(x);s=1 if x>0 else-1
    if j in retained:return group((a,b,append(T,Tindex,t,s*retained[j])))
    if j<12:return group((append(R,Rindex,a,s*gen(t,j)),b,t))
    return group((a,append(R,Rindex,b,s*gen(bet(t),j-10)),t))


def eval_word(w):
    g=0
    for x in w:g=right(g,x)
    return g


def add(d,k,n):
    d[k]+=n
    if not d[k]:del d[k]


started=time.monotonic()
source=[m for m in D['matrices'] if m['family']=='source' and m['direction']=='push']
assert len(source)==11
names=[m['name'] for m in source]
faces=[]


def verify_boundary(c):
    boundary=defaultdict(int)
    for (row,g,sw),n in c.items():
        if row<=21:
            if sw==0:end=(right(g,row),0)
            else:
                # The matrix's only source-prefix/fiber-edge term is
                # s^-1*e_j. Its right endpoint is psi_s(p_j)*s^-1.
                assert g==0
                end=(source[sw-1]['generator_images_G'][row-1],sw)
        else:
            # All source-edge terms are g*s^-1*e_s; the edge cancels
            # the inverse source prefix with no G conjugation.
            assert row-21==sw and sw!=0
            end=(g,0)
        add(boundary,end,n);add(boundary,(g,sw),-n)
    assert not boundary,('entire32-row next boundary',boundary)


def pack(c):return [[r,g,s,n] for(r,g,s),n in sorted(c.items())]


for si,m in enumerate(source,1):
    for j,col in enumerate(m['columns'],1):
        c=defaultdict(int)
        for row,g,n in col:add(c,(row,g,0),-n)
        add(c,(j,0,si),1)
        add(c,(21+si,m['generator_images_G'][j-1],si),1)
        add(c,(21+si,0,si),-1)
        verify_boundary(c)
        faces.append({'type':'source_rectangle','source_index':si,'source_name':m['name'],
                      'paired_generator':j,'boundary32':pack(c),
                      'full_boundary_zero':True})
