    for term in c['full21_cycle']:
        h=term['G_coefficient']
        g=group((other_R(h['A_word']),other_R(h['B_word']),t_word(h['retained_word'])))
        add(chain,(term['row'],g,0),term['coefficient'])
    verify_boundary(chain)
    assert eval_word(c['literal_F21_word'])==0
    faces.append({'type':'node','sheet':1,'node_index':c['node_index'],
                  'literal_F21_word':c['literal_F21_word'],'boundary32':pack(chain),
                  'full_boundary_zero':True})
