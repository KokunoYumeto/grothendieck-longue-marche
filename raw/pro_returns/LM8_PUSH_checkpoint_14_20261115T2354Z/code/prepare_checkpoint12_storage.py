#!/usr/bin/env python3
"""Assemble checkpoint12 only after every required full replay has passed."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
def read(path):
    return json.loads(path.read_text())
def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()

plan = read(ROOT / 'notes/checkpoint11_storage_plan.json')
old_v2 = next(e for e in plan['transforms']
              if e['original_path'] == 'code/pbc_native_smallmod_v2_iterated_trace.jsonl.gz')
v2 = read(ROOT.parent / 'checkpoint12_smallmod_replay/pbc_smallmod_v2_replay_transform.json')
v1 = read(ROOT.parent / 'checkpoint12_smallmod_replay/pbc_smallmod_v1_prefix_transform.json')
primary = read(ROOT.parent / 'checkpoint12_primary_replay/pbc_primary3_v1_replay_transform.json')
suffix = read(ROOT.parent / 'checkpoint12_suffix3_replay/pbc_suffix3_v2_full_replay_transform.json')
qa = read(ROOT / 'notes/checkpoint12_qa_encoding.json')
state = read(ROOT / 'notes/checkpoint12_frozen_state.json')
assert qa['status'] == 'PASS'
large = [e for e in plan['transforms']
         if e.get('codec') != 'PNG_FROM_PDF01'
         and e['original_path'] != v2['original_path']]
assert len(large) == 8
plan['transforms'] = large + [v2, primary, suffix] + qa['transforms']
plan['exact_prefix_reconstructions'] = [e for e in plan['exact_prefix_reconstructions']
                                      if e['original_path'] != v1['original_path']] + [v1]
# The prior recipe remains an exact work record and still has its operational
# leaf input, independently of the new checkpoint12 leaf. The primary attempt
# also retains its separately named frozen checkpoint11 leaf input.
plan['additional_payloads'] = old_v2['additional_payloads']
plan.update({
    'scheduled_utc': '2026-11-15T22:00:00Z',
    'paper_pages': state['paper_pages'], 'paper_statements': state['paper_statements'],
    'verification_scope': (
        'Every large numerical encoding and replay has a complete decoded count '
        'and SHA-256 check. The current smallmod-v2, primary3 and corrected '
        'suffix3 traces are compared byte-for-byte against full actual replays. '
        'All earlier large payloads, exact prefixes and partial records remain '
        'covered. The failed first suffix3 attempt is retained literally. '
        'Every encoded PNG is regenerated byte-for-byte. The materialized '
        'checkpoint01–11 history retains every historical entry or its individually '
        'specified exact decoded replacement. C.31 remains Open.'),
})
names = [e['original_path'] for e in plan['transforms']]
names += [e['original_path'] for e in plan['exact_prefix_reconstructions']]
names += [e['original_path'] for e in plan['superseded_compression_wrappers']]
assert len(names) == len(set(names))
stored = {}
for entry in plan['transforms'] + [v1]:
    assert entry['entire_decoded_byte_hash_verified']
    if entry in plan['transforms']:
        assert entry['kind'] in ('raw_bytes', 'gzip_payload')
    path = Path(entry['local_encoded_file'])
    digest = entry.get('encoded_xz_sha256', entry.get('stored_sha256'))
    assert sha(path) == digest, str(path)
    stored[entry['stored_path']] = path.stat().st_size
    for extra in entry.get('additional_payloads', []):
        path = Path(extra['local_file'])
        assert sha(path) == extra['sha256'], str(path)
        stored[extra['path']] = path.stat().st_size
for extra in plan['additional_payloads']:
    path = Path(extra['local_file'])
    assert sha(path) == extra['sha256']
    stored[extra['path']] = path.stat().st_size
dest = ROOT / 'notes/checkpoint12_storage_plan.json'
dest.write_text(json.dumps(plan, indent=2) + '\n')
print(json.dumps({
    'status': 'PASS', 'transforms': len(plan['transforms']),
    'exact_prefix_reconstructions': len(plan['exact_prefix_reconstructions']),
    'encoded_pngs': qa['encoded_images'], 'distinct_stored_payloads': len(stored),
    'stored_payload_bytes': sum(stored.values()),
    'all_payload_hashes_checked': True,
    'retained_prior_operational_leaf': old_v2['additional_payloads'][0]['path'],
    'path': str(dest),
}, indent=2))
