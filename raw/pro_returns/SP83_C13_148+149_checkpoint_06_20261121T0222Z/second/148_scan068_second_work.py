def matrix_figure(rows,x='.18cm',y='-.30cm',font=r'\ttfamily\scriptsize'):
    out=[r'\figure{\begin{tikzpicture}[x='+x+',y='+y+']', '% Literal rows:']
    out.extend('% '+row for row in rows)
    for i,row in enumerate(rows):
        for j,ch in enumerate(row):
            if ch!=' ':
                out.append(r'\node[inner sep=0pt,font='+font+'] at ('+str(j)+','+str(i)+'){'+ch+'};')
    out.append(r'\end{tikzpicture}}')
    return '\n'.join(out)

