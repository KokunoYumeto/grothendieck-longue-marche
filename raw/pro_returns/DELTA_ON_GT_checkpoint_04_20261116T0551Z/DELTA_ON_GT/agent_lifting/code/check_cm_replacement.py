#!/usr/bin/env python3
"""Finite exact checks used in the arithmetic replacement proof."""
from itertools import product

def mul(A,B,n):
    a,b,c,d=A;e,f,g,h=B
    return ((a*e+b*g)%n,(a*f+b*h)%n,(c*e+d*g)%n,(c*f+d*h)%n)
def det(A,n): a,b,c,d=A;return (a*d-b*c)%n
def powmat(A,k,n):
    out=(1,0,0,1)
    for _ in range(k):out=mul(out,A,n)
    return out

def main():
    pts=[(x,y) for x,y in product(range(7),repeat=2) if (y*y-x*x*x-1)%7==0]
    print('E3 y^2=x^3+1 over F7: affine points =',pts)
    print('#E3(F7) =',len(pts)+1,'; trace =',8-(len(pts)+1))
    assert len(pts)+1==12
    print('Frobenius polynomial: T^2+4T+7; roots -2 +/- sqrt(-3)')
    # Elements u+v*zeta, zeta^2=-1-zeta.
    def cm_mul(x,y):
        u,v=x;s,t=y
        return (u*s-v*t,u*t+v*s-v*t)
    a=(3,2);abar=(1,-2)
    assert cm_mul(a,abar)==(7,0)
    assert cm_mul(a,a)==(5,8)
    print('a=3+2*zeta=1-2*zeta^2; norm(a)=7; a/bar(a)=(5+8*zeta)/7')
    Z=(0,1,-1,-1)
    inv7=pow(7,-1,16)
    eta=tuple(((-3 if i in (0,3) else 0)-8*Z[i])*inv7%16 for i in range(4))
    print('eta matrix modulo16 =',eta)
    assert eta==(11,8,8,3)
    assert tuple(v%4 for v in eta)==(3,0,0,3)
    print('eta modulo4 = -I')
    G=[M for M in product(range(3),repeat=4) if det(M,3)==1]
    S=(0,1,2,0);R=(0,2,1,2);I=(1,0,0,1)
    CR=[M for M in G if mul(M,R,3)==mul(R,M,3)]
    CS=[M for M in G if mul(M,S,3)==mul(S,M,3)]
    assert len(CR)==6 and len(CS)==4
    print('C_SL2(F3)(R) =',CR)
    print('C_SL2(F3)(S) =',CS)
    # C6 x C4, delta(i,j)=i+j mod2. ker(delta) is generated by (1,1).
    ker={(i,j) for i in range(6) for j in range(4) if (i+j)%2==0}
    cyclic={(k%6,k%4) for k in range(12)}
    assert ker==cyclic
    extra=(3,0)
    generated=cyclic|{((i+extra[0])%6,(j+extra[1])%4) for i,j in cyclic}
    assert len(generated)==24
    print('ker(delta) = cyclic order12; adding (-I,I) gives all24 frame pairs')
    print('All arithmetic finite checks passed.')

if __name__=='__main__':main()
