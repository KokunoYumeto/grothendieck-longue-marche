#!/usr/bin/env python3
"""Perfect correction group and exact modular comparison for the A5 source."""
from pathlib import Path
from collections import deque
from contextlib import redirect_stdout
import io,json,runpy,time
import numpy as np
from sympy.combinatorics import PermutationGroup,Permutation

def main():
    start=time.time();here=Path(__file__).resolve().parent
    with redirect_stdout(io.StringIO()):d=runpy.run_path(str(here/'de_distribution_test.py'))
    compressed=np.load(here/'de_ferrari_a5_source_compressed.npz')
    s,r=compressed['s'],compressed['r'];identity=Permutation(list(range(len(s))))
    letters={0:s,1:r,-1:r[r]}
    def word(w):
        out=np.arange(len(s))
        for t in w:out=letters[t][out]
        return Permutation(out.tolist())
    info=json.loads((here/'de_ferrari_a5_corrections.json').read_text())
    cert=np.load(here/'de_ferrari_a5_corrections.npz')
    Dgens=[Permutation(p.tolist()) for p in cert['derived_generators']]
    chosen=[];C=PermutationGroup([identity])
    for p in sorted(Dgens,key=lambda p:int(p.order()),reverse=True):
        if not C.contains(p):
            chosen.append(p);C=PermutationGroup(chosen)
            print('correction generators',len(chosen),'order',C.order(),flush=True)
    assert C.order()==info['F_prime_K6_image_order'] and all(C.contains(p) for p in Dgens)
    second=C.derived_subgroup();second_order=int(second.order())
    print('correction derived order',second_order,flush=True)
    assert second_order==info['F_prime_K6_image_order']
    F=PermutationGroup([word(d['xword']),word(d['yword'])]);Forder=int(F.order())
    E=F.derived_subgroup();Eorder=int(E.order())
    assert Eorder==4*info['F_prime_K6_image_order']
    print('F derived mod correction order',Eorder//int(C.order()),flush=True)
    P=PermutationGroup([Permutation(cert['N_images'][i].tolist()) for i in info['N_selected_generator_indices']])
    assert int(P.order())==info['N_image_order']
    def canon(a,m):
        a=tuple(int(x)%m for x in a);return min(a,tuple(-x%m for x in a))
    def mul(a,b,m):
        A,B,C,D=a;e,f,g,h=b
        return canon((A*e+B*g,A*f+B*h,C*e+D*g,C*f+D*h),m)
    def invert(a,m):
        A,B,C,D=a;return canon((D,-B,-C,A),m)
    ss=canon((0,1,-1,0),6);rr=canon((0,-1,1,-1),6);one=canon((1,0,0,1),6)
    section={one:[]};queue=[one]
    for q in queue:
        for t,g in ((0,ss),(1,rr)):
            h=mul(q,g,6)
            if h not in section:section[h]=section[q]+[t];queue.append(h)
    assert len(queue)==72
    relations=[]
    for q in queue:
        for t,g in ((0,ss),(1,rr)):
            h=mul(q,g,6);rel=section[q]+[t]+d['binv'](section[h])
            assert P.contains(word(rel));relations.append(rel)
    # The entire kernel of B->PSL2(Z/6) is generated by these Schreier
    # words.  Both it and preimage(P) have index72, proving equality.
    aa=canon((1,1,0,1),3);bb=canon((1,0,-1,1),3)
    x=mul(aa,aa,3);y=mul(bb,bb,3)
    fimages={1:x,2:y,-1:invert(x,3),-2:invert(y,3)}
    values=[]
    for i,rec in enumerate(json.loads((here/'de_ferrari_fibres.json').read_text())['records']):
        value=canon((1,0,0,1),3)
        for t in rec['actual_commutator_word_f']:value=mul(value,fimages[t],3)
        values.append({'certificate_index':i,'q3_f':list(value),'missing_coset':rec['missing_coset']})
    # Galois matrix specialization at chi=1: the two unipotent factors
    # have parameter -8*kappa2.  Reduction modulo3 gives these values.
    kummer=[]
    for k in range(3):
        a=-8*k;kummer.append(mul(canon((1,0,a,1),3),canon((1,a,0,1),3),3))
    assert len(set(kummer))==3
    assert all(tuple(row['q3_f']) in kummer for row in values)
    for row in values:row['matching_kappa2_mod3']=kummer.index(tuple(row['q3_f']))
    out={'correction_group_is_perfect':True,'correction_order':int(C.order()),
         'correction_derived_order':second_order,'F_image_order':Forder,'F_derived_image_order':Eorder,
         'F_derived_mod_correction_order':4,'source_mod_N_order':72,
         'PSL2_Z6_order':72,'complete_Schreier_kernel_generators_verified':len(relations),
         'actual_modular_quotient_comparison':True,'three_Galois_q3_matrices':[list(k) for k in kummer],
         'records':values,'selected_correction_generators':len(chosen),
         'seconds':round(time.time()-start,3)}
    here.joinpath('de_ferrari_a5_compare.json').write_text(json.dumps(out,indent=2)+'\n')
    np.savez_compressed(here/'de_ferrari_a5_compare.npz',perfect_generators=np.array([p.array_form for p in chosen]),
                        perfect_derived_generators=np.array([p.array_form for p in second.generators]),
                        F_derived_generators=np.array([p.array_form for p in E.generators]))
    print(json.dumps({k:v for k,v in out.items() if k!='records'},indent=2),flush=True)

if __name__=='__main__':main()
