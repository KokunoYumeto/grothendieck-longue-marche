#!/usr/bin/env python3
"""Exhaustive binary E24 fibre test of the E30 order-two torsion class."""
from pathlib import Path
from contextlib import redirect_stdout
import io,json,runpy,time
import numpy as np
from de_ferrari_two_model import FerrariTwo
from de_ferrari_two_core import InducedTwo
from de_ferrari_two_conjugacy import Conjugacy

def main():
    start=time.time();here=Path(__file__).resolve().parent
    with redirect_stdout(io.StringIO()):d=runpy.run_path(str(here/'de_distribution_test.py'))
    H=FerrariTwo(6);W=InducedTwo(H,d,4)
    delta=H.mul(H.mul(H.a,H.b),H.c);x=H.power(delta,2);z4=H.power(delta,4)
    assert np.array_equal(H.power(z4,4),H.one) and not np.array_equal(H.power(z4,2),H.one)
    assert all(np.array_equal(H.comm(z4,g),H.one) for g in (H.a,H.b,H.c))
    solver=Conjugacy(H,x)
    print('centralizer charts',json.dumps(solver.metadata()),flush=True)
    rows=json.loads((here/'de_ferrari_two_lift.json').read_text())['records']
    origins=json.loads((here/'de_ferrari_fibres.json').read_text())['records']
    CM=np.load(here/'de_ferrari_two_degree6_module.npz')['F_prime_basis']
    X=W.word(d['xword']);outrows=[];cache={};all_targets=set()
    for row,origin in zip(rows,origins):
        ix=row['certificate_index'];chosen=row['chosen_witness']
        base=np.array(chosen['correction_coefficients'],dtype=np.int64)
        original=[H.decode(e) for e in chosen['actual_binary_braid_images']]
        xg=W.power(X,origin['integral_cusp_gauge'])
        for branch in row['branches']:
            lam=branch['lambda_residue'];part=np.array(branch['particular_correction'],dtype=np.int64)
            kernel=np.array(branch['homogeneous_correction_basis'],dtype=np.int64);assert kernel.shape==(7,1)
            for epsilon in range(2):
                coeff=(part+epsilon*kernel[:,0])%2
                difference=(coeff-base)%2
                correction=W.conj(xg,W.element(CM@difference%2))[1][W.root]
                images=[original[0],H.conj(H.inv(correction[4]),original[1]),H.conj(H.inv(correction[5]),original[2])]
                H.check_braids(images)
                y=H.power(H.mul(H.mul(images[0],images[1]),images[2]),2)
                assert np.array_equal(H.power(y,2),H.power(z4,lam))
                all_targets.add(tuple(y));hits=[]
                for exponent in range(4):
                    target=H.mul(y,H.power(z4,exponent));key=tuple(target)
                    if key not in cache:cache[key]=solver.conjugator(target)
                    answer=cache[key]
                    if answer is not None:
                        conjugator=answer['conjugator']
                        assert np.array_equal(H.conj(conjugator,x),target)
                        hits.append({'central_exponent':exponent,'outer_coset':answer['outer_coset'],
                                     'outer_word':answer['outer_word'],'layer_coefficients':answer['layer_coefficients'],
                                     'conjugator':H.encode(conjugator),'U_factor':H.encode(answer['U_factor'])})
                record={'certificate_index':ix,'missing_coset':row['missing_coset'],
                        'lambda_residue':lam,'binary_parameter':epsilon,
                        'torsion_class_passes':bool(hits),'passing_central_exponents':[h['central_exponent'] for h in hits],
                        'image_delta_squared':H.encode(y),'witnesses':hits}
                outrows.append(record)
                print(json.dumps({k:v for k,v in record.items() if k not in ('image_delta_squared','witnesses')}),flush=True)
    out={'test':'conjugacy of (a_prime b_prime c_prime)^2 and (abc)^2 modulo the central subgroup generated by (abc)^4',
         'binary_degree':6,'complete_96_branch_line_inputs':len(outrows),
         'distinct_delta_squared_images':len(all_targets),'distinct_central_translate_targets':len(cache),
         'passes_by_lambda':{str(lam):sum(r['torsion_class_passes'] for r in outrows if r['lambda_residue']==lam) for lam in (1,73)},
         'centralizer_charts':solver.metadata(),'all_centralizer_fibres_retained':True,
         'all_positive_conjugacies_substituted_in_actual_group':True,'records':outrows,
         'seconds':round(time.time()-start,3)}
    here.joinpath('de_ferrari_two_torsion.json').write_text(json.dumps(out,indent=2)+'\n')
    certificate={}
    for c in solver.charts:
        for layer in c['layers']:
            stem=f"coset_{c['coset']}_weight_{layer['weight']}"
            certificate[stem+'_matrix']=layer['matrix']
            certificate[stem+'_basis_units']=np.array([g[:-1] for g in layer['basis']])
            certificate[stem+'_basis_automorphisms']=np.array([H.aut.images[int(g[-1])] for g in layer['basis']])
    np.savez_compressed(here/'de_ferrari_two_torsion_certificate.npz',**certificate)
    print(json.dumps({k:v for k,v in out.items() if k!='records'},indent=2),flush=True)

if __name__=='__main__':main()
