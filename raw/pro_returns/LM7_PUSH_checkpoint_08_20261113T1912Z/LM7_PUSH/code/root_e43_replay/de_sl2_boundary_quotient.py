#!/usr/bin/env python3
"""Exact Fermat H image in the maximal solvable SL2(F5) source quotient.

The comparison is derived from the actual maps already certified in
E38.  The old A5 images of x,y have order15; the new projection kernel
is elementary2, hence the new x,y have order dividing30.  F-image
abelianization has order900 and is generated by these two elements,
so its distinguished map is exactly ordinary abelianization mod30.
Combining that map with the signed modular SL2(F3) map is injective
modulo C, since the latter is injective on im(Fprime)/C=Q8.

This program checks those source-generator orders and then enumerates
the resulting exact7200-element model.  It retains every literal
Fermat Schreier-generator image and both actual Sylow projections.
"""
from pathlib import Path
from itertools import product
from math import lcm
import json,time
import numpy as np

here=Path(__file__).resolve().parent

def mm(a,b,m):
    A,B,C,D=a;e,f,g,h=b
    return ((A*e+B*g)%m,(A*f+B*h)%m,(C*e+D*g)%m,(C*f+D*h)%m)
def mi(a,m):
    A,B,C,D=a
    return (D%m,-B%m,-C%m,A%m)
def mp(a,n,m):
    out=(1,0,0,1)
    if n<0:a=mi(a,m);n=-n
    while n:
        if n&1:out=mm(out,a,m)
        a=mm(a,a,m);n//=2
    return out
def group_order(a,m):
    h=(1,0,0,1);n=0
    while n==0 or h!=(1,0,0,1):h=mm(h,a,m);n+=1
    return n
def matrix_closure(gs,m):
    values=[(1,0,0,1)];seen=set(values)
    for a in values:
        for b in gs:
            c=mm(a,b,m)
            if c not in seen:seen.add(c);values.append(c)
    return values

ONE=(1,0,0,1,0,0)
def mul(a,b):return mm(a[:4],b[:4],3)+((a[4]+b[4])%30,(a[5]+b[5])%30)
def inv(a):return mi(a[:4],3)+(-a[4]%30,-a[5]%30)
def power(a,n):
    out=ONE
    if n<0:a=inv(a);n=-n
    while n:
        if n&1:out=mul(out,a)
        a=mul(a,a);n//=2
    return out
def comm(a,b):return mul(mul(mul(a,b),inv(a)),inv(b))
def closure(gs):
    gs=list(dict.fromkeys(gs));values=[ONE];seen={ONE}
    for a in values:
        for b in gs:
            c=mul(a,b)
            if c not in seen:seen.add(c);values.append(c)
    return values
def fword(w,x,y):
    letters={1:x,2:y,-1:inv(x),-2:inv(y)};g=ONE
    for t in w:g=mul(g,letters[t])
    return g
def reduce_word(w):
    out=[]
    for t in w:
        if out and out[-1]==-t:out.pop()
        else:out.append(t)
    return out
def inverse_word(w):return [-t for t in w[::-1]]

def main():
    start=time.time()
    old=np.load(here/'de_ferrari_a5_source_compressed.npz')
    s,r=old['s'],old['r'];identity=np.arange(len(s))
    letters={0:s,1:r,-1:np.argsort(r)}
    def Bword(w):
        g=identity.copy()
        for t in w:g=letters[t][g]
        return g
    xword=[-1,0,-1,0];yword=[0,-1,0,-1]
    px,py=Bword(xword),Bword(yword)
    def ppower(g,n):
        h=identity.copy()
        for i in range(n):h=g[h]
        return h
    for g in (px,py):
        assert np.array_equal(ppower(g,15),identity)
        assert all(not np.array_equal(ppower(g,n),identity) for n in (1,3,5))
    source=json.loads((here/'de_ferrari_sl2_5_source.json').read_text())
    derived=json.loads((here/'de_ferrari_sl2_5_derived.json').read_text())
    Ccert=json.loads((here/'de_ferrari_sl2_5_Nprime.json').read_text())
    Ecert=json.loads((here/'de_ferrari_sl2_5_Fprime.json').read_text())
    assert source['actual_source_kernel_elementary_abelian']
    assert source['complete_kernel_dimension']==44
    Sorder=source['lifted_group_order']//Ccert['lifted_group_order']
    Forder=Sorder//6;Eorder=Ecert['lifted_group_order']//Ccert['lifted_group_order']
    assert Sorder==43200 and Forder==7200 and Eorder==8
    assert Forder//Eorder==30**2
    x12=(1,2,0,1);y12=(1,0,10,1)
    F12=matrix_closure([x12,y12],12);assert len(F12)==96
    assert all(tuple(-t%12 for t in g) not in set(F12) for g in F12)
    for g in (x12,y12):
        assert group_order(g,12)==6
        assert lcm(15,group_order(g,12))==30
        g3=mp(g,3,12)
        assert all(mm(g3,h,12)==mm(h,g3,12) for h in F12)
    # The actual elementary2 projection gives the upper bound30, and
    # the displayed old/modular projections give the matching lower bound.
    x=tuple(t%3 for t in x12)+(1,0)
    y=tuple(t%3 for t in y12)+(0,1)
    F=closure([x,y]);assert len(F)==Forder
    SL=matrix_closure([x[:4],y[:4]],3);assert len(SL)==24
    char={(1,0,0,1):0};queue=[(1,0,0,1)]
    for g in queue:
        for h in (x[:4],y[:4]):
            v=mm(g,h,3);a=(char[g]+1)%3
            if v in char:assert char[v]==a
            else:char[v]=a;queue.append(v)
    assert len(char)==24 and set(char.values())=={0,1,2}
    fibre={(g+(a,b)) for g in SL for a,b in product(range(30),repeat=2)
           if char[g]==(a+b)%3}
    assert set(F)==fibre
    assert len({g[4:] for g in F})==900
    E=[g for g in F if g[4:]==(0,0)];assert len(E)==8
    assert all(char[g[:4]]==0 for g in E)
    # Rebuild the nine-coset Schreier basis, independently of its saved words.
    words=[];edges=[]
    def section(q):return [1]*q[0]+[2]*q[1]
    for q in product(range(3),repeat=2):
        for t in (1,2):
            qq=list(q);qq[t-1]=(qq[t-1]+1)%3
            w=reduce_word(section(q)+[t]+inverse_word(section(tuple(qq))))
            if w:words.append(w);edges.append([list(q),t])
    saved=json.loads((here/'de_fermat_schreier.json').read_text())
    assert words==saved['basis_words'] and edges==saved['basis_positive_edges']
    assert len(words)==10
    Hgens=[fword(w,x,y) for w in words]
    H=closure(Hgens);assert len(H)==800
    assert set(H)=={g for g in F if g[4]%3==g[5]%3==0}
    assert Sorder//len(H)==54
    central=closure([power(x,3),power(y,3)])
    assert len(central)==100 and set(central)&set(E)=={ONE}
    assert all(comm(a,b)==ONE for a in (power(x,3),power(y,3)) for b in (x,y))
    assert {mul(a,b) for a in E for b in central}==set(H)
    Q8={g[:4] for g in E}
    assert sorted(group_order(g,3) for g in Q8)==[1,2,4,4,4,4,4,4]
    Hg2=[power(g,5) for g in Hgens];Hg5=[power(g,16) for g in Hgens]
    H2=closure(Hg2);H5=closure(Hg5)
    assert len(H2)==32 and len(H5)==25
    assert all(comm(a,b)==ONE for a in Hg2 for b in Hg5)
    assert {mul(a,b) for a in H2 for b in H5}==set(H)
    assert all(power(g,20)==ONE and mul(power(g,5),power(g,16))==g for g in H)
    commutators=[comm(a,b) for a in Hgens for b in Hgens]
    Hprime=closure(commutators);assert len(Hprime)==2
    assert all(comm(a,b)==ONE for a in Hprime for b in Hgens)
    assert any(power(g,10)!=ONE and power(g,4)!=ONE for g in H)
    records=[]
    for i,(w,g,g2,g5) in enumerate(zip(words,Hgens,Hg2,Hg5)):
        a,b=g[4]//3,g[5]//3
        assert g[:4] in Q8 and g[4]%3==g[5]%3==0
        records.append({'index':i,'literal_F_word':w,'signed_SL2_F3':list(g[:4]),
            'F_abelianization_mod30':list(g[4:]),'central_C10_coordinates':[a,b],
            'two_primary_coordinates':[list(g[:4]),a%2,b%2],
            'five_primary_coordinates':[a%5,b%5],
            'literal_two_primary_word':w*5,'literal_five_primary_word':w*16,
            'two_primary_F_model_image':list(g2),'five_primary_F_model_image':list(g5)})
    out={'actual_old_source_x_y_orders':[15,15],
         'actual_signed_modular_x_y_orders':[6,6],
         'actual_new_source_x_y_orders':[30,30],
         'new_order_upper_bound_from_proved_elementary_projection_kernel':True,
         'maximal_solvable_source_order':Sorder,'actual_F_image_order':Forder,
         'actual_F_derived_image_order':Eorder,'actual_F_abelianization_order':900,
         'actual_F_abelianization_map':'ordinary exponent sums modulo30',
         'exact_F_model':'SL2(F3) fibre product over C3 with (Z/30)^2; chi3(g)=a+b mod3',
         'all_F_model_elements_enumerated':len(F),
         'H_image_order':len(H),'actual_source_mod_H_order':54,
         'H_exact_direct_product':'Q8 times C10^2',
         'H_two_primary_order':len(H2),'H_five_primary_order':len(H5),
         'H_Sylow_projection_powers':[5,16],
         'H_derived_order':len(Hprime),'H_lower_central_third_is_trivial':True,
         'H_exponent':20,'all_H_elements_power20_and_Sylow_product_verified':True,
         'actual_B_map_factors_through_P20':True,
         'P20_factor_map':'the same literal images of s,r in G_L/C',
         'H_five_primary_map':'(exponent_x/3, exponent_y/3) modulo5; equals twice the F exponent sums modulo5',
         'H_generator_images':records,
         'SL2_F3_abelianization_C3':[[list(g),char[g]] for g in sorted(char)],
         'seconds':round(time.time()-start,3)}
    (here/'de_sl2_boundary_quotient.json').write_text(json.dumps(out,indent=2)+'\n')
    np.savez_compressed(here/'de_sl2_boundary_quotient.npz',
        F_model_elements=np.array(F),H_model_elements=np.array(H),
        H_two_primary_elements=np.array(H2),H_five_primary_elements=np.array(H5),
        H_generator_images=np.array(Hgens),x_A5_source=px,y_A5_source=py)
    print(json.dumps({k:v for k,v in out.items() if k not in
        ('H_generator_images','SL2_F3_abelianization_C3')},indent=2))
    print('PASS: actual signed source maps, complete H image, Sylow factors and P20 factorization.')

if __name__=='__main__':main()
