#!/usr/bin/env python3
"""Build an exact deterministic encoding of the stopped boundary proof log.

Acceptance requires pbc_verify_boundary_replay.py to compare the ENTIRE
regenerated stream with the immutable original checkpoint. Source/leaf
records are retained verbatim. Operation records are regenerated by the
already checked exact reduction algorithm, not replaced by a proof summary.
"""
from pathlib import Path
import hashlib,json,zipfile
ROOT=Path(__file__).resolve().parents[1];CODE=ROOT/'code';OUT=ROOT.parent/'checkpoint10_replay';OUT.mkdir(exist_ok=True)
SNAP=ROOT.parent/'LM8_PUSH_checkpoint_09.zip';ENTRY='code/pbc_iterated_modular_boundary_trace.jsonl'
rawpath=OUT/'pbc_boundary_original_source_lines.jsonl';rows=OUT/'pbc_boundary_identity_rows.dat'
h=hashlib.sha256();records=0;identities=0;rawcount=0;size=0
with zipfile.ZipFile(SNAP) as z,z.open(ENTRY) as f,rawpath.open('wb') as out,rows.open('w') as data:
 for line in f:
  assert line.endswith(b'\n'),'incomplete original record requires separate preservation'
  h.update(line);size+=len(line);records+=1
  if line.startswith((b'["sub",',b'["mul",',b'["neg",')):continue
  r=json.loads(line);assert r[0] in ('source','leaf'),r[0]
  out.write(line);rawcount+=1
  if r[0]=='leaf' and r[2]=='identity':
   identities+=1;data.write(str(len(r[3]))+' '+' '.join(map(str,r[3]))+' '+str(len(r[4]))+' '+' '.join(map(str,r[4]))+'\n')
manifest={'original_snapshot':str(SNAP),'original_entry':ENTRY,'original_sha256':h.hexdigest(),'original_bytes':size,
 'original_records':records,'identity_rows':identities,'retained_raw_records':rawcount,
 'source_lines':rawpath.name,'source_lines_sha256':hashlib.sha256(rawpath.read_bytes()).hexdigest(),
 'identity_data':rows.name,'identity_data_sha256':hashlib.sha256(rows.read_bytes()).hexdigest(),
 'source_dat':'code/pbc_native_modular_iterated.dat','verified':False}
(OUT/'pbc_boundary_replay_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
old=(CODE/'pbc_native_modular_v2.cpp').read_text();a=old.index('struct Trace {');b=old.index('struct Witness {',a)
trace=r'''struct ReplayDone : std::exception {};
uint64_t ReplayLimit=0,ReplayRecords=0;
std::ifstream ReplayRaw;
struct Trace {
 uint64_t serial=0;
 explicit Trace(const char* name){ReplayRaw.open(name);if(!ReplayRaw)throw std::runtime_error("raw source lines missing");}
 void flush(){std::cout.flush();}
 void line(const std::string&s){
  std::string output=s;
  if(s.rfind("[\"source\",",0)==0||s.rfind("[\"leaf\",",0)==0){
   std::string original;if(!std::getline(ReplayRaw,original))throw std::runtime_error("raw source line missing");original+='\n';
   std::string compact;for(char c:original)if(c!=' ')compact+=c;
   if(compact!=s)throw std::runtime_error("retained source line does not match exact replay");output=original;
  }
  std::cout.write(output.data(),output.size());if(!std::cout)throw std::runtime_error("replay output error");
  if(++ReplayRecords==ReplayLimit){std::cout.flush();throw ReplayDone();}
 }
 uint64_t leaf(const std::string&kind,const std::vector<int>&meta,const Sparse&v){std::ostringstream o;o<<"[\"leaf\","<<++serial<<",\""<<kind<<"\",";writeInts(o,meta);o<<',';writeSparse(o,v);o<<"]\n";line(o.str());return serial;}
 uint64_t sub(uint64_t a,const Z&q,uint64_t b){std::ostringstream o;o<<"[\"sub\","<<++serial<<','<<a<<','<<q<<','<<b<<"]\n";line(o.str());return serial;}
 uint64_t neg(uint64_t a){std::ostringstream o;o<<"[\"neg\","<<++serial<<','<<a<<"]\n";line(o.str());return serial;}
 uint64_t mul(const Z&u,uint64_t a){std::ostringstream o;o<<"[\"mul\","<<++serial<<','<<u<<','<<a<<"]\n";line(o.str());return serial;}
};
'''
src=old[:a]+trace+old[b:];pos=src.index(' void run(){')
src=src[:pos]+r''' void replay(std::istream&rows){
  for(int i=2;i<extra_count;i++){Weights w(extra_count,0);w[i]=1;insert(extras[i],w,trace.leaf("extra",{i+1},extras[i]));}
  if(check())return;
  for(;;){int len;if(!(rows>>len))break;assert(len>0);std::vector<int>meta(len);for(auto&v:meta)rows>>v;Sparse v=readSparse(rows);relation(v,meta);}
  throw std::runtime_error("source leaves ended before the exact terminal record");
 }
'''+src[pos:]
pos=src.index('int main(')
src=src[:pos]+r'''int main(int argc,char**argv){try{
 std::ios::sync_with_stdio(false);std::cin.tie(nullptr);assert(argc==5);
 ReplayLimit=std::stoull(argv[4]);std::ifstream in(argv[1]),rows(argv[3]);assert(in&&rows);
 Witness w(in,argv[2],"unused_replay_certificate.json");w.replay(rows);
 }catch(const ReplayDone&){std::cerr<<"EXACT_REPLAY_TERMINAL_RECORD "<<ReplayRecords<<'\n';return 0;}
 catch(const std::exception&e){std::cerr<<e.what()<<'\n';return 1;}return 1;}
'''
(CODE/'pbc_trace_replay_boundary.cpp').write_text(src)
print(json.dumps(manifest,indent=2))
