#!/usr/bin/env python3
"""Exact order-75 countermodel to a naive semilinear normal-chain criterion.

No external algebra package is used.  The module is F_2[G], and Frobenius is
left multiplication by t=(1,0,0).  Its deck automorphism is conjugation by t.
"""

from collections import deque
import json
from pathlib import Path


# F_25 = F_5[w]/(w^2+w+1), with w of order three.
def omega(x):
    a, b = x
    return (-b % 5, (a - b) % 5)


elements = [(a, b, k) for a in range(5) for b in range(5) for k in range(3)]
index = {g: i for i, g in enumerate(elements)}
identity = index[(0, 0, 0)]
t = index[(1, 0, 0)]


def multiply_tuple(g, h):
    a, b, k = g
    c, d, j = h
    for _ in range(k):
        c, d = omega((c, d))
    return ((a + c) % 5, (b + d) % 5, (k + j) % 3)


mul = [[index[multiply_tuple(g, h)] for h in elements] for g in elements]
inv = [next(j for j in range(75) if mul[i][j] == identity) for i in range(75)]
assert all(mul[mul[a][b]][c] == mul[a][mul[b][c]]
           for a in range(75) for b in range(75) for c in range(75))


def generated(gens):
    gens = set(gens)
    gens |= {inv[g] for g in gens}
    found = {identity}
    queue = deque([identity])
    while queue:
        h = queue.popleft()
        for g in gens:
            x = mul[g][h]
            if x not in found:
                found.add(x)
                queue.append(x)
    return frozenset(found)


def normal_closure(gens):
    return generated(mul[mul[g][h]][inv[g]] for h in gens for g in range(75))


# Enumerate the complete normal-subgroup lattice by adjoining one conjugacy
# class at a time.  Every normal subgroup is generated by such classes.
normal = {frozenset([identity])}
queue = deque(normal)
while queue:
    h = queue.popleft()
    for g in range(75):
        if g not in h:
            k = normal_closure(set(h) | {g})
            if k not in normal:
                normal.add(k)
                queue.append(k)
normal = sorted(normal, key=lambda h: (len(h), sorted(h)))
assert [len(h) for h in normal] == [1, 25, 75]
n = frozenset(i for i, g in enumerate(elements) if g[2] == 0)
assert normal[1] == n

alpha = [mul[mul[t][g]][inv[t]] for g in range(75)]
frob = mul[t]
assert all(frob[mul[g][h]] == mul[alpha[g]][frob[h]]
           for g in range(75) for h in range(75))
assert len(generated([t])) == 5


def invariant_dimension(h):
    # A regular permutation module has one invariant vector per orbit.
    return 75 // len(generated(set(h) | {t}))


dimensions = [invariant_dimension(h) for h in normal]
assert dimensions == [15, 3, 1]
strict = all(dimensions[i] > dimensions[j]
             for i, h in enumerate(normal)
             for j, k in enumerate(normal) if h < k)
assert strict

all_power_dimensions = []
tr = identity
for r in range(1, 6):
    tr = mul[t][tr]
    dims = [75 // len(generated(set(h) | {tr})) for h in normal]
    assert dims == ([75, 3, 1] if r == 5 else [15, 3, 1])
    assert all(dims[i] > dims[j]
               for i, h in enumerate(normal)
               for j, k in enumerate(normal) if h < k)
    all_power_dimensions.append({"r_mod_5": r % 5, "dimensions": dims})
vertical_line = frozenset(index[(0, b, 0)] for b in range(5))
assert vertical_line < n
assert t not in vertical_line
assert invariant_dimension(vertical_line) == invariant_dimension(n) == 3

# The indicator of <t> is F-fixed and its G-stabilizer is exactly <t>.
# Every F-fixed vector is t-fixed by definition; this gives an exact minimum.
t_group = generated([t])
stabilizer = [g for g in range(75)
              if frozenset(mul[g][h] for h in t_group) == t_group]
assert frozenset(stabilizer) == t_group

result = {
    "status": "all assertions passed",
    "characteristic": 2,
    "group_order": 75,
    "group": "(F_25,+) semidirect C_3, multiplier w with w^2+w+1=0 over F_5",
    "module": "F_2[G] with left regular action",
    "frobenius": "left multiplication by t=(1,0,0)",
    "deck_frobenius": "conjugation by t",
    "frobenius_order": 5,
    "normal_subgroup_orders": [len(h) for h in normal],
    "rational_invariant_dimensions": dimensions,
    "all_normal_chain_dimensions_strict": strict,
    "normal_chain_dimensions_for_all_frobenius_powers": all_power_dimensions,
    "number_of_frobenius_fixed_vectors": 2 ** dimensions[0],
    "minimum_stabilizer_order_of_a_frobenius_fixed_vector": 5,
    "missing_intermediate_test": {"H_order": 1, "K_order": 5,
                                  "rational_invariant_dimensions": [15, 15]},
    "missing_test_with_G_normal_upper_subgroup": {
        "H": "the F_5-line spanned by w inside N", "K": "N",
        "rational_invariant_dimensions": [3, 3]},
    "scope": "abstract finite module only; not a Jacobian realization or a curve counterexample",
}
out = Path(__file__).with_suffix(".json")
out.write_text(json.dumps(result, indent=2) + "\n")
print(json.dumps(result, indent=2))
