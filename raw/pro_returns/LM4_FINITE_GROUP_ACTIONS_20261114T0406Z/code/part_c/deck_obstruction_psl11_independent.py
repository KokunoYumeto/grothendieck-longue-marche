#!/usr/bin/env python3
"""Independent D29 deck obstruction, using the 12-point permutation action.

No matrix canonicalization or group tables from the root certificate are used.
The group is generated by z -> z+1 and z -> -1/z on P^1(F_11).
"""
from collections import Counter, deque
from pathlib import Path
import json


def compose(a, b):
    return tuple(a[b[i]] for i in range(12))


def inverse(a):
    return tuple(a.index(i) for i in range(12))


def power(a, n):
    out = tuple(range(12))
    while n:
        if n & 1:
            out = compose(out, a)
        a = compose(a, a)
        n //= 2
    return out


def order(a):
    out, n = a, 1
    while out != tuple(range(12)):
        out = compose(out, a)
        n += 1
    return n


def main():
    one = tuple(range(12))
    u = tuple((i+1) % 11 for i in range(11)) + (11,)
    v = (11,) + tuple((-pow(i, -1, 11)) % 11 for i in range(1, 11)) + (0,)
    group, todo = {one}, deque([one])
    while todo:
        current = todo.popleft()
        for generator in (u, v):
            nxt = compose(current, generator)
            if nxt not in group:
                group.add(nxt)
                todo.append(nxt)
    assert len(group) == 660
    group = sorted(group)
    inverses = {g: inverse(g) for g in group}
    classes, class_of = [], {}
    for g in group:
        if g in class_of:
            continue
        conjugates = {compose(compose(h, g), inverses[h]) for h in group}
        for elt in conjugates:
            assert elt not in class_of
            class_of[elt] = len(classes)
        classes.append(sorted(conjugates))
    assert len(classes) == 8
    element_orders = {order(c[0]) for c in classes}
    assert element_orders == {1, 2, 3, 5, 6, 11}
    # Exact CRT coordinates modulo the exponent 330.
    epsilon, kappa, lam = 221, 165, 109
    assert epsilon % 110 == 1 and epsilon % 3 == 2
    assert kappa % 2 == 1 and kappa % 165 == 0
    assert (epsilon + lam) % 330 == 0
    squares = {}
    for t in group:
        squares.setdefault(compose(t, t), []).append(t)
    f_values = []
    records = []
    for i, c in enumerate(classes):
        l = c[0]
        target, square = power(l, epsilon), power(l, kappa)
        valid = [t for t in squares.get(square, [])
                 if compose(compose(t, l), inverses[t]) == target]
        f_values.append(len(valid))
        records.append({'class': i, 'order': order(l), 'size': len(c),
                        'f': len(valid), 'representative': l,
                        'lambda_power_class': class_of[power(l, lam)]})
    c_index = class_of[u]
    cinv_index = class_of[inverses[u]]
    assert c_index != cinv_index
    assert len(classes[c_index]) == len(classes[cinv_index]) == 60
    pairs = [(c_index, c_index), (cinv_index, c_index),
             (c_index, cinv_index), (cinv_index, cinv_index)]
    results = []
    for a_index, p_index in pairs:
        histogram = Counter(class_of[compose(a, p)]
                            for a in classes[a_index]
                            for p in classes[p_index])
        total = sum(count * f_values[i] for i, count in histogram.items())
        assert sum(histogram.values()) == 3600
        results.append({'a_class': a_index, 'p_class': p_index,
                        'product_class_histogram': dict(sorted(histogram.items())),
                        'homomorphism_count': total})
    assert [r['homomorphism_count'] for r in results] == [10200, 4920, 4920, 10200]
    # Direct independent enumeration of all triples for those pairs via
    # squares indexed by the product L, rather than the class function.
    direct = []
    for a_index, p_index in pairs[:2]:
        count = 0
        for a in classes[a_index]:
            for p in classes[p_index]:
                l = compose(a, p)
                target, square = power(l, epsilon), power(l, kappa)
                count += sum(compose(compose(t, l), inverses[t]) == target
                             for t in squares.get(square, []))
        direct.append(count)
    assert direct == [10200, 4920]
    result = {'group': 'PSL2(F11) on P1(F11)', 'group_order': len(group),
              'generators': {'translation': u, 'negative_inversion': v},
              'exponent': 330, 'CRT': {'epsilon': epsilon, 'kappa': kappa, 'lambda': lam},
              'classes': records, 'order11_class': c_index,
              'inverse_order11_class': cinv_index,
              'pair_counts': results, 'direct_triple_counts': direct,
              'all_checks_passed': True}
    destination = Path(__file__).with_name('deck_obstruction_psl11_independent_output.json')
    destination.write_text(json.dumps(result, indent=2) + '\n')
    print('Generated PSL2(F11) faithfully on 12 points:', len(group), 'elements.')
    print('Class counts and values:', [(r['order'], r['size'], r['f']) for r in records])
    print('Order11 pair counts:', [r['homomorphism_count'] for r in results])
    print('Direct triple enumeration:', direct)
    print('Independent obstruction:', 10200, '!=', 4920)
    print('Wrote', destination)


if __name__ == '__main__':
    main()
