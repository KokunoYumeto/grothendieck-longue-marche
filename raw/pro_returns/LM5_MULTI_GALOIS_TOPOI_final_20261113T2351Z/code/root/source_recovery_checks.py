"""Reproduce the recovered-source integrity and finite C8 matrix checks."""
from pathlib import Path
import csv
import hashlib
import json

PACKAGE = Path(__file__).resolve().parents[2]
if not (PACKAGE / "source_audit").is_dir():
    PACKAGE = Path.cwd() / "deliverable"
AUDIT = PACKAGE / "source_audit"
record = json.loads((AUDIT / "source_recovery_audit.json").read_text())
integrity = []
for item in record["files"]:
    data = (AUDIT / item["path"]).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    assert digest == item["sha256"]
    assert len(data) == item["bytes"]
    integrity.append({"path": item["path"], "sha256": digest, "verified": True})

rows = list(csv.DictReader((AUDIT / "CYCLOTOMIC_return/CYCLOTOMIC_KERNEL_results.csv").open()))
identifier_key = next(key for key in rows[0] if key.lower() == "id")
selected = [row for row in rows if row[identifier_key] in {"B5", "C8"}]
assert {row[identifier_key] for row in selected} == {"B5", "C8"}

matrices = []
for modulus in [2, 3, 5, 25]:
    kernel = [(a, b) for a in range(modulus) for b in range(modulus)
              if (a + b) % modulus == 0]
    expected = [(a, (-a) % modulus) for a in range(modulus)]
    image = sorted({(a + b) % modulus for a in range(modulus)
                    for b in range(modulus)})
    diagonal_image = sorted({2 * a % modulus for a in range(modulus)})
    assert kernel == expected
    assert image == list(range(modulus))
    matrices.append({"modulus": modulus, "matrix": [[1, 1]],
                     "kernel": kernel, "image": image,
                     "diagonal_image": diagonal_image})

print(json.dumps({"source_integrity": integrity, "literal_register_rows": selected,
                  "blowup_inertia_matrix_checks": matrices,
                  "interpretation": "Kernel generated by (1,-1); diagonal is multiplication by 2. Its reduction modulo 2 is zero, while odd reductions witness nonvanishing."},
                 indent=2, ensure_ascii=False))
