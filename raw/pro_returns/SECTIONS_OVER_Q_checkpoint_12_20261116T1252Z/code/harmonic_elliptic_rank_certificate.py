#!/usr/bin/env python3
"""Exact maps, two-isogeny descent data and Tunnell coefficient for A143."""
from fractions import Fraction as F
from itertools import product
from math import isqrt
from pathlib import Path
import json
import sympy as S

k,x,y,u,v,w,q=S.symbols("k x y u v w q",nonzero=True)

def zero_on(expr,var,rhs):
    numerator=S.fraction(S.cancel(expr))[0]
    return S.rem(numerator,var**2-rhs,var)==0

def phi(X,Y):
    return (X-4*k*k/X)/4,Y*(1+4*k*k/X**2)/8

def psi(U,V):
    return U+k*k/U,V*(1-k*k/U**2)

def add_mod(P,Q,p,a):
    if P is None:
        return Q
    if Q is None:
        return P
    x,y=P;xx,yy=Q
    if x==xx and (y+yy)%p==0:
        return None
    slope=((3*x*x+a)*pow(2*y,-1,p) if P==Q
           else (yy-y)*pow(xx-x,-1,p))%p
    rx=(slope*slope-x-xx)%p
    return rx,(slope*(x-rx)-y)%p

def mul_mod(m,P,p,a):
    result=None
    while m:
        if m&1:
            result=add_mod(result,P,p,a)
        P=add_mod(P,P,p,a)
        m//=2
    return result

def points_mod(p,a):
    roots={}
    for y in range(p):
        roots.setdefault(y*y%p,[]).append(y)
    return [None]+[(x,y) for x in range(p)
                   for y in roots.get((x*x*x+a*x)%p,[])]

def main():
    px,py=phi(x,y)
    sx,sy=psi(u,v)
    assert zero_on(py*py-px**3-k*k*px,y,x**3-4*k*k*x)
    assert zero_on(sy*sy-sx**3+4*k*k*sx,v,u**3+k*k*u)
    cx,cy=psi(px,py)
    slope=(3*x*x-4*k*k)/(2*y)
    dx=slope*slope-2*x
    dy=slope*(x-dx)-y
    assert zero_on(cx-dx,y,x**3-4*k*k*x)
    assert zero_on(cy-dy,y,x**3-4*k*k*x)
    fx,fy=phi(sx,sy)
    slopef=(3*u*u+k*k)/(2*v)
    dx=slopef*slopef-2*u
    dy=slopef*(u-dx)-v
    assert zero_on(fx-dx,v,u**3+k*k*u)
    assert zero_on(fy-dy,v,u**3+k*k*u)
    print("Both literal isogenies and both compositions=[2]: PASS.")

    # Exact D→E→F factorization, and the rational order-four action.
    rhs=(u**3-u)/(8*k*q*q)
    XE,YE=2*k*u,8*k*k*q*w*w
    XF,YF=k*(u-1/u)/2,k*k*q*w*w*(u*u+1)/(u*u)
    assert S.simplify((YE*YE-XE**3+4*k*k*XE).subs(w**4,rhs))==0
    assert S.simplify((YF*YF-XF**3-k*k*XF).subs(w**4,rhs))==0
    mapped=phi(XE,YE)
    assert all(S.simplify(a-b)==0 for a,b in zip(mapped,(XF,YF)))
    assert S.simplify(XF.subs(u,-1/u)-XF)==0
    assert S.simplify(YF.subs({u:-1/u,w:w/u},simultaneous=True)-YF)==0
    assert S.simplify(((u*u-(2*XF/k)*u-1)))==0
    assert S.simplify(YF*u*u/(k*k*q*(u*u+1))-w*w)==0
    print("D→E→F, invariant functions and inverse field equations: PASS.")

    R,c,s=F(529,382),F(-338,191),155564491
    qq=F(325596479663,72962)
    aa=F(529,382)*F(147,382)*F((13*s)**2,191)
    assert aa==573*qq*qq
    rho=F(34,7*s)
    P=(F(2028),F(75348))
    Q=(F(5202),F(365976))
    assert 1146*(2*R-1)==P[0]
    assert 8*573**2*qq/s==P[1]
    assert -1146*(2*c-1)==Q[0]
    assert 8*573**2*qq*rho==Q[1]
    images=[]
    for xx,yy in (P,Q):
        assert yy*yy==xx**3-1146**2*xx
        fx=(xx-F(1146**2,1)/xx)/4
        fy=yy*(1+F(1146**2,1)/(xx*xx))/8
        assert fy*fy==fx**3+573**2*fx
        images.append((str(fx),str(fy)))
    doubled_x=((P[0]**2+1146**2)/(2*P[1]))**2
    assert doubled_x==F(22718025625,17522596)
    print("Exact E-points:",P,Q)
    print("Their exact F-images:",images)
    print("Retained independent doubling check x(2P) =",doubled_x)

    # Bits encode the squareclasses (-1,2,3,191).
    generators=(1,14,4,2)  # T0,T1146,P,Q.
    span={0}
    for a in generators:
        span |= {b^a for b in list(span)}
    assert len(span)==16
    assert P[0]==3*26**2 and Q[0]==2*51**2
    print("E x-squareclass image: all16 possible classes, generated by T0,T1146,P,Q.")

    # The three nontrivial possible positive F classes fail a primitive
    # quartic equation at the displayed coefficient prime.
    obstruction_counts={}
    for d,p in ((3,3),(573,3),(191,191)):
        count=0
        assert 573**2%d==0
        lead=d//p
        other=(573**2//d)//p
        assert d%p==0 and (573**2//d)%p==0
        for U,V in product(range(p),repeat=2):
            if U==V==0:
                continue
            assert (lead*pow(U,4,p)+other*pow(V,4,p))%p!=0
            count+=1
        obstruction_counts[d]=dict(prime=p,primitive_pairs=count)
    assert pow((-9)%191,95,191)==190
    print("F quartic obstruction cases:",obstruction_counts)
    print("Thus F/phi(E)=1 and E/2E has16 classes; |E[2]|=4 gives rank2.")

    # Literal signed theta series from Tunnell Theorem1.
    target=573
    theta_terms=[]
    for m in range(-isqrt(target)-1,isqrt(target)+2):
        odd=4*m+1
        if odd*odd>target:
            continue
        for n in range(-isqrt(target//8)-1,isqrt(target//8)+2):
            for j in range(-isqrt(target//4)-1,isqrt(target//4)+2):
                if odd*odd+8*n*n+4*j*j==target:
                    theta_terms.append((m,n,j,(-1 if n%2 else 1)))
    positives=sum(t[-1]==1 for t in theta_terms)
    negatives=sum(t[-1]==-1 for t in theta_terms)
    coefficient=sum(t[-1] for t in theta_terms)
    assert (positives,negatives,coefficient)==(16,16,0)
    counts={}
    points={}
    for b in (8,32):
        ps=[]
        for xx in range(-isqrt(target//4),isqrt(target//4)+1):
            for zz in range(-isqrt(target//b),isqrt(target//b)+1):
                rem=target-4*xx*xx-b*zz*zz
                if rem<0:
                    continue
                yy=isqrt(rem)
                if yy*yy==rem:
                    ps.append((xx,yy,zz))
                    if yy:
                        ps.append((xx,-yy,zz))
        points[b]=ps
        counts[b]=len(ps)
    assert counts=={8:64,32:32}
    assert coefficient==counts[32]-counts[8]//2
    coeff=[0]*(target+1)
    coeff[1]=1
    for step in (8,16):
        for exp in range(step,target+1,step):
            for j in range(target,exp-1,-1):
                coeff[j]-=coeff[j-exp]
    from_product=coeff[target]+2*sum(coeff[target-4*j*j]
                                    for j in range(1,isqrt(target//4)+1))
    assert from_product==coefficient
    print("Literal signed theta terms:16 positive,16 negative; b(573)=0.")
    print("Independent ternary counts:",counts)
    print("Independent eta-product coefficient:",from_product)
    local_checks=[]
    for p in range(5,300):
        if p%8!=3 or any(p%d==0 for d in range(2,isqrt(p)+1)):
            continue
        if 1146%p==0:
            continue
        ep=points_mod(p,-1146**2)
        fp=points_mod(p,573**2)
        assert len(ep)==len(fp)==p+1
        odd=(p+1)//4
        projection=odd*pow(odd,-1,4)
        actual_E2={None,(0,0),(1146%p,0),((-1146)%p,0)}
        image=set()
        for Pp in ep:
            primary=mul_mod(projection,Pp,p,-1146**2)
            assert primary in actual_E2
            if primary is None or primary[0]==0:
                mapped=None
            else:
                xx,yy=primary
                mapped=((xx-1146**2*pow(xx,-1,p))*pow(4,-1,p)%p,
                        yy*(1+1146**2*pow(xx*xx,-1,p))*pow(8,-1,p)%p)
            image.add(mapped)
        assert image=={None,(0,0)}
        local_checks.append(dict(p=p,count=p+1,projection=projection))
    print("Finite good-prime 2-primary checks:",
          len(local_checks),"primes and",
          sum(t["count"] for t in local_checks),"actual E-points.")
    result=dict(points_E=[[str(z) for z in point] for point in (P,Q)],
                points_F=images,doubled_x=str(doubled_x),
                quartic_obstructions=obstruction_counts,
                E_squareclass_count=16,F_squareclass_count=1,rank=2,
                theta_terms=theta_terms,ternary_points=points,
                tunnell_coefficient=coefficient,
                product_coefficients=coeff,
                local_primary_checks=local_checks)
    Path(__file__).with_name("harmonic_elliptic_rank_data.json").write_text(
        json.dumps(result,indent=2)+"\n")
    print("ALL EXACT ELLIPTIC FACTOR CERTIFICATES PASSED.")

if __name__=="__main__":
    main()
