"""Exact finite certificate for the normalized-conjugator claim in task A.3.

Arithmetic takes place in F_7<X,Y> / (all words of length >= 4).
The subgroup generated by exp(X), exp(Y) is the free exponent-7,
class-three group on two generators. No input from prior runs is read.
"""
from collections import deque
from itertools import product

P = 7
WORDS = [()] + [w for n in range(1,4) for w in product((0,1), repeat=n)]
INDEX = {w:i for i,w in enumerate(WORDS)}
MUL = [(i,j,INDEX[a+b]) for i,a in enumerate(WORDS)
       for j,b in enumerate(WORDS) if len(a+b)<=3]

def add(a,b): return tuple((x+y)%P for x,y in zip(a,b))
def scale(k,a): return tuple(k*x%P for x in a)
def mul(a,b):
    out=[0]*len(WORDS)
    for i,j,k in MUL: out[k]=(out[k]+a[i]*b[j])%P
    return tuple(out)
def basis(w): return tuple(int(v==w) for v in WORDS)
ZERO=(0,)*len(WORDS)
ONE=basis(())
X,Y=basis((0,)),basis((1,))
def exp(a):
    a2=mul(a,a); a3=mul(a2,a)
    return add(add(ONE,a),add(scale(pow(2,-1,P),a2),scale(pow(6,-1,P),a3)))
def inverse(a):
    b=add(a,scale(-1,ONE)); b2=mul(b,b); b3=mul(b2,b)
    return add(add(ONE,scale(-1,b)),add(b2,scale(-1,b3)))
def power(a,n):
    if n<0:return power(inverse(a),-n)
    out=ONE
    while n:
        if n&1:out=mul(out,a)
        a=mul(a,a);n//=2
    return out
def conj(a,b):return mul(mul(a,b),inverse(a))
def bracket(a,b):return add(mul(a,b),scale(-1,mul(b,a)))
def log(a):
    b=add(a,scale(-1,ONE));b2=mul(b,b);b3=mul(b2,b)
    return add(add(b,scale(-pow(2,-1,P),b2)),scale(pow(3,-1,P),b3))
Z=bracket(X,Y); U=bracket(X,Z);V=bracket(Y,Z)
x,y=exp(X),exp(Y)
g=exp(Z) # coefficient t=(2^2-1)/24 = 1 mod 7
psi_y=conj(inverse(g),y)
w=mul(x,y);psi_w=mul(x,psi_y)
generators=(x,y,inverse(x),inverse(y))
group={ONE};queue=deque([ONE])
while queue:
    a=queue.popleft()
    for b in generators[:2]:
        c=mul(a,b)
        if c not in group:group.add(c);queue.append(c)
assert len(group)==P**5
assert all(power(a,P)==ONE for a in group)
orbit={w};queue=deque([w])
while queue:
    a=queue.popleft()
    for b in generators:
        c=conj(b,a)
        if c not in orbit:orbit.add(c);queue.append(c)
assert psi_w not in orbit
theta_x=power(x,2);theta_y=conj(inverse(g),power(y,2))
theta_w=mul(theta_x,theta_y)
orbit_w2={conj(a,power(w,2)) for a in group}
assert theta_w in orbit_w2
assert len(orbit)==49
print('p =',P,'; nilpotence class = 3')
print('Group order:',len(group))
print('All group elements satisfy a^7 = 1: True')
print('Coefficient (2^2 - 1)/24 mod 7:',3*pow(24,-1,7)%7)
print('Conjugacy orbit size of xy:',len(orbit))
print('x g^-1 y g conjugate to xy:',psi_w in orbit)
print('x^2 g^-1 y^2 g conjugate to (xy)^2:',theta_w in orbit_w2)
print('log(xy) word coefficients:',{''.join('XY'[i] for i in z):v for z,v in zip(WORDS,log(w)) if v})
print('log(x g^-1 y g) - log(xy):',{''.join('XY'[i] for i in z):v for z,v in zip(WORDS,add(log(psi_w),scale(-1,log(w)))) if v})
print('All assertions passed.')
