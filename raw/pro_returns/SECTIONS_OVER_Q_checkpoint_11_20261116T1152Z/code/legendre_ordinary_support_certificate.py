#!/usr/bin/env python3
"""Finite exact checks accompanying A.78; no numerical Galois inference."""

from math import comb


def vp(n, p):
    if n == 0:
        return float('inf')
    v = 0
    while n % p == 0:
        n //= p
        v += 1
    return v


def poly_mul(a, b, degree):
    c = [0] * (degree + 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            if i+j <= degree:
                c[i+j] += x*y
    return c


def poly_inv(a, degree):
    assert a[0] == 1
    b = [1] + [0]*degree
    for k in range(1, degree+1):
        b[k] = -sum(a[j]*b[k-j] for j in range(1, k+1))
    return b


def evaluate(a, x, modulus):
    result = 0
    for z in reversed(a):
        result = (result*x + z) % modulus
    return result


# Phi(q)=q J(q), formed independently from E4^3/Delta.
degree = 12
e4 = [1] + [240*sum(d**3 for d in range(1, n+1) if n % d == 0)
            for n in range(1, degree+1)]
delta_over_q = [1] + [0]*degree
for n in range(1, degree+1):
    factor = [0]*(degree+1)
    for k in range(min(24, degree//n)+1):
        factor[k*n] = (-1)**k * comb(24, k)
    delta_over_q = poly_mul(delta_over_q, factor, degree)
phi = poly_mul(poly_mul(poly_mul(e4, e4, degree), e4, degree),
               poly_inv(delta_over_q, degree), degree)
assert phi[:5] == [1, 744, 196884, 21493760, 864299970]

cases = 0
samples = []
for h in range(1, 9):
    for unit in (-3, -1, 1, 3, 5, 7):
        r = 2**h * unit
        q = r*r
        precision = h + 4 + 14
        modulus = 2**precision

        def f(z):
            return z * pow((1-z)**2, -1, modulus) % modulus

        constant = sum(n*pow(q, n, modulus)*pow(1-pow(q,n,modulus), -1, modulus)
                       for n in range(1, precision+1)) % modulus

        # All x coordinates are multiplied by4, so every residue is integral.
        x_minus_one = (-1 + 8*sum(f(-pow(q,n,modulus)) for n in range(1, precision+1))
                       - 8*constant) % modulus
        x_plus_r = (8*sum(f(pow(r,2*j+1,modulus)) for j in range(precision+1))
                    - 8*constant) % modulus
        x_minus_r = (8*sum(f(-pow(r,2*j+1,modulus)) for j in range(precision+1))
                     - 8*constant) % modulus
        difference_formula = 16*sum(
            pow(r,2*j+1,modulus)*(1+pow(r,4*j+2,modulus))
            *pow((1-pow(r,4*j+2,modulus))**2, -1, modulus)
            for j in range(precision+1)) % modulus
        assert (x_plus_r-x_minus_r-difference_formula) % modulus == 0
        assert vp(x_minus_one, 2) == 0
        assert vp(x_plus_r, 2) == vp(x_minus_r, 2) == h+3
        assert vp((x_plus_r-x_minus_r) % modulus, 2) == h+4
        assert vp((x_plus_r-x_minus_one) % modulus, 2) == 0
        assert vp((x_minus_r-x_minus_one) % modulus, 2) == 0

        lam = (x_plus_r-x_minus_r)*pow(x_minus_one-x_minus_r, -1, modulus) % modulus
        assert vp(lam, 2) == h+4
        z = lam // 2**(h+4)
        target = 2**14
        q_j_legendre = unit*unit * (lam*lam-lam+1)**3 * pow(z*z*(1-lam)**2, -1, target) % target
        assert q_j_legendre == evaluate(phi, q, target)
        if unit == 1 and h in (1, 2, 4, 8):
            samples.append((h, (x_minus_one, x_plus_r, x_minus_r), lam, precision))
        cases += 1

pairs = [(k,0) for k in range(1,5)] + [(0,k) for k in range(1,5)] + [(-k,-k) for k in range(1,5)]
assert len({(a % 8,b % 8) for a,b in pairs}) == 12
modulus = 48
kernel = {(a,b) for a in range(modulus) for b in range(modulus)
          if a % 8 == b % 8 == 0 and (a+b) % 3 == 0}
generated = {((24*i+8*k) % modulus, (24*j-8*k) % modulus)
             for i in range(2) for j in range(2) for k in range(6)}
assert kernel == generated
label_checks = 0
for delta in range(modulus):
    for a,b in ((delta,0),(0,delta),(delta,delta)):
        assert ((a,b) in kernel) == (delta % 24 == 0)
        label_checks += 1

print('A.78 finite arithmetic certificate: all checks passed.')
print(f'Exact dyadic Tate cases: {cases}, depths h=1..8 and units −3,−1,1,3,5,7.')
print('In each case, v2 X(−1)=−2, v2 X(±r)=h+1,')
print('v2(X(r)−X(−r))=h+2, and v2(X(±r)−X(−1))=−2.')
print('The induced Legendre parameter has valuation h+4, and q*j(lambda)=q*J(q) modulo2^14.')
print('Sample (h, the three scaled coordinates4X modulo2^M, lambda modulo2^M, M):')
for row in samples:
    print(row)
print('All12 potentially-good dyadic valuation pairs have distinct images modulo8.')
print(f'The kernel generated by (24,0),(0,24),(8,−8) modulo48 has order{len(kernel)}.')
print(f'Checks that each cusp label vector lies in that kernel exactly at24-divisible exponents: {label_checks}.')
print('The all-coefficient Tate comparison, scalar centralizer, completed support, and infinite equations are proved in the text.')
