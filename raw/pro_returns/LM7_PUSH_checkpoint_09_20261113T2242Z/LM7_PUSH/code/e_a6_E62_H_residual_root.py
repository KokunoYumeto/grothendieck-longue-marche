#!/usr/bin/env python3
"""Full finite H nilpotent residual and its intersection with E62 N-prime.

Every lower-central term is generated by literal H commutators, closed
under every H generator, and given a complete Schreier presentation.
The final intersection order uses the actual generated product subgroup.
"""
from pathlib import Path
from hashlib import sha256
import json
import subprocess
import time
import numpy as np
from a_cm_gl23_pc import ClassTwoCoordinates, Sifter, mul, inv, comm, conj
from de_a6_schreier_certificate import read_certificate, verify_words
from de_ferrari_a6_source_data import load_data
from e_a6_E62_deep_prepare_root import DAG

HERE = Path(__file__).resolve().parent
STEM = 'e_a6_E62_H_residual_root'


def main():
    started = time.monotonic()
    files = ['a_cm_gl23_joint.npz', 'a_cm_gl23_joint_pc.npz',
             'e_a6_E62_deep_prepare_root.json', 'e_a6_E62_deep_collect_root.json',
             'e_a6_E62_deep_collect_root.npz', 'de_a6_schreier.cpp',
             'de_a6_schreier_certificate.py', 'a_cm_gl23_pc.py']
    hashes = {p: sha256((HERE / p).read_bytes()).hexdigest() for p in files}
    folder = HERE / 'e_a6_E62_H_residual_root_certificates'
    folder.mkdir(exist_ok=False)
    d = load_data()
    P = ClassTwoCoordinates('joint')
    bp = np.load(HERE / 'a_cm_gl23_joint.npz')['joint_B_generators'].astype(np.uint16)
    letters = {0: bp[0], 1: bp[1], -1: inv(bp[1])}
    dag = DAG()
    hwords = json.loads((HERE / files[2]).read_text())['literal_H_basis_F_words']
    H = []
    Hnodes = []
    for w in hwords:
        bw = d['to_B'](w)
        p = P.one.copy()
        for a in bw:
            p = mul(p, letters[a])
        H.append(p); Hnodes.append(dag.word(bw))
    H = np.array(H)
    records = []

    def certify(label, values, source_nodes):
        values = np.array(values, dtype=np.uint16)
        assert values.ndim == 2 and values.shape[1] == P.n
        stem = folder / label
        with stem.with_suffix('.input').open('w') as f:
            f.write(f'{P.n} {len(values)}\n')
            for g in values:
                f.write(' '.join(map(str, g)) + '\n')
        with stem.with_suffix('.out').open('w') as out, stem.with_suffix('.err').open('w') as err:
            subprocess.run([str(HERE / 'de_a6_schreier_fast'), '--greedy',
                            str(stem.with_suffix('.input')), str(stem.with_suffix('.bin'))],
                           stdout=out, stderr=err, check=True)
        cert = read_certificate(stem.with_suffix('.bin'))
        verify_words(cert)
        assert np.array_equal(cert['original'], values)
        with Path(str(stem) + '_replay.out').open('w') as out, Path(str(stem) + '_replay.err').open('w') as err:
            subprocess.run([str(HERE / 'de_a6_schreier_fast'), '--replay', str(stem.with_suffix('.bin'))],
                           stdout=out, stderr=err, check=True)
        converted = []
        for op, a, b in cert['nodes']:
            op, a, b = map(int, (op, a, b))
            if op == 0:
                value = 0
            elif op == 1:
                value = int(source_nodes[a])
            else:
                value = dag.node(op, converted[a], converted[b] if op != 3 else 0)
            converted.append(value)
        word_nodes = [converted[int(w)] for w in cert['words']]
        sift = Sifter(cert)
        info = json.loads(next(line for line in reversed(stem.with_suffix('.out').read_text().splitlines())
                               if line.startswith('{')))
        assert int(info['order']) == sift.order
        info.update(label=label, original_B_word_nodes=list(map(int, source_nodes)),
                    strong_B_word_nodes=word_nodes, all_literal_words_replayed=True,
                    complete_certificate_replayed=True)
        records.append(info)
        return cert['strong'], word_nodes, sift

    current, current_nodes, current_sift = certify('H_full', H, Hnodes)
    levels = [{'depth': 1, 'order': str(current_sift.order), 'certificate': 'H_full'}]
    depth = 1
    while True:
        previous_order = current_sift.order
        values, nodes, keys = [], [], set()
        for h, hn in zip(H, Hnodes):
            for g, gn in zip(current, current_nodes):
                a = comm(h, g)
                key = a.tobytes()
                if key not in keys and not np.array_equal(a, P.one):
                    keys.add(key); values.append(a); nodes.append(dag.node(4, hn, gn))
        if not values:
            values, nodes = [P.one], [0]
        depth += 1
        revision = 0
        while True:
            label = f'H_gamma_{depth:02d}_normal_{revision:02d}'
            gs, gnodes, sift = certify(label, values, nodes)
            assert all(current_sift.contains(g) for g in gs)
            extra, enodes, keys = [], [], set()
            for h, hn in zip(H, Hnodes):
                for g, gn in zip(gs, gnodes):
                    a = conj(h, g)
                    if not sift.contains(a) and a.tobytes() not in keys:
                        keys.add(a.tobytes()); extra.append(a); enodes.append(dag.node(5, hn, gn))
            if not extra:
                break
            values = list(gs) + extra
            nodes = gnodes + enodes
            revision += 1
            assert revision < 100
        current, current_nodes, current_sift = gs, gnodes, sift
        levels.append({'depth': depth, 'order': str(sift.order), 'certificate': label,
                       'all_H_normal_conjugations_checked': len(H)*len(gs),
                       'all_previous_basis_H_commutators_included': True})
        print('H lower central', depth, 'order', sift.order, flush=True)
        if sift.order == previous_order:
            break
        assert depth < 100
    residual_order = current_sift.order
    # C is normal under H by the complete literal action checks in the
    # preparation. The generated group is therefore the actual product RC.
    c_generators = np.r_[P.q, P.z]
    for h in H:
        assert all(P.chains[-1].contains(conj(h, c)) for c in c_generators)
    # This certificate is an order comparison with abstract input letters;
    # its word nodes are not exported as common-source preimages.
    join_stem = folder / 'H_residual_times_C'
    values = np.r_[current, c_generators]
    with join_stem.with_suffix('.input').open('w') as f:
        f.write(f'{P.n} {len(values)}\n')
        for g in values:
            f.write(' '.join(map(str, g)) + '\n')
    with join_stem.with_suffix('.out').open('w') as out, join_stem.with_suffix('.err').open('w') as err:
        subprocess.run([str(HERE / 'de_a6_schreier_fast'), '--greedy',
                        str(join_stem.with_suffix('.input')), str(join_stem.with_suffix('.bin'))],
                       stdout=out, stderr=err, check=True)
    join = read_certificate(join_stem.with_suffix('.bin')); verify_words(join)
    assert np.array_equal(join['original'], values)
    joined = Sifter(join)
    with Path(str(join_stem) + '_replay.out').open('w') as out, Path(str(join_stem) + '_replay.err').open('w') as err:
        subprocess.run([str(HERE / 'de_a6_schreier_fast'), '--replay', str(join_stem.with_suffix('.bin'))],
                       stdout=out, stderr=err, check=True)
    c_order = P.chains[-1].order
    assert (residual_order * c_order) % joined.order == 0
    intersection_order = residual_order * c_order // joined.order
    lower = np.load(HERE / 'e_a6_E62_deep_collect_root.npz')
    lower_meta = json.loads((HERE / 'e_a6_E62_deep_collect_root.json').read_text())
    lower_values = lower['final_binary_values'] & ((1 << 24)-1)
    assert all(current_sift.contains(P.element(int(v))) for v in lower_values)
    lower_order = int(lower_meta['final_E62_projection_order'])
    assert intersection_order % lower_order == 0
    result = {
        'status': 'PASS_COMPLETE_ACTUAL_FINITE_H_NILPOTENT_RESIDUAL',
        'actual_H_generator_count': 10,
        'lower_central_levels': levels,
        'complete_chain_records': records,
        'H_nilpotent_residual_order': str(residual_order),
        'E62_N_prime_order': str(c_order),
        'actual_generated_product_order': str(joined.order),
        'exact_residual_intersection_with_E62_N_prime_order': str(intersection_order),
        'retained_stable_lower_image_order': str(lower_order),
        'stable_lower_image_verified_inside_entire_residual': True,
        'matching_upper_and_lower_images': intersection_order == lower_order,
        'exact_reduced_I_image_order': str(3**6*lower_order) if intersection_order == lower_order else None,
        'input_sha256': hashes,
        'seconds': round(time.monotonic() - started, 6)}
    np.savez_compressed(HERE / (STEM + '.npz'), literal_B_word_DAG=np.array(dag.nodes, dtype=np.int64),
                        original_H_permutations=H, original_H_word_nodes=np.array(Hnodes),
                        final_H_residual_permutations=current,
                        final_H_residual_word_nodes=np.array(current_nodes))
    (HERE / (STEM + '.json')).write_text(json.dumps(result, indent=2) + '\n')
    assert all(sha256((HERE / p).read_bytes()).hexdigest() == h for p, h in hashes.items())
    print(json.dumps({k: v for k, v in result.items() if k not in ['complete_chain_records', 'input_sha256']}, indent=2), flush=True)


if __name__ == '__main__':
    main()
