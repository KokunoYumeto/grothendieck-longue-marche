#!/usr/bin/env python3
"""Exact source, boundary and commutator images in the symplectic B5 tests."""
from pathlib import Path
from hashlib import sha256
import argparse
import json
import time
import numpy as np
from sympy import factorint, Matrix, ZZ
from sympy.matrices.normalforms import smith_normal_form
from sympy.combinatorics import Permutation, PermutationGroup
from de_ferrari_a6_source_data import load_data
from de_fermat_schreier import NWORDS

HERE = Path(__file__).resolve().parent


def main(prime):
    start = time.time()
    tag = 'e_symplectic_five_p' + str(prime)
    names = [tag + '_source_root_compressed.npz', tag + '_source_root.json',
             'de_ferrari_mod9_module.npz', 'de_ferrari_a6_source_data.py',
             'de_fermat_schreier.py']
    hashes = {n: sha256((HERE / n).read_bytes()).hexdigest() for n in names}
    data, d = np.load(HERE / names[0]), load_data()
    s, r = data['s'], data['r']
    ident = Permutation(list(range(len(s))))
    letters = {0: s, 1: r, -1: r[r]}

    def word(w):
        a = np.arange(len(s))
        for t in w:
            a = letters[t][a]
        return Permutation(a.tolist())

    def compact(gens):
        chosen, Q = [], PermutationGroup([ident])
        for g in sorted(gens, key=lambda h: int(h.order()), reverse=True):
            if not Q.contains(g):
                chosen.append(g)
                Q = PermutationGroup(chosen)
        assert all(Q.contains(g) for g in gens)
        return Q, chosen

    G = PermutationGroup([Permutation(s.tolist()), Permutation(r.tolist())])
    F, fgens = compact([word(d['xword']), word(d['yword'])])
    E = F.derived_subgroup()
    N = [word(w) for w in d['Nwords']]
    P, pgens = compact(N)
    D = P.derived_subgroup()
    K, kgens = compact(list(D.generators) + [g**6 for g in N])
    integral = np.load(HERE / 'de_ferrari_mod9_module.npz')['integral_abelianization_kernel']
    fab = np.array([[sum(1 if a == j else -1 if a == -j else 0
                        for a in d['fword'](w)) for w in d['Nwords']]
                    for j in (1, 2)], dtype=np.int64)
    assert integral.shape == (97, 95) and not np.any(fab @ integral)
    assert Matrix(fab.tolist()).rank() == 2
    smith = smith_normal_form(Matrix(integral.tolist()), domain=ZZ)
    assert [abs(int(smith[i, i])) for i in range(95)] == [1] * 95
    correction = list(D.generators)
    for v in integral.T:
        a = ident
        for i, exponent in enumerate(v):
            if exponent:
                a = a * (N[i] ** (6 * int(exponent)))
        correction.append(a)
    C, cgens = compact(correction)
    C2 = C.derived_subgroup()
    assert all(E.contains(a) and K.contains(a) for a in C.generators)
    for a in G.generators:
        assert all(C.contains(~a * g * a) for g in C.generators)
        assert all(K.contains(~a * g * a) for g in K.generators)
    fletters = {1: d['xword'], 2: d['yword'],
                -1: d['binv'](d['xword']), -2: d['binv'](d['yword'])}
    hwords = [sum((fletters[t] for t in w), []) for w in NWORDS]
    hgens = [word(w) for w in hwords]
    H, hc = compact(hgens)
    Hd = H.derived_subgroup()
    H2, h2c = compact([a * b * ~a * ~b for a in hc for b in Hd.generators])
    # Hd is normal. The subgroup generated by these commutators is
    # closed under conjugation here; this check proves the exact gamma3.
    assert all(H2.contains(~a * b * a) for a in hc for b in H2.generators)
    orders = {name: int(group.order()) for name, group in
              [('G', G), ('F', F), ('Fprime', E), ('N', P), ('Nprime', D),
               ('K6', K), ('K6_Fprime', C), ('correction_derived', C2),
               ('H', H), ('Hprime', Hd), ('H_gamma3', H2)]}
    assert orders['G'] == json.loads((HERE / names[1]).read_text())['source_image_order']
    out = {
        'status': 'PASS_COMPLETE_SYMPLECTIC_SOURCE_SUBGROUPS', 'prime': prime,
        'orders': orders, 'factorizations': {n: factorint(o) for n, o in orders.items()},
        'source_mod_N': orders['G'] // orders['N'],
        'source_mod_correction': orders['G'] // orders['K6_Fprime'],
        'source_mod_K6': orders['G'] // orders['K6'],
        'F_abelianization_order': orders['F'] // orders['Fprime'],
        'Fprime_mod_correction': orders['Fprime'] // orders['K6_Fprime'],
        'correction_is_perfect': orders['K6_Fprime'] == orders['correction_derived'],
        'literal_x_y_orders': [int(word(d[t]).order()) for t in ('xword', 'yword')],
        'literal_H_generator_B_words': hwords,
        'literal_H_generator_orders': [int(a.order()) for a in hgens],
        'H_image_class_at_most_two': orders['H_gamma3'] == 1,
        'all97_N_images_and95_saturated_Fprime_columns_used': True,
        'input_sha256': hashes, 'seconds': round(time.time() - start, 3),
    }
    (HERE / (tag + '_subgroups_root.json')).write_text(json.dumps(out, indent=2) + '\n')
    np.savez_compressed(HERE / (tag + '_subgroups_root.npz'),
                        N_images=np.array([a.array_form for a in N], dtype=np.int64),
                        N_generators=np.array([a.array_form for a in pgens], dtype=np.int64),
                        N_derived_generators=np.array([a.array_form for a in D.generators], dtype=np.int64),
                        F_derived_generators=np.array([a.array_form for a in E.generators], dtype=np.int64),
                        correction_generators=np.array([a.array_form for a in cgens], dtype=np.int64),
                        H_images=np.array([a.array_form for a in hgens], dtype=np.int64),
                        H_derived_generators=np.array([a.array_form for a in Hd.generators], dtype=np.int64))
    assert all(sha256((HERE / n).read_bytes()).hexdigest() == h for n, h in hashes.items())
    print(json.dumps({k: v for k, v in out.items() if k not in
                     ('input_sha256', 'literal_H_generator_B_words')}, indent=2), flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--prime', type=int, default=3)
    main(parser.parse_args().prime)
