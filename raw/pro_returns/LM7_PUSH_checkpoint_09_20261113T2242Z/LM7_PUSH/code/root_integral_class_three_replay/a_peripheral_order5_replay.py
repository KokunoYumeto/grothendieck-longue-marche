#!/usr/bin/env python3
"""Replay every new D.36 finite dependency, retaining exact outputs.

Required preexisting certified inputs are a_peripheral_a6_outer.json and
a_peripheral_a6_nielsen.json from D.31--D.32, plus a_peripheral_count.py.
All other mathematical inputs are regenerated by this driver.
"""

from pathlib import Path
import hashlib
import json
import subprocess
import sys
import time

HERE = Path(__file__).resolve().parent


def main():
    started = time.monotonic()
    steps = [
        ('a_peripheral_a5_deleted.py', [], 'a_peripheral_a5_deleted'),
        ('a_peripheral_a6_cup_epi.py', [], 'a_peripheral_a6_cup_epi'),
        ('a_peripheral_surface20.py', ['--prefix', 'a_peripheral_surface20_framed'],
         'a_peripheral_surface20_framed'),
        ('a_peripheral_a6_boundary_search.py',
         ['--surface', str(HERE/'a_peripheral_surface20_framed.json'),
          '--prefix', 'a_peripheral_a6_boundary_framed'], 'a_peripheral_a6_boundary_framed'),
        ('a_peripheral_a6_boundary_search.py',
         ['--surface', str(HERE/'a_peripheral_surface20_framed.json'),
          '--boundary-flip', '0', '--flip-outer', '2',
          '--prefix', 'a_peripheral_a6_boundary_framed_flip'], 'a_peripheral_a6_boundary_framed_flip'),
        ('a_peripheral_order5_certificate.py', [], 'a_peripheral_order5_certificate')]
    records = []
    for filename, arguments, output_stem in steps:
        before = time.monotonic()
        with (HERE/(output_stem+'.out')).open('w') as log:
            subprocess.run([sys.executable, str(HERE/filename), *arguments],
                           cwd=HERE, stdout=log, stderr=log, check=True)
        elapsed = time.monotonic()-before
        data = json.loads((HERE/(output_stem+'.json')).read_text())
        assert data['status'].startswith('PASS_')
        print(filename, data['status'], f'{elapsed:.3f}s', flush=True)
        # Paths in the manifest are relative to this code directory.
        relative_arguments = [Path(a).name if a.endswith('.json') else a for a in arguments]
        records.append({'program': filename, 'arguments': relative_arguments,
                        'output_stem': output_stem, 'status': data['status']})
    result = json.loads((HERE/'a_peripheral_order5_certificate.json').read_text())
    high = 61478762617650840528585632300833961934848
    low = 61478762617650840213814367698461663428608
    assert result['kernel_counts'] == [high]+[low]*4
    assert result['positive_excess'] == 314771264602372298506240
    without_flip = json.loads((HERE/'a_peripheral_a6_boundary_framed.json').read_text())
    pi = next(i for i, profile in enumerate(without_flip['profiles']) if profile == [12, 7, 5])
    assert without_flip['whole_group_epimorphism_counts'][pi] == [360*low]+[360*high]*4
    minimal_files = ['a_peripheral_count.py', 'a_peripheral_a6_outer.json',
                     'a_peripheral_a6_nielsen.json', 'a_peripheral_a5_deleted.py',
                     'a_peripheral_a6_outer_subgroups.cpp', 'a_peripheral_a6_cup_epi.py',
                     'a_peripheral_surface20.py', 'a_peripheral_a6_boundary_search.py',
                     'a_peripheral_order5_certificate.py', 'a_peripheral_order5_replay.py']
    outputs = [record['output_stem']+'.json' for record in records]
    outputs += ['a_peripheral_a6_outer_subgroups.json']
    checksums = {filename: hashlib.sha256((HERE/filename).read_bytes()).hexdigest()
                 for filename in minimal_files+outputs}
    manifest = {'status': 'PASS_COMPLETE_D36_REPLAY',
                'required_runtime': 'Python3 with sympy; g++ supporting C++17',
                'minimal_replay_files': minimal_files, 'steps': records,
                'sha256': checksums,
                'kernel_counts': result['kernel_counts'],
                'no_flip_kernel_counts': [low]+[high]*4,
                'positive_excess': result['positive_excess'],
                'excluded_inputs': 'Every *_incomplete_framing file and the earlier boundary_unique/phase exploratory outputs are excluded.'}
    (HERE/'a_peripheral_order5_manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print('Corrected framed kernel counts:', result['kernel_counts'], flush=True)
    print('Opposite no-flip pattern:', [low]+[high]*4, flush=True)
    print('PASS_COMPLETE_D36_REPLAY', f'total {time.monotonic()-started:.3f}s', flush=True)


if __name__ == '__main__':
    main()
