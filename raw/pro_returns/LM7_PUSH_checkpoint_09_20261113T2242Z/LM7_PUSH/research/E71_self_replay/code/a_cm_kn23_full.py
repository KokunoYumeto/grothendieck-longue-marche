#!/usr/bin/env python3
"""Entire K6 intersect F-prime image in the actual Kn23/E68 quotient."""
from pathlib import Path
from hashlib import sha256
from math import prod
import json
import time
import numpy as np

from a_cm_distribution_e62 import certify
from a_cm_kn23_source import certify_fixed
from a_cm_gl23_pc import Sifter
from de_a6_schreier_certificate import read_certificate,verify_words


HERE=Path(__file__).resolve().parent


def main():
    start=time.monotonic()
    oldsource=json.loads((HERE/'a_cm_kn23_source.json').read_text())
    derived=read_certificate(HERE/'a_cm_kn23_projected.bin')
    verify_words(derived);ds=Sifter(derived)
    extra=np.load(HERE/'a_cm_kn23_ab_lattice.npz')['kernel_basis_sixth_projected_values']
    assert extra.shape==(95,7501)
    missing=[j for j,p in enumerate(extra) if not ds.contains(p)]
    e68=read_certificate(HERE/'a_cm_distribution_orbifold_projected.bin')
    es=Sifter(e68)
    extra_old=[j for j,p in enumerate(extra) if not es.contains(p[:4957])]
    print('Full K6/Fprime extra projected values outside Nprime',missing,flush=True)
    print('Extra old projected values outside E68 image',extra_old,flush=True)
    combined=np.r_[derived['strong'],extra]
    old_stem='a_cm_distribution_orbifold_projected'
    old_cert=e68
    old_order=oldsource['old_E68_correction_order']
    if extra_old:
        old_stem='a_cm_kn23_full_old_projection'
        oi,old_cert=certify(old_stem,combined[:,:4957],greedy=True)
        old_order=int(oi['order'])
    old_base=old_cert['base']
    if missing:
        source_stem='a_cm_kn23_full_projected'
        info,cert=certify_fixed(source_stem,combined,old_base)
        assert prod(info['orbit_lengths'][:len(old_base)])==old_order
        kernel_indices=np.flatnonzero(cert['depths']>=len(old_base))
        full_kernel=cert['strong'][kernel_indices]
        assert np.array_equal(full_kernel[:,:4957],
                              np.tile(np.arange(4957),(len(full_kernel),1)))
        kernel=full_kernel[:,4957:]-4957
        targets=np.load(HERE/'a_cm_kn23_model.npz')['fixed_targets_in_projection']
        kernel_stem='a_cm_kn23_full_old_kernel'
        ki,kc=certify_fixed(kernel_stem,kernel,targets)
        assert int(ki['order'])*old_order==int(info['order'])
    else:
        assert not extra_old
        source_stem='a_cm_kn23_projected';cert=derived
        info=oldsource['projected_correction_source']
        kernel_stem='a_cm_kn23_old_kernel';ki=oldsource['kernel_over_E68']
        kernel_indices=np.load(HERE/'a_cm_kn23_source.npz')['kernel_strong_indices_in_projected']
    ratio,remainder=divmod(int(info['order']),int(oldsource['projected_correction_source']['order']))
    assert remainder==0
    out={'status':'PASS_ENTIRE_K6_INTERSECT_FPRIME_CORRECTION_IMAGE',
         'additional_lattice_generators':95,
         'additional_values_outside_Nprime_image':missing,
         'additional_old_values_outside_E68_image':extra_old,
         'entire_correction_order':info['order'],'enlargement_factor':ratio,
         'entire_old_projection_order':old_order,'kernel_over_old_order':ki['order'],
         'source_certificate':source_stem+'.bin','old_projection_certificate':old_stem+'.bin',
         'kernel_certificate':kernel_stem+'.bin','old_prefix_base_length':len(old_base),
         'source_order_data':info,'kernel_order_data':ki,
         'exact_full_domain':'K6 intersect F-prime, generated by N-prime and the95 literal sixth powers',
         'input_sha256':{name:sha256((HERE/name).read_bytes()).hexdigest() for name in
                        ['a_cm_kn23_source.json','a_cm_kn23_projected.bin',
                         'a_cm_kn23_ab_lattice.json','a_cm_kn23_ab_lattice.npz',
                         'a_cm_distribution_orbifold_projected.bin']},
         'scope':'Entire finite correction image and its old-value kernel; final K_n '
                 'fixed-tuple fibres remain to be evaluated.',
         'seconds':round(time.monotonic()-start,6)}
    np.savez_compressed(HERE/'a_cm_kn23_full.npz',
                        full_source_input_generators=combined,
                        number_Nprime_strong_inputs=len(derived['strong']),
                        kernel_strong_indices_in_selected_source=kernel_indices)
    (HERE/'a_cm_kn23_full.json').write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps(out,indent=2),flush=True)


if __name__=='__main__':main()
