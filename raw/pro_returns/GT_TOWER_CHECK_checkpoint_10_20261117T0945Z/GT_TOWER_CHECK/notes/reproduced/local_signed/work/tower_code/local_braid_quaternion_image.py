#!/usr/bin/env python3
"""Exact local B4 matrices inside the rank73 quaternion surface cover.
This records the literal local support and its full image representation;
no factorization through a smaller quotient is asserted without checking.
"""
import translation_class2_image as T
import translation_quaternion_homology as Q
import numpy as np,json
from pathlib import Path
I73=np.eye(73,dtype=np.int16);Id=T.identity_words
local=[];mats=[];qauts=[]
for j in range(3):
 g=tuple(T.F.sub(T.even_rewrite(T.sub2(v,T.hurwitz[j])),T.old3_std) for v in T.std3_D4)+Id[3:]
 boundary=(1,2,-1,-2,3)
 assert T.F.sub(boundary,g)==boundary
 c=list(g[2])
 while len(c)>1 and c[0]==-c[-1]:c=c[1:-1]
 assert c==[3]
 images=[Q.qiword(w,Q.qgs) for w in g]
 qa=[Q.qiword(Q.sections[h],images) for h in range(8)]
 assert sorted(qa)==list(range(8))
 assert all(Q.qm(qa[a],qa[b])==qa[Q.qm(a,b)] for a in range(8) for b in range(8))
 M=np.stack([Q.rewrite(T.F.sub(w,g),True) for w in Q.basis],axis=1)%3
 local.append(g);mats.append(M);qauts.append(qa)
 assert all(np.array_equal(M@Q.deck[h]%3,Q.deck[qa[h]]@M%3) for h in range(8))
# Complete quaternion residue Schreier words.
auts=[tuple(range(8))];ai={auts[0]:0};reps=[I73];words=[()]
for t,alpha in enumerate(auts):
 for j,beta in enumerate(qauts):
  gamma=tuple(alpha[beta[h]] for h in range(8))
  if gamma not in ai:ai[gamma]=len(auts);auts.append(gamma);reps.append(reps[t]@mats[j]%3);words.append(words[t]+(j+1,))
assert len(auts)==24
rr=[Q.minv(M) for M in reps];kernel=[];kw=[]
for t,alpha in enumerate(auts):
 for j,beta in enumerate(qauts):
  z=ai[tuple(alpha[beta[h]] for h in range(8))]
  M=reps[t]@mats[j]%3@rr[z]%3;A=Q.restrict(M,Q.CB,Q.cbr,Q.CBi)
  kernel.append(A);kw.append(words[t]+(j+1,)+T.F.inv(words[z]))
I18=np.eye(18,dtype=np.int16)
fixed_eq=np.vstack([A-I18 for A in kernel]);fr,fp=Q.rref(fixed_eq)
# Actual support submodule generated by all differences.
U,_=Q.rref(np.vstack([(A-I18).T for A in kernel]));U=U.T
print('LOCAL B4 quaternion residue order',len(auts),'Schreier rows',len(kernel),flush=True)
print('LOCAL M18 common fixed dimension',18-len(fr),'difference-span dimension',U.shape[1],flush=True)
form=np.load(Path(__file__).with_name('translation_quaternion_image.npz'))
print('AVAILABLE FORM KEYS',list(form.files),flush=True)
np.savez_compressed(Path(__file__).with_suffix('.npz'),local_rank73=np.array(mats),quaternion_kernel=np.array(kernel),support_subspace=U,fixed_equations=fr)
Path(__file__).with_suffix('.json').write_text(json.dumps({'scope':'Literal local B4 action on the retained rank73 quaternion cover, before a smaller factorization claim',
 'local_automorphisms':local,'quaternion_automorphisms':qauts,'quaternion_residue_order':len(auts),
 'kernel_words':kw,'kernel_generator_count':len(kernel),'fixed_dimension':18-len(fr),'support_dimension':U.shape[1]},indent=2)+'\n')
def matgap(M):return '['+','.join('['+','.join(str(int(x))+'*Z(3)^0' for x in row)+']' for row in M)+']'
gap='g:=Group(['+','.join(matgap(M) for M in kernel)+']);;\nPrint("LOCAL_KERNEL_SIZE ",Size(g)," SOLVABLE ",IsSolvableGroup(g),"\\n");\nQUIT;\n'
Path(__file__).with_suffix('.g').write_text(gap)
