#!/usr/bin/env python3
"""Verify the retained CM certificate by exhaustive kernel enumeration.

This verifier does not use Gaussian elimination to decide an affine fibre.
It enumerates all 3^8 coefficient vectors for every signed mod-12 candidate,
and independently enumerates every 2-by-2 matrix modulo twelve.
"""
from pathlib import Path
import itertools
import json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'notes/reproduced/quaternion_surface'
certificate = json.loads((DATA / 'modular_quaternion_class2.json').read_text())
archive = np.load(DATA / 'modular_quaternion_class2.npz')
records = certificate['records']

def product(a, b):
    return tuple(sum(a[2*i+k]*b[2*k+j] for k in range(2)) % 12
                 for i in range(2) for j in range(2))
cm = (0, 1, 11, 1)
all_candidates = {a for a in itertools.product(range(12), repeat=4)
                  if (a[0]*a[3]-a[1]*a[2]) % 12 == 1
                  and product(a, cm) == product(cm, a)}
recorded_candidates = {tuple(sum(row['mod12_matrix'], [])) for row in records}
assert len(records) == len(all_candidates) == 36
assert recorded_candidates == all_candidates

vectors = np.array(list(itertools.product(range(3), repeat=8)), dtype=np.int64)
counts = []
for index, row in enumerate(records):
    equation = np.array(row['actual_kernel_equation_8x8'], dtype=np.int64)
    rhs = np.array(row['actual_kernel_rhs'], dtype=np.int64)
    assert np.array_equal(equation, archive['finite_affine_equations'][index])
    assert np.array_equal(rhs, archive['finite_affine_rhs'][index])
    solutions = vectors[np.all((vectors @ equation) % 3 == rhs, axis=1)]
    count = len(solutions)
    assert bool(count) == row['lifts_to_CM_centralizer']
    assert count in (0, 81)
    counts.append({'matrix': row['mod12_matrix'], 'solutions': count,
                   'first_solution': solutions[0].tolist() if count else None})
    print('MATRIX', row['mod12_matrix'], 'EXACT_KERNEL_SOLUTIONS', count)

w = archive['actual_IA'].astype(np.int64)
pivots = archive['actual_IA_pivots']
rows = archive['source_Schreier_rows'].astype(np.int64)
assert w.shape == (8, 315)
assert rows.shape == (36864, 315)
assert np.array_equal(w[:, pivots], np.eye(8, dtype=np.int64))
assert np.array_equal((rows[:, pivots] @ w) % 3, rows % 3)
source_indices = certificate['independent_Schreier_rows']
assert len(source_indices) == 8
independent_coefficients = rows[source_indices][:, pivots]
span = (vectors @ independent_coefficients) % 3
assert len({tuple(row) for row in span}) == 6561
assert sum(row['solutions'] > 0 for row in counts) == 6
assert sum(row['solutions'] for row in counts) == 486
print('PASS independent complete signed matrix census:36 candidates.')
print('PASS exhaustive affine census:236196 vectors tested; six fibres of81, thirty empty.')
print('PASS all36864 actual Schreier rows lie in the8-dimensional span, independently generated by the eight retained source rows.')
(DATA / 'independent_affine_census.json').write_text(json.dumps(counts, indent=2)+'\n')
