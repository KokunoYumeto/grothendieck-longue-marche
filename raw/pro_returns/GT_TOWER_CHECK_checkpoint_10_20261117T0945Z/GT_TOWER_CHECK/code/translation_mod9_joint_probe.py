#!/usr/bin/env python3
"""Check whether actual mod9 homology adjustments preserve class-two output."""
import translation_class2_image as T
import numpy as np,json
from pathlib import Path
push3=[T.power(g,3)[0] for g in T.push];handle3=[T.power(g,3)[0] for g in T.handles]
print('PUSH CUBE outer-IA ranks/nonzero',len(T.rref(push3)[0]),[int(np.count_nonzero(v)) for v in push3],flush=True)
print('HANDLE CUBE outer-IA ranks/nonzero',len(T.rref(handle3)[0]),[int(np.count_nonzero(v)) for v in handle3],flush=True)
rows=[]
for i,g in enumerate(T.push):
 for h in T.push[:i]:rows.append(T.mul(g,T.mul(h,T.mul(T.inv(g),T.inv(h))))[0])
rows += [g[0] for g in T.pairtwists]
W,p=T.rref(rows)
print('COMMUTATORS + PAIR TWISTS rank',len(W),flush=True)
while True:
 old=len(W);W,p=T.rref(np.vstack([W]+[T.act(g[1],W) for g in T.handles+T.push]))
 if old==len(W):break
print('INTEGRAL HOMOLOGY KERNEL normal span',len(W),'compared actual mod3 kernel',len(T.W),flush=True)
print('PUSH CUBES add rank',len(T.rref(np.vstack((W,push3)))[0])-len(W),flush=True)
Path(__file__).with_suffix('.json').write_text(json.dumps({'scope':'Executed actual geometric IA subspace generated by integral homology identity words',
 'push_cube_nonzero':[int(np.count_nonzero(v)) for v in push3],'handle_cube_nonzero':[int(np.count_nonzero(v)) for v in handle3],
 'integral_kernel_rank':len(W),'actual_mod3_kernel_rank':len(T.W),'push_cube_extra_rank':len(T.rref(np.vstack((W,push3)))[0])-len(W)},indent=2)+'\n')
np.savez_compressed(Path(__file__).with_suffix('.npz'),integral_kernel=W,push_cubes=np.array(push3),handle_cubes=np.array(handle3))
