#!/usr/bin/env python3
"""Exact lattice and CRT certificate for the common m=2,3,6 source."""
from pathlib import Path
from math import gcd
from functools import reduce
import json
import numpy as np
HERE=Path(__file__).resolve().parent
facts={}
for p,tag in [(2,'binary'),(3,'signed')]:
    meta=json.loads((HERE/f'check_fivepoint_{tag}_module.json').read_text())
    orders=json.loads((HERE/f'check_fivepoint_{tag}_orders.json').read_text())
    data=np.load(HERE/f'check_fivepoint_{tag}_module.npz')
    assert meta['base_order']==288 and meta['source_rank']==289
    assert meta['eight_map_rank']==meta['six_deck_core_rank']==97
    assert orders['x_order']==orders['y_order']==6*p
    assert orders['pure_abelianization']==f'C{6*p}^2'
    assert np.array_equal(data['projection_left_inverse']@data['common_projection']%p,np.eye(97,dtype=np.int16))
    assert np.array_equal(data['common_projection']@data['core_factor']%p,data['six_deck_map'])
    facts[p]={'eight_map_rank':97,'base_order':288,'pure_abelianization':f'C{6*p}^2'}

vertex=np.load(HERE/'check_fivepoint_signed_vertex.npz')
words=[json.loads(s) for s in vertex['K_schreier_words'].tolist()]
exponents=np.array([[sum(1 if z==j else -1 if z==-j else 0 for z in w)
                     for j in (1,2)] for w in words],dtype=np.int64)
assert len(words)==97
assert not np.any(exponents%2)
assert not np.any(exponents.sum(axis=1)%3)
divisors=[];witness=None
for i in range(97):
    for j in range(i):
        determinant=int(exponents[i,0]*exponents[j,1]-exponents[i,1]*exponents[j,0])
        divisors.append(abs(determinant))
        if abs(determinant)==12 and witness is None:
            witness={'indices':[i,j],'words':[words[i],words[j]],
                     'exponents':[exponents[i].tolist(),exponents[j].tolist()],
                     'determinant':determinant}
assert reduce(gcd,divisors)==12
assert witness is not None
print('PASS actual97 modular Schreier words have exponent lattice L={a,b even; a+b=0 mod3}',flush=True)
print('PASS retained two-word determinant12 witness:',witness['indices'],witness['exponents'],flush=True)

records=[]
for m in (2,3,6):
    n=6*m
    # L is generated by (2,-2),(0,6); mL modulo6m has exactly three values.
    image={((2*m*a)%n,(-2*m*a+6*m*b)%n) for a in range(n) for b in range(n)}
    assert image=={(0,0),(2*m,4*m),(4*m,2*m)}
    assert all(((b%n),(a%n))==((-a%n),(-b%n)) for a,b in image)
    assert all(((-b)%n,(a-b)%n)==(a,b) for a,b in image)
    records.append({'m':m,'generator_order':n,'pure_abelianization':f'C{n}^2',
                    'kernel_lattice_image':sorted(image),'abelian_join_index':3,
                    'full_source_order':f'1728*{m}^97',
                    'modular_source_order':f'576*{m}^97',
                    'extra_kernel_s':-1,'extra_kernel_r':1})
print('PASS exact abelian join index3 and sign action for m=2,3,6',flush=True)

# Literal scalar CRT used on every retained kernel coordinate.
crt={(a,b):next(x for x in range(6) if x%2==a and x%3==b)
     for a in range(2) for b in range(3)}
assert len(set(crt.values()))==6
assert all(crt[((a+c)%2,(b+d)%3)]==(crt[(a,b)]+crt[(c,d)])%6
           for a,b in crt for c,d in crt)
print('PASS exact CRT kernel map C6^97 -> C2^97 x C3^97; common base is B/J of order1728',flush=True)
out={'scope':'Actual common-kernel formula and maps, not a parity-exclusion census',
     'prime_source_facts':facts,'K_free_rank':97,'K_exponent_index':12,
     'lattice_witness':witness,'records':records,
     'common_base_B_order':1728,'crt_table':[{ 'mod2':a,'mod3':b,'mod6':v} for (a,b),v in crt.items()],
     'all_assertions_passed':True}
Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n')
print('PASS exact lattice, source orders and all finite maps certified',flush=True)
