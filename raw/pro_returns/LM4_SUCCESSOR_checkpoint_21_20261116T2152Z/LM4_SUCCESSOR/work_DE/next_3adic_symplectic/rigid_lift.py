"""Actual rigid-kernel lifts for the first3-adic congruence obstruction.

This follows first_lift.py but also places the tetrahedral lift inside
the actual normal closure of B.56's h, hence inside its full rigid kernel.
No common element of the full profinite factors is claimed.
"""
from pathlib import Path
from collections import deque
import json,itertools,time
import numpy as np
import first_lift as f

HERE=Path(__file__).resolve().parent;start=time.monotonic()
n=10;p=3;mod=9;eye=f.eye;J=f.J
T=json.loads((HERE/'T_lift.json').read_text())
C=json.loads((HERE/'C5_lift.json').read_text())
gens=[np.array(a,dtype=np.int64) for a in T['generator_mod9_matrices']]

def reduce(w):
    out=[]
    for j in w:
        if out and out[-1]==-j:out.pop()
        else:out.append(j)
    return out

def wi(w):return [-j for j in reversed(w)]
def power(w,k):return reduce((w if k>=0 else wi(w))*abs(k))
def evaluate(w,gg=gens):
    ii=[f.inv(a) for a in gg];out=eye.copy()
    for j in w:out=out@(gg[j-1] if j>0 else ii[-j-1])%mod
    return f.norm(out)

def source_vector(w,r):
    v=np.zeros(r,dtype=np.int64)
    for j in w:v[abs(j)-1]+=1 if j>0 else -1
    return v

def schreier_word(d,edge):
    a,j,b=d['schreier_edges'][edge]
    left=[i+1 for i in d['section_source_words'][a]]
    right=[i+1 for i in d['section_source_words'][b]]
    return reduce(left+[j+1]+wi(right))

def constrained_words(d):
    piv=[schreier_word(d,e) for e in d['source_pivot_edges']]
    out=[]
    for j,free in enumerate(d['constrained_free_edges']):
        w=power(schreier_word(d,free),d['constrained_free_exponent'])
        for i,v in enumerate(piv):w=reduce(w+power(v,d['constrained_pivot_exponents'][i][j]))
        out.append(w)
    return out

Twords=constrained_words(T);Cwords=constrained_words(C)
for d,gg,ww in [(T,gens,Twords),(C,[np.array(a,dtype=np.int64) for a in C['generator_mod9_matrices']],Cwords)]:
    Q=np.array(d['source_constraint'],dtype=np.int64)
    V=np.array(d['constrained_basis'],dtype=np.int64)
    for j,w in enumerate(ww):
        assert not np.any(Q@source_vector(w,len(gg)))
        assert np.array_equal(evaluate(w,gg),(eye+3*V[:,j].reshape(n,n))%mod)
print('PASS actual integral-source-zero words realize both constrained Lie bases',flush=True)

# The normal subgroup generated by the actual rigid-kernel word h.
hword=[6,11,-6,-5];hm=evaluate(hword)
assert not np.any(f.Q@source_vector(hword,13))
sections=[[i+1 for i in w] for w in T['section_source_words']]
sectionmat=[evaluate(w) for w in sections]
Swords=[reduce(w+hword+wi(w)) for w in sections]
Smat=[evaluate(w) for w in Swords]
R=[eye.copy()];Rwords=[[]];lookup={f.key(eye):0};todo=deque([0]);edges=[]
while todo:
    a=todo.popleft()
    for j,g in enumerate(Smat):
        product=f.norm(R[a]@g)
        k=f.key(product)
        if k not in lookup:
            lookup[k]=len(R);R.append(product)
            Rwords.append(Rwords[a]+[j]);todo.append(lookup[k])
        edges.append((a,j,lookup[k]))
print('normal closure of h: mod3 order',len(R),'Schreier edges',len(edges),flush=True)

def expandS(indices):
    out=[]
    for j in indices:out=reduce(out+Swords[j])
    return out

Rinv=[f.inv(a) for a in R]
V=[];descriptions=[]
for a,j,b in edges:
    A=f.norm(R[a]@Smat[j]@Rinv[b])
    assert np.array_equal(A%3,eye)
    V.append((((A-eye)%mod)//3).reshape(-1))
    descriptions.append(['schreier',a,j,b])

# Congruence conjugators are represented by actual full-kernel
# Schreier generators. Their commutators with conjugates of h are
# themselves products of conjugates of h.
fullwords=[]
for edge in T['full_basis_edges']:
    a,j,b=edge
    w=reduce(sections[a]+[j+1]+wi(sections[b]));fullwords.append(w)
fullm=[evaluate(w) for w in fullwords]
for i,a in enumerate(fullm):
    for j,b in enumerate(Smat):
        A=f.norm(a@b@f.inv(a)@f.inv(b))
        assert np.array_equal(A%3,eye)
        V.append((((A-eye)%mod)//3).reshape(-1))
        descriptions.append(['commutator',i,j])
V=np.array(V,dtype=np.int64).T
N,selected=f.span(V)
Nwords=[];Nd=[]
for k in selected:
    d=descriptions[k];Nd.append(d)
    if d[0]=='schreier':
        _,a,j,b=d
        w=reduce(expandS(Rwords[a])+Swords[j]+wi(expandS(Rwords[b])))
    else:
        _,i,j=d
        a,b=fullwords[i],Swords[j]
        w=reduce(a+b+wi(a)+wi(b))
    Nwords.append(w)
    assert not np.any(f.Q@source_vector(w,13))
    assert np.array_equal(evaluate(w),(eye+3*N[:,len(Nwords)-1].reshape(n,n))%mod)

assert N.shape[1]==np.array(T['full_basis']).shape[1]
# Equality of spaces is checked, not just equality of dimensions.
assert f.span(np.hstack([N,np.array(T['full_basis'])]))[0].shape[1]==N.shape[1]
print('PASS normal closure of actual rigid word h contains all',N.shape[1],
      'tetrahedral congruence directions modulo9',flush=True)

Cb=np.array(C['constrained_basis'],dtype=np.int64)
common,coordinates=f.intersection(N,Cb)
assert common.shape[1]==3
common_words=[]
Cgens=[np.array(a,dtype=np.int64) for a in C['generator_mod9_matrices']]
for j in range(common.shape[1]):
    wt=[];wc=[]
    for i,w in enumerate(Nwords):wt=reduce(wt+power(w,int(coordinates[i,j])))
    for i,w in enumerate(Cwords):wc=reduce(wc+power(w,int(coordinates[N.shape[1]+i,j])))
    a,b=evaluate(wt),evaluate(wc,Cgens)
    assert np.array_equal(a,b)
    assert np.array_equal(a,(eye+3*common[:,j].reshape(n,n))%mod)
    assert not np.any(f.Q@source_vector(wt,13))
    assert not np.any(source_vector(wc,6))
    common_words.append({'T_word':wt,'C5_word':wc,'common_mod9_matrix':a.tolist()})
    print('common direction',j,'actual source-word lengths',len(wt),len(wc),flush=True)

# Determine the bracket on this explicit three-dimensional space.
_,pivotrows=f.rref(common.T)
small=common[pivotrows,:]
si=np.array(__import__('sympy').Matrix(small).inv_mod(3),dtype=np.int64)
brackets={}
for i in range(3):
    for j in range(i+1,3):
        a=common[:,i].reshape(n,n);b=common[:,j].reshape(n,n)
        z=(a@b-b@a).reshape(-1)%p
        v=si@z[pivotrows]%p
        assert np.array_equal(common@v%p,z)
        brackets[f'{i},{j}']=v.tolist()
print('common Lie brackets',brackets,flush=True)

def bracket(a,b):
    A=(common@a%p).reshape(n,n);B=(common@b%p).reshape(n,n)
    z=(A@B-B@A).reshape(-1)%p
    return si@z[pivotrows]%p

sl2=None
vectors=[np.array(v,dtype=np.int64) for v in itertools.product(range(3),repeat=3) if any(v)]
for e in vectors:
    for ff in vectors:
        h=bracket(e,ff)
        if len(f.rref(np.array([e,ff,h]).T)[1])!=3:continue
        if np.array_equal(bracket(h,e),2*e%p) and np.array_equal(bracket(h,ff),ff%p):
            sl2={'e':e.tolist(),'f':ff.tolist(),'h':h.tolist()};break
    if sl2:break
print('standard sl2 triple:',sl2,flush=True)

record={'normal_h_mod3_order':len(R),'normal_h_congruence_dimension':N.shape[1],
        'normal_h_basis':N.tolist(),'normal_h_basis_descriptions':Nd,
        'normal_h_basis_actual_source_words':Nwords,
        'common_basis':common.tolist(),'common_coordinates':coordinates.tolist(),
        'common_actual_words':common_words,'Lie_bracket_coordinates':brackets,
        'standard_sl2_triple':sl2,
        'scope':'Three actual matched mod9 quotient directions; tetrahedral lifts are in the normal closure of B56 h, hence the actual rigid kernel. No common element of K or joint-forgetful finite-quotient equality is asserted.'}
(HERE/'rigid_lift_certificate.json').write_text(json.dumps(record,indent=2)+'\n')
print('PASS exact rigid first-lift word witnesses in',round(time.monotonic()-start,3),'seconds',flush=True)
