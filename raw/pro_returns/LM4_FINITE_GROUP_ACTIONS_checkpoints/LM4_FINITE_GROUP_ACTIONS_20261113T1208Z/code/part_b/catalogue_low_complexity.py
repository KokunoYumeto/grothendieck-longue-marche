#!/usr/bin/env python3
"""Complete exact catalogues for Mod^+/-_{1,1} and Mod^+/-_{0,4}.

All arithmetic is integral.  The completeness arguments for the amalgams,
the rational grid, the section poset, and conjugacy fusion accompany the code
in B.25.  No finite quotient is substituted for a mapping class group.
"""
from collections import Counter, deque
from fractions import Fraction
from functools import lru_cache
from itertools import product, combinations
from math import gcd
from pathlib import Path
import csv
import json

OUT = Path(__file__).resolve().parent
I = (1, 0, 0, 1)
S = (0, -1, 1, 0)
R = (0, -1, 1, 1)
F = (0, 1, 1, 0)
N = 12

def mm(a, b):
    return (a[0]*b[0]+a[1]*b[2], a[0]*b[1]+a[1]*b[3],
            a[2]*b[0]+a[3]*b[2], a[2]*b[1]+a[3]*b[3])

def mv(a, v):
    return (a[0]*v[0]+a[1]*v[1], a[2]*v[0]+a[3]*v[1])

def det(a):
    return a[0]*a[3]-a[1]*a[2]

def neg(a):
    return tuple(-x for x in a)

def matrix_inverse(a):
    d = det(a)
    assert d in (-1, 1)
    return (d*a[3], -d*a[1], -d*a[2], d*a[0])

def closure(gens, mul, identity):
    h = {identity}
    todo = list(gens)
    while todo:
        x = todo.pop()
        if x in h:
            continue
        h.add(x)
        for y in tuple(h):
            z = mul(x, y)
            if z not in h:
                todo.append(z)
            z = mul(y, x)
            if z not in h:
                todo.append(z)
    return frozenset(h)

class Model:
    def __init__(self, pillow):
        self.pillow = pillow
        self.type = '(0,4)' if pillow else '(1,1)'
        self.prefix = 'S' if pillow else 'T'
        self.identity = self.elt(I)
        linear = [self.elt(S), self.elt(R), self.elt(F)]
        tr = [self.elt(I, (1, 0)), self.elt(I, (0, 1))] if pillow else []
        self.vertices = [closure(tr+[linear[i], linear[2]], self.mul,
                                 self.identity) for i in (0, 1)]
        self.edge = self.vertices[0] & self.vertices[1]
        assert [len(x) for x in self.vertices] == ([16, 24] if pillow else [8, 12])
        assert len(self.edge) == (8 if pillow else 4)
        self.grid = frozenset(self.point(p) for p in product(range(N), repeat=2))
        self.punctures = (frozenset(self.point(p) for p in
                                  product((0, N//2), repeat=2)) if pillow
                          else frozenset({(0, 0)}))
        self.surface_grid = self.grid - self.punctures
        self.element_ids = {g: i for i, g in enumerate(sorted(set.union(
            *(set(x) for x in self.vertices))))}
        self.subgroups = [self.all_subgroups(g) for g in self.vertices]
        self.words = []
        for i in range(2):
            choices = [(self.elt(S if i == 0 else R), 'S' if i == 0 else 'R'),
                       (self.elt(F), 'F')]
            if pillow:
                choices += [(self.elt(I, (1, 0)), 'U'), (self.elt(I, (0, 1)), 'V')]
            words = {self.identity:'1'}
            todo = deque([self.identity])
            while todo:
                x = todo.popleft()
                for g, label in choices:
                    y = self.mul(x, g)
                    if y not in words:
                        words[y] = ('' if x == self.identity else words[x])+label
                        todo.append(y)
            assert set(words) == set(self.vertices[i])
            self.words.append(words)
        # Independent denominator certificate: every isolated solution of
        # (A-epsilon I)p=-t/2 lies on the N-grid.  Integral translates of a
        # particular solution are generated by the columns of the inverse.
        for g in self.element_ids:
            a, t = g
            if det(a) != 1 or g == self.identity:
                continue
            for epsilon in ((1, -1) if pillow else (1,)):
                b = (a[0]-epsilon, a[1], a[2], a[3]-epsilon)
                d = det(b)
                if d == 0:
                    assert b == (0, 0, 0, 0) and t != (0, 0)
                    continue
                bi = tuple(Fraction(x, d) for x in (b[3],-b[1],-b[2],b[0]))
                particular = mv(bi, tuple(Fraction(-x, 2) for x in t))
                assert all(N % x.denominator == 0 for x in bi+particular)

    def elt(self, a, t=(0, 0)):
        if self.pillow:
            a = min(a, neg(a))
        return (a, tuple(x % 2 for x in t))

    def mul(self, x, y):
        a, t = x
        b, u = y
        au = mv(a, u)
        return self.elt(mm(a, b), (t[0]+au[0], t[1]+au[1]))

    def inv(self, x):
        a, t = x
        b = matrix_inverse(a)
        u = mv(b, t)
        return self.elt(b, neg(u))

    def conj(self, g, h):
        return self.mul(self.mul(g, h), self.inv(g))

    def group_conj(self, g, h):
        return frozenset(self.conj(g, x) for x in h)

    @lru_cache(None)
    def order(self, x):
        y = self.identity
        for n in range(1, 49):
            y = self.mul(y, x)
            if y == self.identity:
                return n
        raise AssertionError(('nonfinite element', x))

    def all_subgroups(self, g):
        hs = {frozenset({self.identity})}
        frontier = set(hs)
        while frontier:
            new = {closure(set(h)|{x}, self.mul, self.identity)
                   for h in frontier for x in g-h}
            new -= hs
            hs |= new
            frontier = new
        return frozenset(hs)

    def point(self, p):
        p = tuple(x % N for x in p)
        return min(p, tuple((-x) % N for x in p)) if self.pillow else p

    def act_point(self, g, p):
        a, t = g
        q = mv(a, p)
        return self.point((q[0]+N//2*t[0], q[1]+N//2*t[1]))

    def linear_fixed_sign(self, g, p):
        a, t = g
        q0 = mv(a, p)
        q = ((q0[0]+N//2*t[0]) % N, (q0[1]+N//2*t[1]) % N)
        if q == p:
            return 1
        if self.pillow and q == tuple((-x) % N for x in p):
            return -1
        return None

    @lru_cache(None)
    def fixed_points(self, g):
        return frozenset(p for p in self.surface_grid
                         if self.act_point(g, p) == p)

    def direction(self, a, epsilon):
        b = (a[0]-epsilon, a[1], a[2], a[3]-epsilon)
        assert gcd(*(abs(x) for x in b)) in (1, 2)
        row = (b[0], b[1]) if b[:2] != (0, 0) else (b[2], b[3])
        assert row != (0, 0)
        v = (row[1], -row[0])
        d = gcd(abs(v[0]), abs(v[1]))
        return (v[0]//d, v[1]//d)

    @lru_cache(None)
    def mirror_components(self, g):
        assert det(g[0]) == -1 and self.order(g) == 2
        graph = {}
        a, t = g
        signs = (1, -1) if self.pillow else (1,)
        for epsilon in signs:
            v = self.direction(a, epsilon)
            for p in product(range(N), repeat=2):
                q0 = mv(a, p)
                q = ((q0[0]+N//2*t[0]) % N,
                     (q0[1]+N//2*t[1]) % N)
                if q != tuple(epsilon*x % N for x in p):
                    continue
                x = self.point(p)
                graph.setdefault(x, set())
                for sg in (-1, 1):
                    y = self.point((p[0]+sg*v[0], p[1]+sg*v[1]))
                    graph[x].add(y)
        # Each nonempty fixed set before removing punctures is a circle.
        assert all(len(neighbors) == 2 for neighbors in graph.values()), (g, graph)
        left = set(graph)-self.punctures
        result = []
        while left:
            todo = [min(left)]
            comp = set()
            while todo:
                p = todo.pop()
                if p in comp or p in self.punctures:
                    continue
                comp.add(p)
                todo.extend(graph[p]-comp-self.punctures)
            left -= comp
            compact = not any(graph[p] & self.punctures for p in comp)
            result.append(('oval' if compact else 'line', frozenset(comp)))
        return tuple(sorted(result, key=lambda z:(z[0], sorted(z[1]))))

    @lru_cache(None)
    def fixed_components(self, h):
        if len(h) == 1:
            return (('surface', self.surface_grid),)
        positive = [g for g in h if det(g[0]) == 1 and g != self.identity]
        if positive:
            pts = set(self.surface_grid)
            for g in h:
                pts &= self.fixed_points(g)
            return tuple(('point', frozenset({p})) for p in sorted(pts))
        assert len(h) == 2
        return self.mirror_components(next(g for g in h if g != self.identity))

    def act_section(self, g, section):
        h, kind, points = section
        return (self.group_conj(g, h), kind,
                frozenset(self.act_point(g, p) for p in points))

    def included(self, c, d):
        return c[0] < d[0] and d[2] <= c[2]

    def mu(self, g, section):
        if g == self.identity:
            return Fraction(0)
        if det(g[0]) == -1:
            assert self.order(g) == 2
            return Fraction(1, 2)
        assert section[1] == 'point'
        p = next(iter(section[2]))
        epsilon = self.linear_fixed_sign(g, p)
        assert epsilon is not None
        a = g[0] if epsilon == 1 else neg(g[0])
        assert det(a) == 1 and a != I
        return self.matrix_rotation(a)

    def matrix_rotation(self, a):
        if a == I:
            return Fraction(0)
        trace = a[0]+a[3]
        if trace == -2:
            return Fraction(1, 2)
        n = {-1:3, 0:4, 1:6}[trace]
        # det((1,0), A(1,0)) has the sign of the local rotation angle.
        sg = 1 if a[2] > 0 else -1
        assert a[2] != 0
        return Fraction(sg, n) % 1

    def group_name(self, h):
        n = len(h)
        orders = Counter(self.order(g) for g in h)
        exp = max(orders)
        ab = all(self.mul(x, y) == self.mul(y, x) for x in h for y in h)
        if n == 1:
            return '1'
        if n in orders:
            return 'C'+str(n)
        if ab:
            if exp == 2:
                return 'C2^'+str(n.bit_length()-1)
            if n == 8 and exp == 4:
                return 'C4_x_C2'
            return 'abelian_'+str(n)+'_exp_'+str(exp)
        if n == 6:
            return 'S3'
        if n == 8:
            assert orders[2] == 5
            return 'D8'
        if n == 12:
            return 'A4' if orders[3] == 8 else 'D12'
        if n == 16:
            return 'D8_x_C2'
        if n == 24:
            return 'S4'
        return 'nonabelian_'+str(n)

    def generators(self, h):
        if len(h) == 1:
            return []
        elements = sorted(h-{self.identity}, key=lambda g:(-self.order(g),g))
        for n in range(1, 4):
            for gens in combinations(elements, n):
                if closure(gens, self.mul, self.identity) == h:
                    return list(gens)
        raise AssertionError(('needs more generators',h))

    def catalogue(self):
        # Union-find uses actual subgroups of the two vertex groups.  Internal
        # conjugations and identification of the edge subgroups are exact.
        nodes = [(i, h) for i in range(2) for h in self.subgroups[i]]
        parent = {x:x for x in nodes}
        def root(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x
        def union(x, y):
            rx, ry = root(x), root(y)
            if rx != ry:
                parent[ry] = rx
        for i, h in nodes:
            for g in self.vertices[i]:
                union((i, h), (i, self.group_conj(g, h)))
            if h <= self.edge:
                union((0, h), (1, h))
        classes = {}
        for node in nodes:
            classes.setdefault(root(node), []).append(node)
        reps = [min(ns, key=lambda x:(x[0], sorted(x[1]))) for ns in classes.values()]
        reps.sort(key=lambda x:(len(x[1]), sum(det(g[0]) == 1 for g in x[1]),
                                self.group_name(x[1]), x[0], sorted(x[1])))
        if not self.pillow:
            assert len(reps) == 13
        rows = []
        details = []
        for j, (i, h) in enumerate(reps, start=1):
            name = self.prefix+f'{j:02}'
            sections = [(k, kind, pts) for k in self.subgroups[i] if k <= h and len(k)>1
                        for kind, pts in self.fixed_components(k)]
            sections.sort(key=lambda c:(len(c[0]), sorted(c[0]), c[1], sorted(c[2])))
            maxima = [c for c in sections if not any(self.included(c, d) for d in sections)]
            remaining = set(maxima)
            orbits = []
            while remaining:
                c = next(iter(remaining))
                orbit = {self.act_section(g, c) for g in h}
                assert orbit <= set(maxima)
                remaining -= orbit
                orbits.append(orbit)
            section_ids = {c:k for k, c in enumerate(sections)}
            section_records = []
            reflection_multiple_maxima = 0
            for c in sections:
                k, kind, pts = c
                m = {self.element_ids[g]:str(self.mu(g,c)) for g in sorted(k)}
                for g in k:
                    val = self.mu(g, c)
                    assert val.denominator == self.order(g)
                    z = self.identity
                    for a in range(self.order(g)+1):
                        assert self.mu(z,c) == (a*val) % 1
                        z = self.mul(z,g)
                stab = [g for g in h if self.act_section(g,c) == c]
                max_over = [d for d in maxima if d == c or self.included(c,d)]
                if any(det(g[0]) == 1 and g != self.identity for g in k):
                    assert len(max_over) == 1
                elif len(max_over) > 1:
                    reflection_multiple_maxima += 1
                # A section with a rotation has exactly its point stabilizer;
                # its full lift centralizer is trivial.  Mirrors use B.4.
                if c in maxima and kind == 'point':
                    assert frozenset(stab) == k
                section_records.append({
                    'section_id':section_ids[c],
                    'image_elements':[self.element_ids[g] for g in sorted(k)],
                    'image_order':len(k), 'fixed_component_kind':kind,
                    'fixed_component_grid':[list(p) for p in sorted(pts)],
                    'centralizer_in_surface_group':'Z' if kind=='oval' else '1',
                    'mu_by_element_id':m, 'maximal':c in maxima,
                    'strict_extensions':[section_ids[d] for d in sections if self.included(c,d)],
                    'maximal_overgroups':[section_ids[d] for d in max_over],
                    'Gamma_stabilizer_elements':[self.element_ids[g] for g in sorted(stab)],
                    'Gamma_stabilizer_order':len(stab)})
            row = {'type':self.type, 'class_id':name, 'abstract_group':self.group_name(h),
                   'order':len(h), 'positive_order':sum(det(g[0])==1 for g in h),
                   'vertex_group_order':len(self.vertices[i]),
                   'generator_element_ids':';'.join(str(self.element_ids[g]) for g in self.generators(h)),
                   'generator_words':';'.join(self.words[i][g] for g in self.generators(h)),
                   'full_splitting_classes':len(self.fixed_components(h)),
                   'nontrivial_partial_splitting_classes':len(sections),
                   'maximal_partial_classes_Phi':len(maxima),
                   'Gamma_orbits_on_Phi':len(orbits),
                   'oval_section_classes':sum(c[1]=='oval' for c in sections),
                   'line_section_classes':sum(c[1]=='line' for c in sections),
                   'reflection_classes_with_multiple_maximal_extensions':reflection_multiple_maxima}
            rows.append(row)
            punctures = []
            for p in sorted(self.punctures):
                stab = [g for g in h if self.act_point(g,p) == p]
                mu = {}
                for g in stab:
                    if g == self.identity:
                        val = Fraction(0)
                    elif det(g[0]) == -1:
                        val = Fraction(1,2)
                    else:
                        val = self.matrix_rotation(g[0])
                        if self.pillow:
                            val = (2*val) % 1
                    assert val.denominator == self.order(g)
                    mu[self.element_ids[g]] = str(val)
                punctures.append({'grid_point':p,
                    'stabilizer_elements':[self.element_ids[g] for g in sorted(stab)],
                    'local_mu_by_element_id':mu,
                    'orbit':sorted({self.act_point(g,p) for g in h})})
            details.append({'class_id':name, 'elements':[self.element_ids[g] for g in sorted(h)],
                            'sections':section_records,
                            'punctures':punctures,
                            'Phi_orbits':sorted([sorted(section_ids[c] for c in orb) for orb in orbits])})
        stem = 'type_0_4' if self.pillow else 'type_1_1'
        with (OUT/(stem+'_finite_subgroups.csv')).open('w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
        data = {'surface_type':self.type, 'grid_denominator':N,
                'coordinates':'p/N in R^2/Z^2, modulo p~-p for the pillowcase',
                'affine_translation_convention':'t/2 for t in {0,1}^2',
                'elements':[{'id':self.element_ids[g], 'matrix':g[0], 'twice_translation':g[1],
                             'order':self.order(g), 'orientation':det(g[0])}
                            for g in sorted(self.element_ids)],
                'vertex_group_orders':[len(v) for v in self.vertices],
                'edge_order':len(self.edge),
                'all_vertex_subgroup_counts':[len(hs) for hs in self.subgroups],
                'mapping_class_subgroup_conjugacy_classes':len(reps),
                'fusion_classes':[[{'vertex':i, 'elements':[self.element_ids[g] for g in sorted(h)]}
                                   for i,h in sorted(ns,key=lambda x:(x[0],sorted(x[1])))]
                                  for ns in classes.values()],
                'catalogue':details}
        (OUT/(stem+'_partial_sections.json')).write_text(json.dumps(data,indent=2)+'\n')
        return {'type':self.type, 'conjugacy_classes':len(reps),
                'vertex_orders':[len(v) for v in self.vertices],
                'edge_order':len(self.edge),
                'all_vertex_subgroups':[len(hs) for hs in self.subgroups],
                'table':rows}

if __name__ == '__main__':
    summaries = [Model(False).catalogue(), Model(True).catalogue()]
    (OUT/'catalogue_low_complexity_output.json').write_text(json.dumps(summaries,indent=2)+'\n')
    print(json.dumps(summaries,indent=2))
