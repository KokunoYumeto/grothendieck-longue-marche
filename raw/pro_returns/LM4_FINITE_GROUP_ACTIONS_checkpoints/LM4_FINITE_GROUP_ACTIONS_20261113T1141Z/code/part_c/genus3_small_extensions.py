#!/usr/bin/env python3
"""Exact index-two extensions of the seven small positive torus groups.
All orientation-preserving isomorphisms are generated by Aut(H) and the
change of negative coset representative t -> k t.
"""
from pathlib import Path
from itertools import product
import json,sys
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
from catalogue_genus3_reflection_quotients import Group,hom
ROOT=HERE.parent/'root'
if not (ROOT/'catalogue_higher_genus.py').exists():ROOT=HERE.parents[1]/'root'

def automorphisms(H):
 gens=[];sub={H.one}
 for q in range(H.n):
  if q not in sub:
   gens.append(q);sub=H.subgroup(gens)
  if len(sub)==H.n:break
 aut=set()
 for image in product(*(tuple(q for q in range(H.n) if H.orders[q]==H.orders[g]) for g in gens)):
  a=hom(H,gens,image)
  if a is not None:aut.add(a)
 return sorted(aut)

def extensions(H):
 autos=automorphisms(H);valid=set()
 for a in autos:
  for A in range(H.n):
   if a[A]==A and all(a[a[q]]==H.conj(A,q) for q in range(H.n)):
    valid.add((a,A))
 todo_set=set(valid);records=[]
 while todo_set:
  first=min(todo_set);orb={first};queue=[first]
  for a,A in queue:
   nxt=[]
   for k in range(H.n):
    nxt.append((tuple(H.conj(k,a[q]) for q in range(H.n)),H.prod([k,a[k],A])))
   for b in autos:
    bi=[0]*H.n
    for j,q in enumerate(b):bi[q]=j
    nxt.append((tuple(b[a[bi[q]]] for q in range(H.n)),b[A]))
   for pair in nxt:
    assert pair in valid
    if pair not in orb:orb.add(pair);queue.append(pair)
  assert orb<=todo_set;todo_set-=orb
  a,A=first;N=H.n
  def mul(v,w):
   h,b=v%N,v//N;k,c=w%N,w//N
   value=H.mul[h][a[k] if b else k]
   if b and c:value=H.mul[value][A]
   return value+N*(b^c)
  per=[tuple(mul(v,w) for w in range(2*N)) for v in range(2*N)]
  G=Group(per)
  orientation=tuple(1 if q[H.one]<N else -1 for q in G.el)
  records.append({'group':G,'orientation':orientation,'alpha':a,'square':A,'extension_orbit':sorted(orb)})
 return records

if __name__=='__main__':
 acts=json.loads((ROOT/'research_data/actions-genus3.json').read_text())['actions']
 for i in (3,5,7,8,12,17,18):
  act=acts[i-1];H=Group([tuple(x-1 for x in p) for p in act['autgreps'][0]])
  es=extensions(H)
  print('O3.'+str(i),'positiveorder',H.n,'Aut',len(automorphisms(H)),'oriented extensions',len(es))
