"""Literal source-adapted F12 basis at the actual transported w=1 cluster.

There is no new geometric approximation here: inputs are the certified
common-marked braid and source-word data.  Both source lassos over every
product are retained.  Membership failures concern only the displayed
finite free subgroup, never the whole source image.
"""
from pathlib import Path
import json, hashlib
from weighted_stallings import multiply as mul, inverse as inv, substitute as sub, WeightedFold

P = Path(__file__).resolve().parent
d = json.loads((P/'w_pencil_fiber_data.json').read_text())
l = json.loads((P/'w_local_markings.json').read_text())
source = {int(k): tuple(w) for k,w in d['source_fiber_words'].items()}
w1 = l['all_local_markings'][1]
assert w1['name'] == 'base_positive_0'
per = {int(k):tuple(w) for k,w in w1['transported_peripheral_words_by_label'].items()}
indices = [11,12,13,14,15,16,18,20,22]
cluster = [1,6,7]
new = {i+1:source[j] for i,j in enumerate(indices)}
new.update({10+i:per[j] for i,j in enumerate(cluster)})
fold = WeightedFold(list(new.values()))
back = {j:fold.rewrite((j,)) for j in range(1,13)}
assert all(w is not None for w in back.values())
for j in range(1,13):
    assert sub(new[j],back)==(j,)
    assert sub(back[j],new)==(j,)
print('PASS: nine actual source words plus three actual w1 cluster meridians form F12 basis; all24 inverse identities')
source_new = {i:sub(w,back) for i,w in source.items()}
per_new = {i:sub(w,back) for i,w in per.items()}
for i in indices: assert source_new[i] == (indices.index(i)+1,)
print('Source basis indices:',indices)
print('Cluster basis labels:',cluster)
for i in [17,19,21,23]: print('Other product source word',i,':',list(source_new[i]))
print('Actual exterior meridians in the adapted basis:')
for i in [j for j in range(12) if j not in cluster]:print(i,':',list(per_new[i]))
actions = {}
for name,a in d['old_and_filled_actions'].items():
    a = {int(k):tuple(w) for k,w in a.items()}
    actions[name] = {j:sub(sub(w,a),back) for j,w in new.items()}
inverse_actions = {}
for name,a in d['old_and_filled_inverse_actions'].items():
    a = {int(k):tuple(w) for k,w in a.items()}
    inverse_actions[name] = {j:sub(sub(w,a),back) for j,w in new.items()}
for name,a in actions.items():
    ai=inverse_actions[name]
    for j in range(1,13):
        assert sub(a[j],ai)==(j,) and sub(ai[j],a)==(j,)
print('PASS all264 adapted action/inverse identities')
out = {
    'description':__doc__,
    'source_word_indices':indices,
    'cluster_order_labels':cluster,
    'new_basis_in_initial':new,
    'initial_basis_in_new':back,
    'all_source_words_in_new':source_new,
    'w1_peripheral_words_in_new':per_new,
    'actions_in_new':actions,
    'inverse_actions_in_new':inverse_actions,
    'input_sha256':{n:hashlib.sha256((P/n).read_bytes()).hexdigest() for n in ['w_pencil_fiber_data.json','w_local_markings.json']},
    'scope':'The exact actual fiber is generated by nine source words and three transported cluster directions. This proves neither whole-source normality nor whole partial-kernel normality.'
}
(P/'w_source_adapted_basis.json').write_text(json.dumps(out,indent=2)+'\n')
