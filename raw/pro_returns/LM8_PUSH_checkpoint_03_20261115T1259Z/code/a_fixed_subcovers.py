#!/usr/bin/env python3
"""Finite inertia certificates for statement A.22; standard-library only."""
from itertools import product
from pathlib import Path
import json


def subgroup(identity, gens, mul):
    out={identity}; todo=[identity]
    while todo:
        a=todo.pop()
        for b in gens:
            c=mul(a,b)
            if c not in out:out.add(c);todo.append(c)
    return out


def audit(name, elements, identity, mul, inverse):
    records=[]
    for a,b in product(elements,repeat=2):
        if len(subgroup(identity,[a,b],mul)) != 8:continue
        c=mul(mul(mul(a,b),inverse(a)),inverse(b))
        assert c != identity and mul(c,c)==identity
        assert all(mul(c,z)==mul(z,c) for z in elements)
        records.append((a,b,c))
    assert len(records)==24
    assert len({c for a,b,c in records})==1
    return records


D=list(product(range(4),range(2)));di=(0,0)
def dm(a,b):return ((a[0]+(-1 if a[1] else 1)*b[0])%4,(a[1]+b[1])%2)
def dinv(a):return next(b for b in D if dm(a,b)==di)
drec=audit('D8',D,di,dm,dinv)
central=drec[0][2]
reflections=[]
for j in range(4):
    R={di,(j,1)}
    assert central not in R
    cosets={frozenset(dm(g,h) for h in R) for g in D}
    assert len(cosets)==4
    unseen=set(cosets);lengths=[]
    while unseen:
        coset=next(iter(unseen));orbit={coset};nxt=frozenset(dm(central,g) for g in coset)
        orbit.add(nxt)
        assert len(orbit)==2
        unseen-=orbit;lengths.append(len(orbit))
    assert sorted(lengths)==[2,2]
    reflections.append({'reflection':(j,1),'inertia_orbit_lengths':lengths})

Q=[(s,j) for s in [1,-1] for j in range(4)];qi=(1,0)
def qm(a,b):
    s,i=a;t,j=b
    if i==0:return s*t,j
    if j==0:return s*t,i
    if i==j:return -s*t,0
    return s*t*(1 if (i,j) in ((1,2),(2,3),(3,1)) else -1),6-i-j
def qinv(a):return next(b for b in Q if qm(a,b)==qi)
qrec=audit('Q8',Q,qi,qm,qinv)
out={'D8_generating_pairs':len(drec),'D8_cusp_monodromy':central,
     'Q8_generating_pairs':len(qrec),'Q8_cusp_monodromy':qrec[0][2],
     'D8_reflection_quotients':reflections,
     'fixed_subgroup_in_original_P2':'closed subgroup generated by c^2',
     'scope':'Finite ramification certificate; the completion and fixed-subgroup proofs are in A.22.'}
Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps(out,indent=2))
