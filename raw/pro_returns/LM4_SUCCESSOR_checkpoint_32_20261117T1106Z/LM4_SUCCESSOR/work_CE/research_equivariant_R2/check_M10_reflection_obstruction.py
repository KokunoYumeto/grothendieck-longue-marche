"""Exact semilinear PSL2(F9) obstruction, no GAP or group-data imports.
F9=F3[i]/(i^2+1); a+bi is encoded a+3b. Matrices act on P1(F9).
The index-two extension consists of (M,e) with squareclass(det M)=e.
"""
from itertools import product
from collections import Counter, deque
from pathlib import Path
import json
P=Path(__file__).resolve().parent
A=lambda x,y: (x%3+y%3)%3+3*((x//3+y//3)%3)
N=lambda x: (-x%3)%3+3*((-(x//3))%3)
def M(x,y):
 a,b=x%3,x//3;c,d=y%3,y//3
 return (a*c-b*d)%3+3*((a*d+b*c)%3)
def pw(x,n):
 r=1
 while n:
  if n&1:r=M(r,x)
  x=M(x,x);n//=2
 return r
inv={x:pw(x,7)for x in range(1,9)}
squares={M(x,x)for x in range(1,9)}
def det(g):return A(M(g[0],g[3]),N(M(g[1],g[2])))
def norm(g):
 u=inv[next(x for x in g if x)]
 return tuple(M(u,x)for x in g)
def matmul(g,h):
 a,b,c,d=g;e,f,k,l=h
 return (A(M(a,e),M(b,k)),A(M(a,f),M(b,l)),A(M(c,e),M(d,k)),A(M(c,f),M(d,l)))
def semimul(g,h):
 m,e=g;n,f=h
 if e:n=tuple(pw(x,3)for x in n)
 return(norm(matmul(m,n)),e^f)
def perm(g):
 m,e=g;a,b,c,d=m
 out=[]
 for t in range(10):
  if t==9:num,den=a,c
  else:
   if e:t=pw(t,3)
   num,den=A(M(a,t),b),A(M(c,t),d)
  out.append(9 if den==0 else M(num,inv[den]))
 return tuple(out)
def pm(g,h):return tuple(g[h[i]]for i in range(10))
def pi(g):
 a=[0]*10
 for i,x in enumerate(g):a[x]=i
 return tuple(a)
ONE=tuple(range(10))
def generated(gs):
 gs=tuple(set(gs)|{pi(x)for x in gs});found={ONE};todo=[ONE]
 for x in todo:
  for g in gs:
   y=pm(x,g)
   if y not in found:found.add(y);todo.append(y)
 return found
def order(g):
 h=g;k=1
 while h!=ONE:h=pm(h,g);k+=1
 return k
mats=sorted({norm(g)for g in product(range(9),repeat=4)if det(g)})
assert len(mats)==720
ALL={(g,e):perm((g,e))for g in mats for e in (0,1)}
assert len(set(ALL.values()))==1440
G={h:p for h,p in ALL.items()if (det(h[0])not in squares)==bool(h[1])}
L={h:p for h,p in G.items()if h[1]==0}
assert len(G)==720 and len(L)==360
GP=set(G.values());LP=set(L.values())
# Four elementary unipotents generate PSL2(F9), checked directly.
ng=[perm(((1,t,0,1),0))for t in (1,3)]+[perm(((1,0,t,1),0))for t in (1,3)]
assert generated(ng)==LP
# A diagonal-field element adjoins the entire other coset.
eta=4;assert pw(eta,4)==2 and eta not in squares
h=(norm((eta,0,0,1)),1);hp=perm(h)
assert order(hp)==4 and generated(ng+[hp])==GP
# Check the semilinear matrix law faithfully on all generator edges.
for x,px in ALL.items():
 for y in [((1,1,0,1),0),((1,0,3,1),0),h,((1,0,0,1),1)]:
  yy=(norm(y[0]),y[1])
  assert perm(semimul(x,yy))==pm(px,perm(yy))
# Perfectness by a complete generating commutator family.
comm=[pm(pm(pm(x,y),pi(x)),pi(y))for x in LP for y in ng]
dg={ONE};chosen=[]
for x in comm:
 if x not in dg:
  chosen.append(x);dg=generated(chosen)
  if len(dg)==360:break
assert dg==LP
assert {g for g in LP if all(pm(g,x)==pm(x,g)for x in ng)}=={ONE}
orders0=Counter(order(p)for p in LP)
orders1=Counter(order(p)for p in GP-LP)
assert orders0[2]==45 and orders1[2]==0
# Every nontrivial normal subgroup of L is L: normal closures of one
# representative of each of its nonidentity conjugacy classes.
remaining=LP-{ONE};class_sizes=[]
while remaining:
 x=min(remaining)
 cl={pm(pm(g,x),pi(g))for g in LP}
 remaining-=cl;class_sizes.append(len(cl))
 assert generated(cl)==LP
# An involution of the quotient C2 has no lift, even without generation.
assert all(pm(g,g)!=ONE for g in GP-LP)
print('Full projective semilinear group:',len(ALL))
print('Actual diagonal-field extension:',len(G),'kernel:',len(L))
print('Kernel perfect and centerless: PASS; simple by all conjugacy-class normal closures: PASS')
print('Kernel element orders:',dict(sorted(orders0.items())))
print('Other coset element orders:',dict(sorted(orders1.items())))
print('Other-coset involutions: 0; all45 extension involutions lie in the kernel')
print('Generating matrices for kernel: upper/lower unipotents with t=1,i')
print('Extra semilinear generator:',h,'permutation:',hp,'order:',order(hp))
print('Every scalar quotient with kernel image central kills the perfect kernel: C2 remains')
