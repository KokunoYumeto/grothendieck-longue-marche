#!/usr/bin/env python3
"""Independent finite checks for E.20; no prime-recursion existence claim."""
from math import gcd, factorial
from fractions import Fraction
import sympy as sp

def valuation(n, p):
    if n == 0:
        return 10**9
    if isinstance(n, Fraction):
        return valuation(n.numerator, p) - valuation(n.denominator, p)
    k = 0
    while n % p == 0:
        n //= p
        k += 1
    return k

index_cases = 0
for M in range(1, 31):
    for multiplier in range(1, 13):
        n = sp.ilcm(24, 4*M) * multiplier
        H_order = int(n)//2
        for index in sp.divisors(gcd(H_order, M)):
            # In Z/H_order, H_F is generated by index.
            assert M % index == 0
            # 2 M H lies in 2 H_F.
            assert (2*M) % gcd(2*index, H_order) == 0
            # The fixed field has residual radical degree gcd(2M, n/2)=2M.
            assert gcd(2*M, H_order) == 2*M
            index_cases += 1
print('cyclic degree/index cases:', index_cases)

D, k, e, n = sp.symbols('D k e n', positive=True, integer=True)
point_bound = sp.expand((4*D+10)**2+1-(D+2)*(4*D+10)-3*D)
assert point_bound == 12*D**2+59*D+81
print('point-bound endpoint:', point_bound)

transition_cases = 0
for e0 in range(1, 31):
    for j in range(8):
        n0 = e0*factorial(j+4)
        m0 = e0*factorial(j+5)
        assert (n0//e0)*(m0//n0) == m0//e0
        transition_cases += 1
print('common-coordinate exponent transitions:', transition_cases)

# Run rational Newton iteration on actual targets 1+p^L*c. Work modulo a
# chosen power, preserving denominators prime to p; verify predicted bounds.
newton_cases = 0
nonunit_derivatives = 0
for p in (2,3,5,7,11,13):
    for exponent in (2,3,4,6,12,24,120):
        v = valuation(exponent,p)
        for extra in (1,2,4):
            L = 2*v + extra
            precision = L + 8
            modulus = p**precision
            target = 1+p**L
            x = 1
            for _ in range(30):
                # Calculate f modulo enough extra digits for dividing by p^v.
                mod_high = p**(precision+v)
                f = (pow(x,exponent,mod_high)-target) % mod_high
                if f == 0:
                    break
                assert valuation(f,p) > 2*v
                derivative = exponent*pow(x,exponent-1,mod_high)
                assert valuation(derivative,p) == v
                correction = ((f//(p**v))*pow((derivative//(p**v))%modulus,-1,modulus))%modulus
                x = (x-correction)%modulus
                if (pow(x,exponent,modulus)-target)%modulus == 0:
                    break
            assert (pow(x,exponent,modulus)-target)%modulus == 0
            assert valuation(x-1,p) >= L-v
            newton_cases += 1
            nonunit_derivatives += bool(v)
print('actual Newton lifts:', newton_cases)
print('lifts with nonunit derivative:', nonunit_derivatives)
print('PASS: all finite assertions; field/cover existence remains mathematical.')
