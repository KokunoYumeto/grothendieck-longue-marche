#!/usr/bin/env python3
"""Render the actual S4 subgroup lattice from the checked CSVs.

No manuscript-image access and no transcription or research-note mutation.
The standalone generator key makes every node an actual subgroup of Sym(1,2,3,4).
"""
from pathlib import Path
from itertools import combinations
from collections import Counter
import csv
import json
import re
import subprocess
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
with (HERE / 's4_subgroups.csv').open() as f:
    rows = list(csv.DictReader(f))
with (HERE / 's4_hasse_edges.csv').open() as f:
    edges = list(csv.DictReader(f))
assert len(rows) == 30 and len(edges) == 66

E = (0, 1, 2, 3)
def compose(a, b):
    return tuple(a[b[i]] for i in range(4))

def parse_cycle(s):
    if s == '1':
        return E
    p = list(E)
    for c in re.findall(r'\(([1234]+)\)', s):
        cc = [int(x)-1 for x in c]
        for i, x in enumerate(cc):
            p[x] = cc[(i+1) % len(cc)]
    return tuple(p)

def generate(gens):
    gens = tuple(gens)
    seen, todo = {E}, [E]
    while todo:
        h = todo.pop()
        for g in gens:
            a = compose(h, g)
            if a not in seen:
                seen.add(a)
                todo.append(a)
    return frozenset(seen)

groups = {r['id']: frozenset(map(parse_cycle, r['elements'].split())) for r in rows}
orders = {r['id']: int(r['order']) for r in rows}
generator_key = []
for r in rows:
    h = groups[r['id']]
    assert len(h) == orders[r['id']]
    candidates = sorted((x for x in r['elements'].split() if x != '1'), key=lambda x: (len(x), x))
    chosen = []
    if len(h) > 1:
        for count in range(1, 4):
            matches = [cs for cs in combinations(candidates, count) if generate(map(parse_cycle, cs)) == h]
            if matches:
                chosen = min(matches, key=lambda cs: (sum(map(len, cs)), cs))
                break
        assert chosen
    assert generate(list(map(parse_cycle, chosen))) == h
    generator_key.append({'id': r['id'], 'type': r['type'], 'order': r['order'],
                          'generators': ', '.join(chosen) if chosen else 'identity'})

actual_pairs = {(e['lower'], e['upper']) for e in edges}
expected_pairs = {(a, b) for a, h in groups.items() for b, k in groups.items()
                  if h < k and not any(h < m < k for m in groups.values())}
assert actual_pairs == expected_pairs and len(actual_pairs) == 66
for e in edges:
    assert groups[e['lower']] < groups[e['upper']]
    assert int(e['relative_index']) == orders[e['upper']] // orders[e['lower']]

key_csv = HERE / 's4_subgroup_generator_key.csv'
with key_csv.open('w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=['id', 'type', 'order', 'generators'])
    w.writeheader()
    w.writerows(generator_key)

type_labels = {
    '1': '1', 'C2_double': 'C2 · double', 'C2_transposition': 'C2 · transposition',
    'C3': 'C3', 'C4': 'C4', 'V4_nonnormal': 'V4 · other', 'V4_normal': 'V4 · normal',
    'S3': 'S3', 'D8': 'D8', 'A4': 'A4', 'S4': 'S4'
}
fills = {'1': '#ffffff', 'C2_double': '#e4edf7', 'C2_transposition': '#f0f3f7',
         'C3': '#fff0d2', 'C4': '#e1f0f8', 'V4_nonnormal': '#e8eef5',
         'V4_normal': '#ede5f6', 'S3': '#e8effb', 'D8': '#d8eeea',
         'A4': '#eadff4', 'S4': '#20344e'}
lines = [
    'digraph S4Subgroups {',
    'graph [rankdir=BT, bgcolor="white", pad="0.35", nodesep="0.20", ranksep="0.76", splines=spline, outputorder=edgesfirst, fontname="DejaVu Sans", fontsize=15, labelloc=t, labeljust=l];',
    'graph [label="ACTUAL SUBGROUPS OF S4\\n30 distinct subgroups · 66 covering inclusions\\nArrows point to the larger subgroup. Unlabelled: index 2; teal 3: index 3; amber 4: index 4.\\nEach node shows its CSV ID, type and order. Generators are listed in s4_subgroup_generator_key.md."];',
    'node [shape=box, style="rounded,filled", fontname="DejaVu Sans", fontsize=10, color="#708097", penwidth=1.0, margin="0.10,0.07"];',
    'edge [color="#a1aab8", penwidth=0.85, arrowsize=0.52, fontname="DejaVu Sans", fontsize=9, fontcolor="#526176"];',
]
key_by_id = {r['id']: r for r in generator_key}
for r in rows:
    k = key_by_id[r['id']]
    fontcolor = '#ffffff' if r['type'] == 'S4' else '#17273c'
    label = f"{r['id']}\n{type_labels[r['type']]}\norder {r['order']}"
    tooltip = f"{r['id']}: generated by {k['generators']}; order {r['order']}"
    lines.append(f'{r["id"]} [label={json.dumps(label, ensure_ascii=False)}, fillcolor="{fills[r["type"]]}", fontcolor="{fontcolor}", tooltip={json.dumps(tooltip)}];')
for e in edges:
    index = int(e['relative_index'])
    attrs = [f'tooltip="{e["lower"]} is a subgroup of {e["upper"]}; index {index}"']
    if index == 3:
        attrs += ['color="#187d78"', 'fontcolor="#146660"', 'penwidth=1.15', 'label="3"']
    elif index == 4:
        attrs += ['color="#b77a1c"', 'fontcolor="#8a5b10"', 'penwidth=1.15', 'label="4"']
    lines.append(f'{e["lower"]} -> {e["upper"]} [{", ".join(attrs)}];')
lines.append('}')
dot_path = HERE / 's4_subgroup_inclusions.dot'
dot_path.write_text('\n'.join(lines) + '\n')
svg_path = HERE / 's4_subgroup_inclusions.svg'
png_path = HERE / 's4_subgroup_inclusions.preview.png'
subprocess.run(['dot', '-Tsvg', str(dot_path), '-o', str(svg_path)], check=True)
subprocess.run(['dot', '-Tpng', '-Gdpi=125', str(dot_path), '-o', str(png_path)], check=True)

xml = ET.parse(svg_path)
ns = {'s': 'http://www.w3.org/2000/svg'}
svg_nodes = xml.findall('.//s:g[@class="node"]', ns)
svg_edges = xml.findall('.//s:g[@class="edge"]', ns)
assert len(svg_nodes) == 30 and len(svg_edges) == 66
node_titles = {g.find('s:title', ns).text for g in svg_nodes}
edge_titles = {g.find('s:title', ns).text for g in svg_edges}
assert node_titles == set(groups)
assert edge_titles == {f'{a}->{b}' for a, b in actual_pairs}
row_by_id = {r['id']: r for r in rows}
svg_y = {}
for g in svg_nodes:
    ident = g.find('s:title', ns).text
    texts = g.findall('.//s:text', ns)
    r = row_by_id[ident]
    assert [t.text for t in texts] == [ident, type_labels[r['type']], f'order {r["order"]}']
    svg_y[ident] = sum(float(t.attrib['y']) for t in texts) / len(texts)
assert all(svg_y[e['lower']] > svg_y[e['upper']] for e in edges)

key_md = HERE / 's4_subgroup_generator_key.md'
md = [
    '# Key to the actual S4 subgroup-inclusion diagram', '',
    'Each ID is one actual subgroup of the permutations of {1,2,3,4}, as listed in `s4_subgroups.csv`; repeated types are separate subgroups. Permutations are written in disjoint-cycle notation, with ordinary function composition. The identity subgroup is generated by the empty set.', '',
    'In `s4_subgroup_inclusions.svg`, arrows point from a proper subgroup to a containing subgroup with no subgroup strictly between them. Every unlabelled arrow has index 2; teal arrows labelled 3 have index 3, and amber arrows labelled 4 have index 4. All 30 nodes and 66 covering inclusions are shown.', '',
    '| ID | Type | Order | Generators |', '|---|---|---:|---|'
]
for r in generator_key:
    md.append(f'| {r["id"]} | {type_labels[r["type"]]} | {r["order"]} | `{r["generators"]}` |')
md += ['', 'Verification: every displayed generator set generates exactly the corresponding CSV subgroup; the 66 source edges are exactly all proper inclusions with no intermediate subgroup; every relative index is correct; the SVG contains 30 node groups and 66 edge groups whose titles match the CSV identifiers and directed pairs.', '',
       'Scope: this is an exact subgroup-inclusion diagram. It is not the full category of equivariant maps between the corresponding homogeneous spaces.', '']
key_md.write_text('\n'.join(md))

evidence = {
    'source_nodes': 's4_subgroups.csv', 'source_edges': 's4_hasse_edges.csv',
    'nodes': len(svg_nodes), 'cover_edges': len(svg_edges),
    'edge_direction': 'lower subgroup -> upper subgroup; upward layout',
    'relative_index_counts': dict(Counter(e['relative_index'] for e in edges)),
    'generator_sets_checked': len(generator_key),
    'all_generator_sets_generate_exact_csv_subgroup': True,
    'all_and_only_actual_cover_inclusions': True,
    'all_relative_indices_checked': True,
    'svg_node_ids_and_directed_edge_titles_match_sources': True,
    'all_svg_arrows_rise_from_lower_to_upper_node': True,
    'rendered_node_labels_match_ids_types_orders_and_have_three_lines': True,
    'visual_review': 'Own generated PNG inspected after fixing label escaping; all 30 subgroup labels readable at full size, arrows point upward, no node-label overlap. Lower ranks remain dense; SVG supports zoom and CSV remains exact adjacency source.',
    'svg_dimensions': {k: xml.getroot().attrib[k] for k in ['width', 'height', 'viewBox']},
    'files': [svg_path.name, key_md.name, key_csv.name, dot_path.name, png_path.name],
    'scope': 'Graphviz rendering of exact finite subgroup data, not manuscript-image reconstruction.'
}
(HERE / 's4_subgroup_inclusions_check.json').write_text(json.dumps(evidence, indent=2) + '\n')
print(json.dumps(evidence, indent=2))
