#!/usr/bin/env python3
"""Actual pro-5 quotient of the standard involution and local h replacements.

The quotient is generated by 1+X,1+Y in the truncated noncommutative
algebra F_5<X,Y>/(words of length four).  The local h_r are evaluations
of the proved continuous pro-5 midpoint formulas, not assigned global h.
"""
from collections import deque
from itertools import product
from pathlib import Path
import json

p = 5
words = [()] + [w for n in range(1,4) for w in product((0,1), repeat=n)]
index = {w:i for i,w in enumerate(words)}
size = len(words)
one = (1,) + (0,)*(size-1)
zero = (0,)*size
products = [(i,j,index[a+b]) for i,a in enumerate(words)
            for j,b in enumerate(words) if len(a)+len(b)<=3]

def add(a,b):
    return tuple((u+v)%p for u,v in zip(a,b))

def scale(a,n):
    return tuple(n*u%p for u in a)

def mul(a,b):
    out = [0]*size
    for i,j,k in products:
        out[k] += a[i]*b[j]
    return tuple(u%p for u in out)

def power(a,n):
    if n < 0:
        return power(inv(a),-n)
    out = one
    while n:
        if n&1:
            out = mul(out,a)
        a = mul(a,a)
        n >>= 1
    return out

def inv(a):
    u = add(a,scale(one,-1))
    u2 = mul(u,u)
    return add(add(add(one,scale(u,-1)),u2),scale(mul(u2,u),-1))

def gen(letter):
    out = list(one)
    out[index[(letter,)]] = 1
    return tuple(out)

x,y = gen(0),gen(1)
z = inv(mul(x,y))
c = mul(mul(mul(x,y),inv(x)),inv(y))

def substitution_table(image_x,image_y):
    images = [add(image_x,scale(one,-1)), add(image_y,scale(one,-1))]
    table = []
    for w in words:
        out = one
        for letter in w:
            out = mul(out,images[letter])
        table.append(out)
    return table

def substitute(a,table):
    out = [0]*size
    for coeff,row in zip(a,table):
        if coeff:
            for i,value in enumerate(row):
                out[i] += coeff*value
    return tuple(u%p for u in out)

delta_table = substitution_table(inv(x),inv(y))
theta_table = substitution_table(y,x)
omega_table = substitution_table(y,z)

def delta(a): return substitute(a,delta_table)
def theta(a): return substitute(a,theta_table)
def omega(a): return substitute(a,omega_table)
def omega2(a): return omega(omega(a))

seen = {one}
queue = deque([one])
while queue:
    a = queue.popleft()
    for b in (x,y):
        new = mul(a,b)
        if new not in seen:
            seen.add(new)
            queue.append(new)
elements = sorted(seen)
checks = []

def check(name,value):
    assert value,name
    checks.append({'name':name,'passed':True})

check('actual_truncated_Magnus_image_order',len(elements)==5**5)
check('every_image_element_has_exponent_five',all(power(a,5)==one for a in elements))
check('two_sided_inverse_for_every_image_element',all(mul(a,inv(a))==mul(inv(a),a)==one for a in elements))
check('delta_theta_omega_preserve_the_actual_image',all(
    delta(a) in seen and theta(a) in seen and omega(a) in seen for a in elements))
check('delta_theta_and_omega_have_the_stated_orders',all(
    delta(delta(a))==a and theta(theta(a))==a and omega(omega2(a))==a for a in elements))
check('unique_square_root_map_is_inverse_to_squaring',all(
    power(power(a,3),2)==a and power(power(a,2),3)==a for a in elements))

def midpoint(a):
    return mul(a,power(mul(inv(a),delta(a)),3))

check('midpoint_is_fixed_by_original_delta',all(delta(midpoint(a))==midpoint(a) for a in elements))
check('midpoint_retracts_the_actual_fixed_subset',all(midpoint(a)==a for a in elements if delta(a)==a))

def emul(a,b):
    g,i = a; h,j = b
    return (mul(g,delta(h) if i else h),(i+j)%2)

def einv(a):
    g,i = a
    return (delta(inv(g)) if i else inv(g),i)

def econj(a,b):
    return emul(emul(a,b),einv(a))

def Omega(a):
    g,i = a
    return (mul(omega(g),inv(y)) if i else omega(g),i)

s = (one,1)
t1 = (x,1)
r = Omega(Omega(s))
q = Omega(s)
check('actual_Omega_semidirect_relations',
      all(omega(delta(a))==mul(mul(inv(y),delta(omega(a))),y) for a in (x,y))
      and emul(Omega(s),Omega(s))==(one,0)
      and Omega(Omega(Omega(s)))==s)
check('original_standard_z_reflection_is_Omega_squared_s',r==t1 and emul(q,(z,0))==r)

def triple_product(g,k):
    out = power(x,k)
    for value in (inv(omega2(g)),power(z,k),inv(omega(g)),power(y,k),inv(g)):
        out = mul(out,value)
    return out

def coefficient(a):
    assert a[index[(0,)]]==a[index[(1,)]]==0
    assert a[index[(0,0)]]==a[index[(1,1)]]==0
    assert (a[index[(0,1)]]+a[index[(1,0)]])%p==0
    return a[index[(0,1)]]

rows = []
for target in range(p):
    g = midpoint(power(c,(-target*3)%p))
    h = mul(inv(g),theta(g))
    Y = mul(mul(h,y),inv(h))
    u1 = omega2(h)
    u2 = mul(mul(inv(omega(h)),inv(y)),inv(h))
    check('r%d_original_coboundary_and_first_symmetry'%target,
          delta(h)==h and mul(h,theta(h))==one and coefficient(h)==target)
    check('r%d_both_original_z_endpoint_transporters'%target,
          econj((u1,0),t1)==r and econj((u2,0),(Y,1))==q)
    values=[]
    for mu in (1,3,7,9):
        k=(mu-1)//2
        D=triple_product(h,k)
        a=mul(h,power(y,-k))
        norm=mul(mul(a,omega(a)),omega2(a))
        assert norm==inv(D)
        assert coefficient(D)==(-3*target-k*(k+1)//2)%p
        values.append({'mu_mod_10':mu,'k_mod_5':k%p,
                       'D_commutator_coefficient':coefficient(D),
                       'full_finite_D_is_identity':D==one,
                       'square_equation_mod_5':(mu*mu-1+24*target)%p==0})
    check('r%d_norm_and_original_coefficient_for_all_unit_parameters'%target,
          all(row['square_equation_mod_5']==(row['D_commutator_coefficient']==0) for row in values))
    rows.append({'chosen_local_coefficient':target,
                 'h_truncated_Magnus_coordinates':list(h),
                 'unit_parameter_tests':values})

check('coefficient_one_has_no_unit_zero_even_in_this_actual_finite_image',
      all(not row['full_finite_D_is_identity'] for row in rows[1]['unit_parameter_tests'])
      and all(not row['square_equation_mod_5'] for row in rows[1]['unit_parameter_tests']))
check('original_full_standard_h_maps_to_the_zero_coefficient_member',
      rows[0]['h_truncated_Magnus_coordinates']==list(one))

out={'status':'PASS','scope':'Original standard delta; alternate local pro-5 h_r from exact continuous maps. The original full h is 1.',
     'prime':p,'truncation_degree':3,'word_basis':[''.join('XY'[i] for i in w) or '1' for w in words],
     'actual_image_order':len(elements),'checks':checks,'assertion_count':len(checks),'rows':rows}
text=json.dumps(out,indent=2)+'\n'
Path(__file__).with_name('actual_odd_local_midpoint_output.json').write_text(text)
print(text,end='')
