#!/usr/bin/env python3
"""Aggregate the reader's page records without changing or adjudicating readings.

This script reads only records/scanNNN.json and the generated/manual doubts files.
It does not open page images, the context archive, page transcriptions or inventory.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sys

STEM = "MPL_57_089-132"
EXPECTED = set(range(89, 133)) - {98}
GENERATED_MARKER = "<!-- Generated by records/refresh_doubts.py; edit scan records or the manual sidecar. -->"
MANUAL_START = "<!-- BEGIN MANUAL AUDIT ADDITIONS -->"
MANUAL_END = "<!-- END MANUAL AUDIT ADDITIONS -->"
FIELDS = {"scan", "doubts", "notations", "abbreviations", "observations"}
OPTIONAL_FIELDS = {"audit"}
LEGIBILITY_PATTERN = re.compile(r"difficult|compressed|obscur|faint|overwrit|arrowhead|headless|heavily|fully scribbl|show-through|upside down|rotation|rotated", re.I)


def normalized(text: str) -> str:
    return text.rstrip() + "\n" if text.strip() else ""


def digest(text: str) -> str:
    return hashlib.sha256(normalized(text).encode()).hexdigest()


def code_cell(value: str) -> str:
    # Backtick delimiters longer than any in the record preserve literal LaTeX
    # quote marks. Escaping pipes is needed by Markdown's table syntax.
    value = value.replace("\r\n", "\n").replace("\n", " ").replace("|", "\\|")
    ticks = "`" * (max((len(m) for m in re.findall(r"`+", value)), default=0) + 1)
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    return f"{ticks}{pad}{value}{pad}{ticks}"


def prose_cell(value: str) -> str:
    return value.replace("\r\n", "\n").replace("\n", " ").replace("|", "\\|")


def read_records(folder: Path):
    records = []
    errors = []
    warnings = []
    for path in sorted(folder.glob("scan*.json")):
        match = re.fullmatch(r"scan(\d{3})\.json", path.name)
        if not match:
            errors.append(f"{path.name}: filename does not match scanNNN.json")
            continue
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            errors.append(f"{path.name}: {exc}")
            continue
        if not isinstance(record, dict):
            errors.append(f"{path.name}: record must be an object")
            continue
        number = int(match.group(1))
        if type(record.get("scan")) is not int or record["scan"] != number:
            errors.append(f"{path.name}: integer scan field must equal filename number {number}")
        if number not in EXPECTED:
            errors.append(f"{path.name}: scan is outside the required nonblank set")
        for key in sorted(FIELDS - set(record)):
            errors.append(f"{path.name}: missing field {key}")
        for key in sorted(set(record) - FIELDS - OPTIONAL_FIELDS):
            warnings.append(f"{path.name}: additional field {key!r} is retained in its source record but not aggregated")
        for field, length in [("doubts", 4), ("notations", 3), ("abbreviations", 2)]:
            value = record.get(field)
            if not isinstance(value, list):
                errors.append(f"{path.name}: {field} must be an array")
                continue
            for i, row in enumerate(value, 1):
                if not isinstance(row, list) or len(row) != length or not all(isinstance(x, str) for x in row):
                    errors.append(f"{path.name}: {field}[{i}] must contain {length} strings")
                elif field == "doubts" and row[3] not in {"high", "medium", "low"}:
                    errors.append(f"{path.name}: doubts[{i}] confidence must be high, medium, or low")
        observations = record.get("observations")
        if not isinstance(observations, list) or not all(isinstance(x, str) for x in observations):
            errors.append(f"{path.name}: observations must be an array of strings")
        if "audit" in record:
            audit = record["audit"]
            if not isinstance(audit, dict):
                errors.append(f"{path.name}: optional audit field must be an object")
            else:
                if not isinstance(audit.get("utc"), str):
                    errors.append(f"{path.name}: audit.utc must be a string")
                if type(audit.get("replacement_count")) is not int or audit["replacement_count"] < 0:
                    errors.append(f"{path.name}: audit.replacement_count must be a nonnegative integer")
                if not isinstance(audit.get("notes"), list) or not all(isinstance(x, str) for x in audit["notes"]):
                    errors.append(f"{path.name}: audit.notes must be an array of strings")
        records.append(record)
    if not records:
        warnings.append("No page records are present")
    return records, errors, warnings


def preserve_manual(root: Path, output: Path):
    folder = root / "records"
    manual_path = folder / "doubts_manual.md"
    if not manual_path.exists():
        manual_path.write_text("", encoding="utf-8")
    manual = normalized(manual_path.read_text(encoding="utf-8"))
    warnings = []
    if output.exists():
        previous = output.read_text(encoding="utf-8")
        if GENERATED_MARKER in previous:
            match = re.search(re.escape(MANUAL_START) + r"\n(.*?)" + re.escape(MANUAL_END), previous, re.S)
            baseline = re.search(r"<!-- manual-sha256: ([0-9a-f]{64}) -->", previous)
            if match and baseline:
                inline = normalized(match.group(1))
                baseline_hash = baseline.group(1)
                if digest(inline) != baseline_hash:
                    if digest(manual) == baseline_hash:
                        manual_path.write_text(inline, encoding="utf-8")
                        manual = inline
                        warnings.append("Manual audit additions edited in the generated file were preserved in records/doubts_manual.md")
                    elif inline != manual:
                        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
                        target = folder / f"doubts_manual_preserved_{stamp}.md"
                        target.write_text(inline, encoding="utf-8")
                        warnings.append(f"Both manual copies changed; the generated-file copy was preserved as records/{target.name}")
        else:
            initial = "# Doubts and notation\n\n## Recurring notation table\n\n| Ink / use | LaTeX | Scans | Comments |\n|---|---|---|---|\n\n## Doubt register\n\n| Cote | Scan | Approximate line | Reading | Alternatives | Confidence |\n|---|---|---|---|---|---|\n\n## Abbreviations\n\n## Legibility and limits\n\nWork in progress.\n"
            if normalized(previous) != normalized(initial):
                stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
                target = folder / f"doubts_preaggregation_{stamp}.md"
                target.write_text(previous, encoding="utf-8")
                warnings.append(f"The pre-existing non-template doubts file was preserved as records/{target.name}")
    return manual, warnings


def aggregate(records, manual: str, root: Path):
    notation_review_path = root / "records/notation_review.md"
    legibility_review_path = root / "records/reader_legibility_review.md"
    notation_review = notation_review_path.read_text(encoding="utf-8").strip() if notation_review_path.exists() else ""
    legibility_review = legibility_review_path.read_text(encoding="utf-8").strip() if legibility_review_path.exists() else ""
    notation = defaultdict(list)
    abbreviation = defaultdict(list)
    confidence = Counter()
    low_scans = set()
    observation_evidence = []
    doubt_count = 0
    for record in records:
        scan = record["scan"]
        for row in record["notations"]:
            if scan not in notation[tuple(row)]:
                notation[tuple(row)].append(scan)
        for row in record["abbreviations"]:
            if scan not in abbreviation[tuple(row)]:
                abbreviation[tuple(row)].append(scan)
        for row in record["doubts"]:
            doubt_count += 1
            confidence[row[3]] += 1
            if row[3] == "low":
                low_scans.add(scan)
        observation_evidence.extend((scan, o) for o in record["observations"] if LEGIBILITY_PATTERN.search(o))
    lines = ["# Doubts and notation", "", GENERATED_MARKER, ""]
    if notation_review:
        lines.extend([notation_review, ""])
    table_note = "Entries below reproduce the reader's notation records. Exact repeats are grouped; nonidentical entries remain separate. "
    if notation_review:
        table_note += "The completed reader comparison above supplies the visual cross-page assessment; this detailed table is a mechanical aggregation of the page records."
    else:
        table_note += "This table records choices made during transcription and does not itself certify the final cross-page visual comparison."
    lines.extend(["## Recurring notation table", "", table_note, "", "| Ink / use | LaTeX | Scans | Recorded comments |", "|---|---|---|---|"])
    for (ink, latex, comment), scans in notation.items():
        lines.append(f"| {prose_cell(ink)} | {code_cell(latex)} | {', '.join(f'{n:03d}' for n in scans)} | {prose_cell(comment)} |")
    lines.extend(["", "## Doubt register", "", "Readings, alternatives, locations, and confidence labels are reproduced from the page records without editorial normalization. The approximate locations are the reader's labels, not newly inferred line numbers.", "", "| File | Scan | Approximate line / location | Reading | Alternatives / recorded qualification | Confidence |", "|---|---|---|---|---|---|"])
    for record in records:
        for location, reading, alternative, rating in record["doubts"]:
            lines.append(f"| 57.pdf | {record['scan']:03d} | {prose_cell(location)} | {code_cell(reading)} | {prose_cell(alternative)} | {rating} |")
    lines.extend(["", "## Abbreviations", "", "Expansions are the reader's interpretations and belong only in this list. Exact repeated abbreviation/expansion pairs are grouped; differing interpretations remain separate.", "", "| Abbreviation on the page | Suggested expansion | Scans |", "|---|---|---|"])
    for (abbr, expansion), scans in abbreviation.items():
        lines.append(f"| {code_cell(abbr)} | {prose_cell(expansion)} | {', '.join(f'{n:03d}' for n in scans)} |")
    covered = ", ".join(f"{r['scan']:03d}" for r in records)
    lines.extend(["", "## Legibility and limits", ""])
    if legibility_review:
        # Nest the supplied reader assessment within this section; its prose is
        # reproduced unchanged and remains separate from the script's counts.
        nested_review = re.sub(r"(?m)^(#{1,5}) ", r"\1# ", legibility_review)
        lines.extend([nested_review, "", "### Aggregated record summary", ""])
    lines.append(f"This aggregation covers {len(records)} page records (scans {covered}) and {doubt_count} recorded doubt entries: {confidence['high']} high, {confidence['medium']} medium, and {confidence['low']} low confidence. These are recorded reading judgments, not an estimate of the transcription's error rate. No image was inspected by this aggregation script.")
    if low_scans:
        lines.extend(["", "The least trusted entries in these records are those explicitly marked **low** confidence, on scans " + ", ".join(f"{n:03d}" for n in sorted(low_scans)) + "; the table preserves their exact locations and qualifications. Absence of a doubt entry is not a certification that a page is unambiguous."])
    if observation_evidence:
        lines.extend(["", "The following recorded observations bear directly on orientation or legibility; they are reproduced verbatim:", ""])
        for scan, observation in observation_evidence:
            lines.append(f"- Scan {scan:03d}: {observation}")
    lines.extend(["", "## Manual audit additions", "", "Manual additions are stored separately in `records/doubts_manual.md` and included below. The refresh script preserves edits made inside this marked section.", "", f"<!-- manual-sha256: {digest(manual)} -->", MANUAL_START, manual.rstrip(), MANUAL_END])
    saved = sorted((root / "records").glob("doubts_manual_preserved_*.md")) + sorted((root / "records").glob("doubts_preaggregation_*.md"))
    if saved:
        lines.extend(["", "Additional preserved manual material (not silently merged):", ""])
        lines.extend(f"- `records/{path.name}`" for path in saved)
    return "\n".join(lines) + "\n", doubt_count, len(notation), len(abbreviation)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    root = args.root.resolve()
    records, errors, warnings = read_records(root / "records")
    report_path = root / "records/doubts_aggregation_report.md"
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    if not errors:
        target = root / f"{STEM}_doubts.md"
        manual, manual_warnings = preserve_manual(root, target)
        warnings.extend(manual_warnings)
        contents, count, notations, abbreviations = aggregate(records, manual, root)
        temporary = target.with_suffix(".md.tmp")
        temporary.write_text(contents, encoding="utf-8")
        temporary.replace(target)
        summary = f"Aggregated {len(records)} records, {count} doubt entries, {notations} distinct notation entries, and {abbreviations} distinct abbreviation/expansion pairs."
    else:
        summary = "Aggregation stopped because records were malformed. The existing doubts file was not overwritten."
    report = ["# Doubts aggregation record", "", now, "", summary, "", "This is a mechanical aggregation only: no scans, context contents, transcription files, or inventory were read or changed.", "", "## Schema errors", ""]
    report.extend([f"- {e}" for e in errors] or ["None."])
    report.extend(["", "## Warnings", ""])
    report.extend([f"- {w}" for w in warnings] or ["None."])
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")
    print(summary)
    for entry in errors:
        print("ERROR:", entry)
    for entry in warnings:
        print("WARNING:", entry)
    print(report_path)
    return int(bool(errors))


if __name__ == "__main__":
    sys.exit(main())
