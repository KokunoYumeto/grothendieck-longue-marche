#!/usr/bin/env python3
"""Retain the verified checkpoint12 storage and the failed G86 search exactly."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
def read(path):
    return json.loads(path.read_text())
def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()

plan = read(ROOT / 'notes/checkpoint12_storage_plan.json')
qa = read(ROOT / 'notes/checkpoint13_qa_encoding.json')
state = read(ROOT / 'notes/checkpoint13_frozen_state.json')
new = read(ROOT / 'code/pbc_quotient86_primary2_full_replay_transform.json')
assert qa['status'] == 'PASS'
assert new['kind'] == 'gzip_payload'
assert new['entire_decoded_byte_hash_verified']
assert new['decoded_bytes'] == 352632137
assert new['decoded_sha256'] == '755f8f962f7c7938af754974063c6ec72ca74f65abb73a758d14d0da2edc7da8'
large = [e for e in plan['transforms'] if e.get('codec') != 'PNG_FROM_PDF01']
assert len(large) == 11
plan['transforms'] = large + [new] + qa['transforms']
plan.update({
    'scheduled_utc': '2026-11-15T23:00:00Z',
    'paper_pages': state['paper_pages'],
    'paper_statements': state['paper_statements'],
    'verification_scope': (
        'All prior numerical payloads retain their complete decoded count and '
        'SHA-256 checks, including actual full byte comparisons and exact prefixes. '
        'The new G86 trace is retained by an executed full 352632137-byte replay; '
        'its original-source target replay failed, so its successful arithmetic '
        'search is not used as a mathematical quotient certificate. The complete '
        'failure records are included. The independent G26 original-row '
        'certificate proves only the original three-primary component. '
        'C.31 remains Open. Every encoded QA image is regenerated byte for byte. '
        'The materialized checkpoint01-12 history retains every historical entry '
        'or its individually specified exact decoded replacement.'),
})
names = [e['original_path'] for e in plan['transforms']]
names += [e['original_path'] for e in plan['exact_prefix_reconstructions']]
names += [e['original_path'] for e in plan['superseded_compression_wrappers']]
assert len(names) == len(set(names))
stored = {}
encoded_prefixes = [e for e in plan['exact_prefix_reconstructions']
                    if 'local_encoded_file' in e]
for entry in plan['transforms'] + encoded_prefixes:
    assert entry['entire_decoded_byte_hash_verified']
    if entry in plan['transforms']:
        assert entry['kind'] in ('raw_bytes', 'gzip_payload')
    if 'local_encoded_file' in entry:
        path = Path(entry['local_encoded_file'])
        digest = entry.get('encoded_xz_sha256', entry.get('stored_sha256'))
        assert sha(path) == digest, str(path)
        stored[entry['stored_path']] = path.stat().st_size
    for extra in entry.get('additional_payloads', []):
        path = Path(extra['local_file'])
        assert sha(path) == extra['sha256'], str(path)
        stored[extra['path']] = path.stat().st_size
for extra in plan.get('additional_payloads', []):
    path = Path(extra['local_file'])
    assert sha(path) == extra['sha256']
    stored[extra['path']] = path.stat().st_size
recipe = read(Path(new['local_encoded_file']))
assert recipe['entire_original_byte_comparison']
for name, digest in [('source_dat', 'source_dat_sha256'),
                     ('replay_source', 'replay_source_sha256'),
                     ('replay_executable', 'replay_executable_sha256')]:
    assert sha(ROOT / recipe[name]) == recipe[digest]
for dep in recipe['build_dependencies']:
    assert sha(ROOT / dep['path']) == dep['sha256']
dest = ROOT / 'notes/checkpoint13_storage_plan.json'
dest.write_text(json.dumps(plan, indent=2) + '\n')
print(json.dumps({
    'status': 'PASS', 'transforms': len(plan['transforms']),
    'exact_prefix_reconstructions': len(plan['exact_prefix_reconstructions']),
    'encoded_pngs': qa['encoded_images'],
    'distinct_stored_payloads': len(stored),
    'stored_payload_bytes': sum(stored.values()),
    'all_payload_hashes_checked': True,
    'new_trace_mathematical_status': 'Original-source target replay failed; retained work record only.',
    'path': str(dest),
}, indent=2))
