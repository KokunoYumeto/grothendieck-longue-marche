#!/usr/bin/env python3
"""Assemble checkpoint 11's fully verified reversible storage plan."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]

def read(path):
    return json.loads(path.read_text())

def sha(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()

plan = read(ROOT / 'notes/checkpoint10_storage_plan.json')
v5 = read(ROOT.parent / 'checkpoint11_replay/pbc_v5_replay_transform.json')
v2 = read(ROOT.parent / 'checkpoint11_smallmod_replay/pbc_smallmod_v2_replay_transform.json')
v1 = read(ROOT.parent / 'checkpoint11_smallmod_replay/pbc_smallmod_v1_prefix_transform.json')
qa = read(ROOT / 'notes/checkpoint11_qa_encoding.json')
assert qa['status'] == 'PASS'

large = [entry for entry in plan['transforms']
         if entry.get('codec') != 'PNG_FROM_PDF01'
         and entry['original_path'] != v5['original_path']]
assert len(large) == 7
plan['transforms'] = large + [v5, v2] + qa['transforms']
for entry in plan['exact_prefix_reconstructions']:
    if entry['kind'] == 'native_v4':
        entry['stored_source_path'] = 'code/pbc_v5_replay_recipe.json'
plan['exact_prefix_reconstructions'].append(v1)

plan.update({
    'scheduled_utc': '2026-11-15T21:00:00Z',
    'paper_pages': 455,
    'paper_statements': 258,
    'verification_scope': (
        'All large encoded payloads fully decoded and hashed. The boundary, '
        'native-v5 and smallmod-v2 deterministic replays each compared every '
        'original decoded byte. Every old smallmod-v1 byte was compared with '
        'the frozen v2 prefix and with actual portable-helper restoration. '
        'Every encoded PNG was regenerated byte-for-byte. All source/leaf '
        'records, partial records, algorithms, dependency hashes and restore '
        'commands are retained. Storage verification does not prove C.31.'),
})

originals = [e['original_path'] for e in plan['transforms']]
originals += [e['original_path'] for e in plan['exact_prefix_reconstructions']]
originals += [e['original_path'] for e in plan['superseded_compression_wrappers']]
assert len(originals) == len(set(originals))
stored = {}
for entry in plan['transforms'] + [v1]:
    assert entry['entire_decoded_byte_hash_verified']
    path = Path(entry['local_encoded_file'])
    digest = entry.get('encoded_xz_sha256', entry.get('stored_sha256'))
    assert sha(path) == digest, str(path)
    stored[entry['stored_path']] = path.stat().st_size
    for extra in entry.get('additional_payloads', []):
        path = Path(extra['local_file'])
        assert sha(path) == extra['sha256'], str(path)
        stored[extra['path']] = path.stat().st_size

dest = ROOT / 'notes/checkpoint11_storage_plan.json'
dest.write_text(json.dumps(plan, indent=2) + '\n')
print(json.dumps({
    'status': 'PASS',
    'transforms': len(plan['transforms']),
    'exact_prefix_reconstructions': len(plan['exact_prefix_reconstructions']),
    'encoded_pngs': qa['encoded_images'],
    'distinct_stored_payloads': len(stored),
    'stored_payload_bytes': sum(stored.values()),
    'all_encoded_payload_hashes_checked': True,
    'path': str(dest),
}, indent=2))
