#!/usr/bin/env python3
"""Exact subgroup and curve-degree support for the unregistered extension."""
from pathlib import Path
import json,math

def ds(m):
    out={frozenset((a,0) for a in range(0,m,d)) for d in range(1,m+1) if m%d==0}
    for d in range(1,m+1):
        if m%d:continue
        for a in range(d):
            out.add(frozenset({(j,0) for j in range(0,m,d)}|{((a+j)%m,1) for j in range(0,m,d)}))
    return out
rows=[]
for m in (4,8,16,32,64):
    def mul(x,y):return((x[0]+(-1 if x[1] else 1)*y[0])%m,(x[1]+y[1])%2)
    I={(j,0) for j in range(0,m,2)}
    for H in ds(m):
        deg=2*m//len(H);HI={mul(h,i) for h in H for i in I};cusps=2*m//len(HI)
        genus=(deg-cusps+2)//2
        for odd in (1,3,5,9,15,27):
            newdegree=deg*odd;newcusps=cusps*odd;newgenus=1+odd*(genus-1)
            assert 2*newgenus-2+newcusps==newdegree
            assert newgenus>=1
            if len(H)<2*m:assert cusps>=2 and newcusps>=2
            # The Bezout projection is an actual integral power on the product.
            assert math.gcd(2*m,odd)==1
            e2=1 if odd==1 else odd*pow(odd,-1,2*m)
            eodd=0 if odd==1 else (2*m)*pow(2*m,-1,odd)
            assert e2%(2*m)==1 and e2%odd==0
            assert eodd%(2*m)==0 and eodd%odd==1%odd
            rows.append({'m':m,'H_order':len(H),'base_degree':deg,'base_cusps':cusps,'base_genus':genus,'odd_isogeny_degree':odd,'pullback_degree':newdegree,'pullback_cusps':newcusps,'pullback_genus':newgenus})
# Literal finite product generation: subgroups generated by two arbitrary
# elements split into their projections in the coprime D8 x C3 case.
m=4
G=[(a,e,b) for a in range(m) for e in (0,1) for b in range(3)]
def mul(x,y):return((x[0]+(-1 if x[1] else 1)*y[0])%m,(x[1]+y[1])%2,(x[2]+y[2])%3)
def gen(gens):
    H={(0,0,0)}
    while True:
        J=H|{mul(x,y) for x in H for y in gens}
        if J==H:return H
        H=J
checked=0
for x in G:
    for y in G:
        H=gen((x,y));H2={(a,e) for a,e,b in H};HB={b for a,e,b in H}
        assert H=={(a,e,b) for a,e in H2 for b in HB};checked+=1
out={'status':'PASS','candidate':'Dihedral two-power times odd abelian, unregistered','curve_degree_rows':rows,'curve_degree_row_count':len(rows),'all_D8_times_C3_two_generator_subgroups_checked':checked,'scope':'Exact finite coprime subgroup and Euler-characteristic support. Actual connectedness, semistable morphism extension, nilpotent compact type and rational subtree lifting are proved in the separate draft.'}
Path(__file__).with_suffix('.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps({'status':out['status'],'curve_degree_rows':len(rows),'finite_product_pairs':checked},indent=2))
