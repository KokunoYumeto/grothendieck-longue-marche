"""Exact finite certificates for the three CM field intersections.
Only arithmetic and finite groups are checked; no GT pentagon claim is made.
"""
import itertools
import sympy as sp

# E3 at a split good prime, and its fifth-division polynomial.
points = 1 + sum((y*y-x*x*x-1)%7 == 0 for x in range(7) for y in range(7))
assert points == 12
print('E3(F7):', points, 'trace:', 8-points)
x=sp.symbols('x')
psi5=sp.expand(32*(x**3+1)**2*(x**6+20*x**3-8)-(3*x**4+12*x)**3)
assert psi5 == 5*x**12+380*x**9-240*x**6-1600*x**3-256
print('psi5(E3) =',psi5)

# F25=F5[t]/(t^2-2), with sqrt(-3)=t.
def mul25(u,v): return ((u[0]*v[0]+2*u[1]*v[1])%5,(u[0]*v[1]+u[1]*v[0])%5)
def power(mul,u,n,one):
    out=one
    while n:
        if n&1: out=mul(out,u)
        u=mul(u,u); n//=2
    return out
def order(mul,u,one,bound):
    out=one
    for n in range(1,bound+1):
        out=mul(out,u)
        if out==one:return n
    raise AssertionError('order exceeds bound')
for u in [(3,1),(3,4)]:
    assert order(mul25,u,(1,0),24)==24
print('Both -2 +/- sqrt(-3) have order 24 in F25^*.')

# Quotient by the unique odd Cartan subgroup: C8 semidirect_5 C2.
group=list(itertools.product(range(8),range(2)))
def gm(a,b):return ((a[0]+pow(5,a[1],8)*b[0])%8,(a[1]+b[1])%2)
one=(0,0)
def inv(a):return next(b for b in group if gm(a,b)==one and gm(b,a)==one)
def comm(a,b):return gm(gm(gm(a,b),inv(a)),inv(b))
commutators={comm(a,b) for a in group for b in group}
assert commutators == {(0,0),(4,0)}
cartan=[a for a in group if a[1]==0]
det=lambda a:(a[0]+2*a[1])%4
assert all(det(gm(a,b))==(det(a)+det(b))%4 for a in group for b in group)
kerdet=[a for a in group if det(a)==0]
assert len(kerdet)==4 and order(gm,(2,1),one,16)==4
assert all(gm(a,b)==gm(b,a) for a in cartan for b in cartan)
assert all(gm(a,b)==gm(b,a) for a in kerdet for b in kerdet)
print('M35 group: order16, derived C2, K3-kernel C8, K5-kernel C4.')

# F81=F3[z]/Phi5(z). z has order5; Frobenius^3 sends z to z^2.
def add81(a,b):return tuple((u+v)%3 for u,v in zip(a,b))
def mul81(a,b):
    v=[0]*7
    for i,u in enumerate(a):
        for j,w in enumerate(b):v[i+j]=(v[i+j]+u*w)%3
    for i in range(6,3,-1):
        c=v[i]
        for j in range(1,5):v[i-j]=(v[i-j]-c)%3
    return tuple(v[:4])
one81=(1,0,0,0);zero81=(0,0,0,0);z=(0,1,0,0)
all81=list(itertools.product(range(3),repeat=4))
assert all(power(mul81,u,80,one81)==one81 for u in all81 if u!=zero81)
assert power(mul81,z,27,one81)==power(mul81,z,2,one81)
minusone=(2,0,0,0)
U=[u for u in all81 if u!=zero81 and power(mul81,u,10,one81) in [one81,minusone]]
assert len(U)==20
orders=[order(mul81,u,one81,80) for u in U]
assert max(orders)==20
for u in U:
    if power(mul81,u,10,one81)==minusone:
        assert order(mul81,u,one81,80) in [4,20]
    if order(mul81,u,one81,80)==4:
        assert power(mul81,u,27,one81)==power(mul81,u,3,one81)
print('J5[3] unit constraint: C20; multiplier -1 forces 2-part order4; base generator inverts C4.')

# All order16 extensions with u^4=1, vuv^-1=u^-1, v^4 in <u>:
# consistency permits v^4=1 or u^2. In both cases the multiplier kernel
# generated by u^2 and v is abelian, and derived subgroup is <u^2>.
for twist in [0,2]:
    gg=list(itertools.product(range(4),range(4)))
    def mult(a,b):
        i,j=a;k,l=b
        return ((i+((-1)**j)*k+twist*((j+l)//4))%4,(j+l)%4)
    assert all(mult(mult(a,b),c)==mult(a,mult(b,c)) for a in gg for b in gg for c in gg)
    ee=(0,0)
    ii={a:next(b for b in gg if mult(a,b)==ee and mult(b,a)==ee) for a in gg}
    cc={mult(mult(mult(a,b),ii[a]),ii[b]) for a in gg for b in gg}
    assert cc=={(0,0),(2,0)}
    ker=[a for a in gg if a[0]%2==0]
    assert all(mult(a,b)==mult(b,a) for a in ker for b in ker)
    print('J5[3] extension twist',twist,': derived C2 and abelian multiplier kernel of order8.')

# The fourth-root product at alpha=1 in y^2=x^5-1 equals f'(1)=5.
assert sp.diff(x**5-1,x).subs(x,1)==5
print('Yelton product for alpha=1: 5.')
print('PASS: exact CM arithmetic certificates.')
