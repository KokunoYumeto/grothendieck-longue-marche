"""Exact certificate for the noncentral 2-module tripod refinement (A.47).

Permutations act on the left; vectors are even-weight 9-bit vectors.
The full group 2^8:A9 is not enumerated. Generation follows from the
proved simplicity/H1 argument plus the explicit non-coboundary test.
"""
from collections import deque

def cycle(*xs):
    p=list(range(9))
    for a,b in zip(xs,xs[1:]+xs[:1]):p[a]=b
    return tuple(p)
def compose(p,q):return tuple(p[q[i]] for i in range(9))
def inverse(p):return tuple(p.index(i) for i in range(9))
def act(p,v):return sum(1<<p[i] for i in range(9) if v>>i&1)
def norm(p,v):
    result=0
    for _ in range(7): result^=v;v=act(p,v)
    return result

def rank(vectors):
    piv={}
    for v in vectors:
        while v:
            i=v.bit_length()-1
            if i in piv:v^=piv[i]
            else:piv[i]=v;break
    return len(piv)

def support(v):return [i+1 for i in range(9) if v>>i&1]

I=tuple(range(9))
X=cycle(0,1,2,3,4,5,6)
Y=cycle(0,1,4,3,2,7,8)
XY=compose(X,Y);Z=inverse(XY)
V=[v for v in range(512) if v.bit_count()%2==0]
solutions=[]
coboundaries={(w^act(X,w),w^act(Y,w)) for w in V}
for vx in V:
    if norm(X,vx):continue
    for vy in V:
        if norm(Y,vy):continue
        if norm(XY,vx^act(X,vy)):continue
        solutions.append((vx,vy))
assert len(solutions)==1024 and len(coboundaries)==256
assert coboundaries<=set(solutions)
vx,vy=next(pair for pair in solutions if pair not in coboundaries)
vz=act(Z,vx^act(X,vy))
assert norm(X,vx)==norm(Y,vy)==norm(Z,vz)==0
assert not any(vx==w^act(X,w) and vy==w^act(Y,w) for w in V)
print('V: even-weight F2^9, dimension8; exact number',len(V))
print('Fixed dimensions for X,Y,Z:',[sum(act(p,v)==v for v in V).bit_length()-1 for p in (X,Y,Z)])
print('Order-seven lift equations: exactly',len(solutions),'solutions, dimension10')
print('Simultaneous V-conjugacy coboundaries:',len(coboundaries),'dimension8')
print('Quotient dimension:',10-8)
print('Chosen vector supports: vx=',support(vx),'vy=',support(vy),'vz=',support(vz))
print('All three affine lift orders divide7, and projected orders are7: PASS')
print('Exhaustive256-vector common-coboundary test: NOT a coboundary: PASS')
seen={I};todo=deque([I])
while todo:
    g=todo.popleft()
    for h in (X,Y):
        gh=compose(g,h)
        if gh not in seen:seen.add(gh);todo.append(gh)
assert len(seen)==181440
print('Head generated by X,Y: exactly181440 elements = A9: PASS')
three_cycles=[cycle(i,j,k) for i in range(9) for j in range(i+1,9) for k in range(j+1,9)]
assert all(any((v^act(g,v)).bit_count()==2 for g in three_cycles) for v in V if v)
assert rank([(1<<i)^(1<<j) for i in range(9) for j in range(i+1,9)])==8
print('Simplicity certificate: every nonzero vector has a weight2 difference, and pair-vectors span V: PASS')
print('With H1(A9,V)=0 proved by Shapiro, the non-coboundary pair generates 2^8:A9.')
print('The module is noncentral: X moves the pair-vector supported on1,8 to2,8.')
print('All finite certificates PASS. No full order-two lift is inferred.')
