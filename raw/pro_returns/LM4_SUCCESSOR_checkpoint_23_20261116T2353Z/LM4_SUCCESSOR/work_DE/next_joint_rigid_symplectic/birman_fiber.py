from membership_rigid7 import reduce_word as red,inverse as inv,multiply as mul,substitute,artin
j=json.loads((HERE.parent/'next_B59_image/common_base_braid_words.json').read_text())
initial=j['initial_order_labels'];keep={1,4,5,6,11};old=[x for x in initial if x in keep]
def delete(w,order,keep):
 a=list(order);out=[]
 for b in w:
  k=abs(b)-1
  if a[k] in keep and a[k+1] in keep:
   q=sum(x in keep for x in a[:k])+1;out.append(q if b>0 else -q)
  a[k],a[k+1]=a[k+1],a[k]
 assert a==list(order)
 return red(out)
tau=tuple(range(old.index(11)+1,5));new=old[:];x=new.pop(new.index(11));new.append(x)
braids={int(i)+1:mul(inv(tau),delete(w,initial,keep),tau) for i,w in j['C5'].items()}
print('old/new finite order',old,new,'tau',tau,flush=True)
# The six rational square meridian stems are ordered by their slope.
centres=[0,1,s.Rational(30901699,10**8)+s.I*s.Rational(95105652,10**8),
 -s.Rational(80901699,10**8)+s.I*s.Rational(58778525,10**8),
 -s.Rational(80901699,10**8)-s.I*s.Rational(58778525,10**8),
 s.Rational(30901699,10**8)-s.I*s.Rational(95105652,10**8)]
base=s.Rational(371,100)+s.I*s.Rational(237,100);eps=s.Rational(1,100)
fan=sorted(range(6),key=lambda i:s.im(centres[i]+eps*(1+s.I)-base)/s.re(centres[i]+eps*(1+s.I)-base))
