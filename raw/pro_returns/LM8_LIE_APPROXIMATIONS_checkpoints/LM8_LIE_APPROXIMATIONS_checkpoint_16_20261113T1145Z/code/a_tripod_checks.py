#!/usr/bin/env python3
"""Independent exact finite checks for A.20--21.

No GAP is used for either the explicit D24 certificate or the universal
S3 group calculation.  The GAP catalogue run is separately parsed and
recorded, including its precise exhaustive bound.
"""
from collections import deque
from itertools import permutations, product
from pathlib import Path
import hashlib
import json
import re

HERE = Path(__file__).resolve().parent


def dihedral_certificate():
    # r^a s^b with s r s = r^{-1}; x=s and y=sr.
    elements = list(product(range(12), range(2)))
    identity = (0, 0)
    def mul(v, w):
        a, b = v
        c, d = w
        return ((a + (-1 if b else 1) * c) % 12, (b + d) % 2)
    def inv(v):
        return next(w for w in elements if mul(v, w) == identity)
    def power(v, n):
        ans = identity
        for _ in range(n):
            ans = mul(ans, v)
        return ans
    assert all(mul(mul(a, b), c) == mul(a, mul(b, c))
               for a in elements for b in elements for c in elements)
    x, y = (0, 1), (11, 1)
    r = mul(x, y)
    assert r == (1, 0)
    lhs, rhs = mul(power(x, 7), power(y, 7)), power(r, 7)
    conjugacy = sorted({mul(mul(inv(g), r), g) for g in elements})
    assert lhs == r and rhs == (7, 0) and rhs not in conjugacy
    return {
        "order": 24, "normal_form": "r^a s^b",
        "x": x, "y": y, "xy": r, "unit_mod_12": 7,
        "powered_product": lhs, "required_peripheral_power": rhs,
        "conjugacy_class_of_xy": conjugacy,
        "associativity_triples": 24**3, "conjugators_exhausted": 24,
    }


def universal_s3():
    ps = list(permutations(range(3)))
    p_index = {g: i for i, g in enumerate(ps)}
    identity_index = p_index[tuple(range(3))]
    assert identity_index == 0
    mt = [[p_index[tuple(a[b[k]] for k in range(3))]
           for b in ps] for a in ps]
    it = [next(j for j in range(6) if mt[i][j] == 0)
          for i in range(6)]
    evaluations = list(product(range(6), repeat=2))
    x = tuple(a for a, b in evaluations)
    y = tuple(b for a, b in evaluations)
    one = (0,) * len(evaluations)
    def mul(a, b):
        return tuple(mt[i][j] for i, j in zip(a, b))
    def inv(a):
        return tuple(it[i] for i in a)
    def conjugate(a, b):
        return mul(mul(inv(b), a), b)
    def closure(generators):
        result = {one}
        queue = deque([one])
        while queue:
            a = queue.popleft()
            for b in generators:
                z = mul(a, b)
                if z not in result:
                    result.add(z)
                    queue.append(z)
        return result
    universe = closure([x, y])
    assert len(universe) == 972
    comm = mul(mul(mul(x, y), inv(x)), inv(y))
    normal_generators = {comm}
    queue = deque([comm])
    while queue:
        a = queue.popleft()
        for b in (x, y):
            z = conjugate(a, b)
            if z not in normal_generators:
                normal_generators.add(z)
                queue.append(z)
    derived = sorted(closure(normal_generators))
    assert len(derived) == 27
    assert all(mul(a, b) == mul(b, a) for a in derived for b in derived)
    assert all(mul(mul(a, a), a) == one for a in derived)

    norm_pass, peripheral_pass, joint_pass = [], [], []
    complete_pairs = []
    edge_checks = 0
    for f in derived:
        images = [x, conjugate(y, f)]
        substitution = {one: one}
        queue = deque([one])
        while queue:
            a = queue.popleft()
            for generator, image in zip((x, y), images):
                z = mul(a, generator)
                target = mul(substitution[a], image)
                edge_checks += 1
                if z not in substitution:
                    substitution[z] = target
                    queue.append(z)
                else:
                    assert substitution[z] == target
        assert set(substitution) == universe
        norm_ok = mul(f, substitution[f]) == one
        lhs = mul(x, images[1])
        hs = [h for h in derived if lhs == conjugate(mul(x, y), h)]
        if norm_ok:
            norm_pass.append(f)
        if hs:
            peripheral_pass.append(f)
        if norm_ok and hs:
            joint_pass.append(f)
            for h in hs:
                if mul(h, substitution[h]) == one:
                    complete_pairs.append((f, h))
    assert len(norm_pass) == 2
    assert len(peripheral_pass) == 9
    assert joint_pass == [one]
    assert complete_pairs == [(one, one)]
    return {
        "description": "Subgroup of S3^36 generated by both coordinate evaluation tuples",
        "evaluations": len(evaluations), "order": len(universe),
        "derived_order": len(derived),
        "derived_is_elementary_abelian_3": True,
        "f_values_exhausted": len(derived),
        "norm_pass": len(norm_pass), "third_peripheral_derived_pass": len(peripheral_pass),
        "joint_f_pass": len(joint_pass), "joint_f_only_identity": True,
        "complete_f_h_pairs": len(complete_pairs),
        "complete_pair_only_identity": True,
        "substitution_generator_edges_checked": edge_checks,
    }


def catalogue_result():
    path = HERE / "a_tripod_finite.out"
    raw = path.read_text()
    # GAP wraps its lists. Collapse line breaks only inside each ORDER record.
    order_pattern = re.compile(
        r"ORDER (\d+) GROUPS (\d+) PAIRS (\d+) FAIL_GROUPS \[(.*?)\] FAIL_PAIRS (\d+)",
        re.S,
    )
    rows = []
    for m in order_pattern.finditer(raw):
        n, groups, pairs = map(int, m.group(1, 2, 3))
        ids = [int(x.strip()) for x in m.group(4).split(",") if x.strip()]
        rows.append({"order": n, "group_count": groups,
                     "ordered_pairs_tested": pairs, "failing_group_ids": ids,
                     "failing_pairs": int(m.group(5))})
    assert [r["order"] for r in rows] == list(range(1, 49))
    assert sum(r["group_count"] for r in rows) == 250
    assert sum(r["ordered_pairs_tested"] for r in rows) == 293009
    assert sum(r["failing_pairs"] for r in rows) == 8688
    assert all(r["failing_pairs"] == 0 for r in rows if r["order"] < 24)
    r24 = next(r for r in rows if r["order"] == 24)
    assert r24["failing_group_ids"] == [3, 4, 6, 8, 12]
    assert r24["failing_pairs"] == 432
    assert "UNIVERSAL_S3_ORDER 972 DERIVED_ORDER 27" in raw
    assert "UNIVERSAL_S3_NORM_PASS 2 PERIPHERAL_DERIVED_PASS 9 JOINT_PASS 1" in raw
    assert "UNIVERSAL_S3_JOINT_ONLY_IDENTITY true" in raw
    return {
        "scope": "All ordered pairs of all SmallGroups isomorphism types, orders 1--48",
        "gap_version": re.search(r"GAP_VERSION (\S+)", raw).group(1),
        "smallgrp_version": re.search(r"SMALLGRP_VERSION (\S+)", raw).group(1),
        "exhaustive": True, "sampled": False, "group_count": 250,
        "ordered_pairs": 293009, "total_failing_pairs": 8688,
        "minimum_witness_order_for_specified_unit_and_f1": 24,
        "rows": rows, "gap_output_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }


def main():
    result = {
        "status": "PASS",
        "dihedral_certificate": dihedral_certificate(),
        "universal_s3": universal_s3(),
        "smallgroups_catalogue": catalogue_result(),
        "scope_limit": (
            "These are exhaustive finite tests in stated quotients and bounds. "
            "They do not exhaust profinite automorphisms, classify finite peripheral "
            "subgroups, or prove nonexistence of all nontrivial solutions of (A--I)."
        ),
    }
    (HERE / "a_tripod_checks.json").write_text(json.dumps(result, indent=2) + "\n")
    print("PASS: D24 certificate, including 13824 associativity triples and 24 conjugators.")
    print("PASS: independent universal S3 group: order 972, derived order 27.")
    print("Norm f values: 2; third derived-conjugator f values: 9; joint f values: identity only.")
    print("Full norm/peripheral pairs (f,h): identity pair only.")
    print("PASS: GAP catalogue: 250 groups, 293009 ordered pairs, orders 1--48, exhaustive.")
    print("Minimum finite witness order for the specified mixed-sign f=1 candidate: 24.")
    print("No unrestricted profinite realization conclusion.")


if __name__ == "__main__":
    main()
