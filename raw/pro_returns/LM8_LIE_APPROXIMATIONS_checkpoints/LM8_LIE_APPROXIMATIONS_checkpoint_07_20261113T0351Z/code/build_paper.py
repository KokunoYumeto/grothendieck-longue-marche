#!/usr/bin/env python3
"""Build the paper, record logs, and audit explicit TeX overflow/citation errors.

A normal complete TeX Live installation needs only lualatex and bibtex.
The optional workspace fallback is detected automatically when present.
No document content or mathematical output is generated by this script.
"""
from pathlib import Path
import os,shutil,subprocess,json,re,sys
ROOT=Path(__file__).resolve().parents[1]
NAME='LM8_LIE_APPROXIMATIONS_paper'
AUDIT=ROOT/'audit'
AUDIT.mkdir(exist_ok=True)
env=os.environ.copy()
workspace=ROOT.parent
fmt=workspace/'texbuild/format/lualatex.fmt'
tds=workspace/'runtime_tex/tds'
if fmt.exists() and tds.exists():
    env.update(TEXMF='{'+str(tds)+',/usr/share/texmf,/usr/share/texlive/texmf-dist}',
               TEXMFCNF='/usr/share/texlive/texmf-dist/web2c',
               TEXMFVAR=str(workspace/'texbuild'),
               TEXMFCACHE=str(workspace/'texbuild/cache'),
               LUAINPUTS=str(tds)+'//:'+str(workspace/'runtime_tex')+'//:/usr/share/texlive/texmf-dist//:',
               OPENTYPEFONTS='/usr/share/texmf/fonts/opentype//:')
    latex=['luahbtex','--fmt='+str(fmt)]
else:
    latex=['lualatex']
latex+=['--interaction=nonstopmode','--halt-on-error',NAME+'.tex']
def run(argv,tag):
    path=AUDIT/('build_'+tag+'.txt')
    with path.open('w') as out:
        p=subprocess.run(argv,cwd=ROOT,env=env,stdout=out,stderr=subprocess.STDOUT)
    print(tag, 'exit',p.returncode,flush=True)
    if p.returncode:
        print(path.read_text()[-6000:])
        raise SystemExit(p.returncode)
def warnings():
    log=(ROOT/(NAME+'.log')).read_text(errors='replace')
    problems=[]
    for m in re.finditer(r'Overfull \\([hv])box \(([0-9.]+)pt too (wide|high)\)',log):
        problems.append({'kind':m[1],'points':float(m[2]),
                         'context':log[max(0,m.start()-150):m.start()+600]})
    return log,problems
run(latex,'latex1')
log,before=warnings()
run(['bibtex',NAME],'bibtex')
run(latex,'latex2')
run(latex,'latex3')
log,after=warnings()
(AUDIT/'final_build.log').write_text(log)
result={'latex_command':latex,'overflow_before':before,'overflow_after':after,
        'over_2pt_before':sum(p['points']>2 for p in before),
        'over_2pt_after':sum(p['points']>2 for p in after),
        'undefined_citations':len(re.findall(r'Citation .* undefined',log)),
        'undefined_references':len(re.findall(r'Reference .* undefined',log)),
        'missing_characters':len(re.findall(r'Missing character:',log))}
(AUDIT/'typesetting.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps({k:v for k,v in result.items() if not isinstance(v,list)},indent=2))
if result['over_2pt_after'] or result['undefined_citations'] or result['undefined_references'] or result['missing_characters']:
    raise SystemExit('Typesetting gate has not passed; correct source and rebuild.')

