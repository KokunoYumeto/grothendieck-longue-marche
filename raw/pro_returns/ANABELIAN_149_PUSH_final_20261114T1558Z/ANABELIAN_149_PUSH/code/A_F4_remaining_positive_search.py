#!/usr/bin/env python3
"""Accelerated exact search for a separating cyclic cover of moduli key203.

Only orders whose primitive unit group is generated by2 and−1 are included
in the default main search, together with the requested89/109/113 probes.
Known entirely empty prime supports are skipped. A positive main-search
result immediately stops; a non-Artin positive is retained for exact packet
analysis. The canonical discovery engine remains unchanged.
"""
from pathlib import Path
from math import gcd
import argparse,json,time
from A_fast_polynomials import FastArithmetic,DIGEST

ROOT=Path(__file__).parent

def units_generated(n):
    orbit=[];x=1
    while x not in orbit:orbit.append(x);x=2*x%n
    generated=set(orbit)|{(-x)%n for x in orbit}
    units={i for i in range(n) if gcd(i,n)==1}
    return generated==units

def support(n):
    result=set();p=3
    while p*p<=n:
        if n%p==0:
            result.add(p)
            while n%p==0:n//=p
        p+=2
    if n>1:result.add(n)
    return result

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--max-order',type=int,default=251)
    parser.add_argument('--orders',type=int,nargs='*');args=parser.parse_args()
    excluded=[{3,5},{3,7},{5,7},{3,11},{7,11},{13},{19},{23},{29},{31},{37},{43},{53},{59},{61},{67}]
    orders=args.orders or [n for n in range(89,args.max_order+1,2)
              if (units_generated(n) or n in [89,109,113])
              and not any(support(n)<=S for S in excluded)]
    A=FastArithmetic(4,19);out={'status':'EXPLORATORY exact positive-cover search',
          'accelerator_C_source_sha256':DIGEST,'planned_orders':orders,'tests':[]}
    dest=Path(__file__).with_suffix('.json')
    for n in orders:
        r=A.test([1,9,14],n)
        r={'moduli_key':'203','curve_coefficients':[1,9,14],
           'units_generated_by_2_and_minus_1':units_generated(n),**r}
        out['tests'].append(r);dest.write_text(json.dumps(out,indent=2)+'\n')
        print(n,r['theta_n_exists'],r['coordinate_polynomial_degree'],r['runtime_seconds'],flush=True)
        if r['theta_n_exists'] and r['units_generated_by_2_and_minus_1']:
            out['positive_separating_cover_conductor']=n;dest.write_text(json.dumps(out,indent=2)+'\n');break

if __name__=='__main__':main()
