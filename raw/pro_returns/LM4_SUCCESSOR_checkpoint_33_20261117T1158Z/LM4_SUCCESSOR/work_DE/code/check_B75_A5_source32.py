import hashlib
import json
from pathlib import Path


def compose(p, q):
    return tuple(p[q[i] - 1] for i in range(5))


def order(p):
    identity = (1, 2, 3, 4, 5)
    current = identity
    for n in range(1, 121):
        current = compose(current, p)
        if current == identity:
            return n
    raise AssertionError('Permutation order bound unexpectedly exceeded')


def parity(p):
    return sum(p[i] > p[j] for i in range(5) for j in range(i + 1, 5)) % 2


identity = (1, 2, 3, 4, 5)
e = (2, 1, 4, 3, 5)
a = (3, 2, 5, 4, 1)
ea = compose(e, a)
assert compose(e, e) == identity
assert ea == (4, 1, 5, 3, 2)
assert (order(e), order(a), order(ea)) == (2, 3, 5)
assert parity(e) == parity(a) == 0
# Enumerate only the subgroup generated by the two prescribed permutations.
# This is the fixed example's full verification, not a group/target census.
