#!/usr/bin/env python3
"""Render every exact all-prime Hall residue polynomial from the certificate."""
import json
from pathlib import Path
import sympy as S

root=Path(__file__).resolve().parents[1]
data=json.loads((root/'code/de_tame_hall.json').read_text())
q,h=S.symbols('q h')
aa=S.symbols('a1:9')
bb=S.symbols('b1:9')
symbols=[q,h,*aa,*bb]
latex_symbols={a:rf'a_{{{j}}}' for j,a in enumerate(aa,1)}
latex_symbols.update({b:rf'b_{{{j}}}' for j,b in enumerate(bb,1)})
lines=[r'\subsection*{Expanded integral Hall residue polynomials for D.32}',
       r'This appendix is generated by \texttt{de\_hall\_tex.py}.\par',
       r'It uses the exact output of \texttt{de\_tame\_hall.py}.',
       r'Both scripts are in the \texttt{code/} directory.',
       r'The variables and their order are defined in D.32.',
       r'For each prime substitute its actual $q,h_q,a_i,b_i$.',
       r'These are rational presentations of integer-valued polynomials;',
       r'denominators divisible by five must be cancelled before reduction.',
       r'No lower-stage relation has been used to shorten these expressions.',
       r'\begingroup\small\allowdisplaybreaks[4]']
counts=[]
for n,item in data['symbolic_residues'].items():
    for j,string in enumerate(item['polynomials'],1):
        poly=S.Poly(S.sympify(string),*symbols)
        assert len(poly.terms())==item['term_counts'][j-1]
        terms=[]
        for exponents,co in poly.terms():
            value=abs(co)*S.prod(z**e for z,e in zip(symbols,exponents))
            terms.append(('-' if co<0 else '+',S.latex(value,symbol_names=latex_symbols)))
        lines.append(r'\begin{align*}')
        for start in range(0,len(terms),3):
            portion=terms[start:start+3]
            text=' '.join((('' if start==0 and k==0 and sign=='+' else sign)+' '+term)
                          for k,(sign,term) in enumerate(portion))
            prefix=rf'R_{{{n},{j}}}={{}}&' if start==0 else r'&{}'
            suffix=r'\\' if start+3<len(terms) else '.'
            lines.append(prefix+text+suffix)
        lines.append(r'\end{align*}')
        counts.append([int(n),j,len(terms)])
lines.append(r'\endgroup')
(root/'sections/D_hall_polynomials.tex').write_text('\n'.join(lines)+'\n')
print(json.dumps({'status':'all nine exact polynomials rendered',
                  'term_counts':counts,
                  'lines':len(lines)},indent=2))
