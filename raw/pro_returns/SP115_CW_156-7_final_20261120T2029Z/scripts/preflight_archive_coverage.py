#!/usr/bin/env python3
"""Check checkpoint filename retention before packaging; no archive is extracted."""
from pathlib import Path
import datetime,json,zipfile
R=Path(__file__).resolve().parents[1]
checkpoints=sorted((R.parent/'result').glob('SP115_CW_156-7_checkpoint_*.zip'))
current={str(p.relative_to(R)) for p in R.rglob('*') if p.is_file() and p.suffix!='.zip' and '__pycache__' not in p.parts}
current.add('ARCHIVE_MANIFEST.json')
rows=[];required=set()
for p in checkpoints:
 with zipfile.ZipFile(p) as z:names={i.filename for i in z.infolist() if not i.is_dir() and not i.filename.lower().endswith('.zip')}
 required.update(names);rows.append({'checkpoint':p.name,'eligible_members':len(names),'missing_from_final_plan':sorted(names-current)})
report={'checked_utc':datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC'),'mode':'Pre-packaging filename coverage; final archive is also checked after creation','checkpoints':rows,'checkpoint_union_members':len(required),'all_retained':required<=current,'excluded_inputs':['supplied scans','witnesses','context','prior checkpoint ZIPs'],'notes':'Current deliverables replace earlier versions of the same paths. ARCHIVE_MANIFEST.json is generated by make_archive.py; historical checkpoints are not nested.'}
(R/'review/archive_coverage_preflight.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(report,ensure_ascii=False))
assert report['all_retained']
