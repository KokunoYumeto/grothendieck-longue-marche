#!/usr/bin/env python3
"""Independent rank90 and local-quaternion intersection of 81 classes.

The mixed submodule is generated directly in the original Hall basis,
and all eight quaternion matrices are tested.  This does not reuse
the adapted-basis constraints from the other implementation.
"""
import ast
from itertools import product
import json
from pathlib import Path
import numpy as np

PREC=10
MOD=3**PREC
hall=[(i,j,k) for i in range(10) for j in range(i) for k in range(j,10)]
lookup={h:i for i,h in enumerate(hall)}
source=ast.parse(Path('deliverable/code/b_char2_symmetry.py').read_text())
exec(compile(ast.Module(body=[x for x in source.body if isinstance(x,ast.FunctionDef)
       and x.name in {'bracket','lie3','inverse_unit'}],type_ignores=[]),'b_Hall_functions','exec'))
global_data=np.load('deliverable/code/b_global_action_ambiguity_matrices.npz')
sym=np.load('deliverable/code/b_char2_symmetry_matrices.npz')
aff=np.load('deliverable/code/b_char2_translation_affine_matrices.npz')
Z=global_data['arithmetic_Q_and_geometry_coset_numerators']%3
assert Z.shape==(330,4)
assert np.array_equal(global_data['arithmetic_Q_and_geometry_coset_denominators'],np.full(4,3))
U=np.array([[0,-1],[2,-2],[1,0],[0,-2],[1,-1],[2,0],[1,-2],[2,-1]],dtype=np.int64)
u=np.concatenate(([3,0],U[:,0]))
v=np.concatenate(([0,3],U[:,1]))

def rref(matrix,columns=None):
    A=matrix.copy()%3
    if columns is None:columns=A.shape[1]
    pivots=[]
    r=0
    for j in range(columns):
        nz=np.flatnonzero(A[r:,j])
        if not len(nz):continue
        k=r+int(nz[0]);A[[r,k]]=A[[k,r]]
        A[r]=A[r]*int(A[r,j])%3
        for i in range(len(A)):
            if i!=r:A[i]=(A[i]-A[i,j]*A[r])%3
        pivots.append(j);r+=1
        if r==len(A):break
    return A,pivots

def kernel(matrix):
    A,piv=rref(matrix)
    free=[j for j in range(matrix.shape[1]) if j not in piv]
    ans=np.zeros((matrix.shape[1],len(free)),dtype=np.int64)
    for k,j in enumerate(free):
        ans[j,k]=1
        for i,p in enumerate(piv):ans[p,k]=-A[i,j]%3
    assert not np.any(matrix@ans%3)
    return ans,A[:len(piv)]

# J is generated by [u,[e_i,e_j]], [v,[e_i,e_j]] in the ORIGINAL basis.
J=np.zeros((330,90),dtype=np.int64)
column=0
for h in [u,v]:
    for i in range(10):
        for j in range(i):
            for k,a in enumerate(h):
                if a:
                    for row,sgn in bracket(i,j,k):J[row,column]-=int(a)*sgn
            column+=1
assert column==90
aug,pivots=rref(np.column_stack((J,Z)),90)
assert pivots==list(range(90))
mixed=aug[90:,90:]
Km,Rm=kernel(mixed)
assert Km.shape==(4,2)
assert all(not np.any(Z[row]) for row,h in enumerate(hall) if min(h)<2)
print('Original-basis mixed90 generators have a unit minor and leave dimension2: PASS',flush=True)

qactions=[lie3(q%3)%3 for q in sym['Q8_matrices']]
qconditions=np.vstack([(q-np.eye(330,dtype=np.int64))@Z%3 for q in qactions])
Kq,Rq=kernel(qconditions)
assert Kq.shape==(4,2)
combined=np.vstack((mixed,qconditions))
K,Rc=kernel(combined)
assert K.shape==(4,1)
print('All eight local quaternion actions leave dimension2; joint intersection dimension1: PASS',flush=True)

vectors=np.array(list(product(range(3),repeat=4)),dtype=np.int64).T
flags_m=~np.any(mixed@vectors%3,axis=0)
flags_q=~np.any(qconditions@vectors%3,axis=0)
flags=flags_m&flags_q
assert [int(sum(flags_m)),int(sum(flags_q)),int(sum(flags))]==[9,9,3]
z=Z@K[:,0]%3
inner,ip=rref(np.column_stack((aff['ad_w']%3,z)),10)
assert ip==list(range(10)) and np.any(inner[10:,-1])
print('Independent exhaustive81-element counts:9 mixed,9 quaternion,3 joint; surviving line is not inner',flush=True)

parameters=json.loads(Path('deliverable/code/b_char2_translation_affine.json').read_text())['all27_parametrization']
h3=np.array(parameters['order3_direction'],dtype=np.int64)
h9=np.array(parameters['order9_direction'],dtype=np.int64)
domain=aff['domain_moduli']
rows=aff['Smith_row_full_F4']
positive=aff['positive_F4']
local_moduli=aff['affine_row_moduli'][:198]
target=(rows@(5*z)%MOD)[positive]%local_moduli
matches=[]
for a,b in product(range(3),repeat=2):
    x=(a*h3+3*b*h9)%domain
    image=(rows@aff['embedding_F2_to_full_F4']%MOD@x%MOD)[positive]%local_moduli
    if np.array_equal(target,image):matches.append((a,b,x))
assert len(matches)==1
a,b,x=matches[0]
assert a==0 and b in [1,2]
assert set(np.flatnonzero(x))=={11} and int(x[11]) in [27,54]
assert np.any(target) and not np.any(3*target%local_moduli)
print('Remaining generator local Q2 Smith coordinates:',x.tolist(),flush=True)

# An actual local coefficient quotient A(-1) -> C81 detecting the line.
E=sym['invariant_basis'];selected=sym['invariant_rows']
EI=inverse_unit(E[selected,:])
Pi=sum(lie3(q) for q in sym['Q8_matrices'])%MOD*pow(8,-1,MOD)%MOD
Q2=sym['Smith_row_F2'];pos2=sym['positive_F2']
coefficient_detector=Q2[pos2[11],:]@EI%MOD@Pi[selected,:]%MOD%81
assert np.any(coefficient_detector%3)
# Reconstruct the actual Frob2 action to verify it descends as a trivial quotient.
quats=sym['Q8_matrices'];M2=(quats[4,:2,:2]-quats[6,:2,:2])%MOD
Pc=np.zeros((8,8),dtype=np.int64)
for j,i in enumerate([0,2,1,3,5,4,7,6]):Pc[i,j]=1
# Cross block determined modulo81; M2 available modulo3^10 is ample.
raw=U@M2-2*Pc@U
assert not np.any(raw%3)
F2=np.zeros((10,10),dtype=np.int64)
F2[:2,:2]=M2;F2[2:,2:]=2*Pc;F2[2:,:2]=raw//3
F2%=MOD
R2=lie3(F2)*pow(2,-1,MOD)%MOD
assert not np.any(coefficient_detector@(R2-np.eye(330,dtype=np.int64))%81)
print('Primitive local coefficient quotient C81 kills(Frob2−1) and detects the residualC3: PASS',flush=True)

result={'status':'independent original-Hall refinement verified',
        'starting_group':'C3^4','mixed_rank':90,'mixed_group':'C3^2',
        'local_quaternion_group':'C3^2','intersection_group':'C3',
        'exhaustive_counts':[81,9,9,3],
        'mixed_constraints':Rm.tolist(),'quaternion_constraints':Rq.tolist(),
        'combined_constraints':Rc.tolist(),
        'remaining_local_Q2_coordinates':x.tolist(),
        'minimal_local_coefficient_precision':81,
        'scope':'Exact homogeneous ambiguity under the specified constraints, not a realization statement for all three module classes.'}
Path('deliverable/code/b_action_ambiguity_refinement.json').write_text(json.dumps(result,indent=2)+'\n')
np.savez_compressed('deliverable/code/b_action_ambiguity_refinement_matrices.npz',
                    mixed_original_columns=J,global_coset_numerators=Z,
                    mixed_constraints=mixed,quaternion_constraints=qconditions,
                    joint_kernel=K,remaining_numerator=z,
                    remaining_Q2_coordinates=x,local_C81_detector=coefficient_detector)
