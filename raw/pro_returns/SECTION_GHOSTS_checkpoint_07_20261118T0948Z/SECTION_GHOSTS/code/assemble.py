#!/usr/bin/env python3
"""Assemble source fragments, bibliography and the numbered-result register."""
from pathlib import Path
import re, csv
ROOT = Path(__file__).resolve().parents[1]

def brace(text, start):
    assert text[start] == '{'
    depth, i = 1, start+1
    while depth:
        if text[i] == '{' and text[i-1] != '\\': depth += 1
        if text[i] == '}' and text[i-1] != '\\': depth -= 1
        i += 1
    return text[start+1:i-1], i

def statements(text):
    for m in re.finditer(r'\\begin\{result\}', text):
        pos=m.end()
        args=[]
        for _ in range(3):
            while text[pos].isspace():
                pos += 1
            arg,pos=brace(text,pos)
            args.append(arg)
        yield (*args, m.start(), pos)

source = (ROOT/'sections/part_B_audit.tex').read_text()
source = re.sub(r'\\subsection\{[^\n]*\}\s*', '', source)
chunks = list(statements(source))
by_part = {p:[] for p in 'ABE'}
for i, (sid,status,title,start,end) in enumerate(chunks):
    stop = chunks[i+1][3] if i+1 < len(chunks) else len(source)
    by_part[sid[0]].append((sid,source[start:stop]))
for part, blocks in by_part.items():
    blocks.sort(key=lambda b:tuple(map(int,b[0].split('.')[1:])))
    title = {'A':'Arithmetic of the varying family','B':'The unique predecessor and scalar tests','E':'The power completion and the original recursion'}[part]
    target=ROOT/f'sections/part_{part}_arithmetic_generated.tex'
    target.write_text('% Generated by code/assemble.py; edit part_B_audit.tex.\n'+
                      '\\subsection{'+title+'}\n\n'+'\n'.join(b[1] for b in blocks))
    print('assembled', target.name, len(blocks), 'statements')

bibs = sorted((ROOT/'notes').glob('*references.bib'))
bibtext='\n\n'.join(p.read_text() for p in bibs)
# apalike omits the url field. Put verified source links in the note as
# breakable TeX URLs, including URLs already present in source notes.
entries=list(re.finditer(r'@\w+\s*\{',bibtext))
for entry in reversed(entries):
    opening=entry.end()-1
    content, stop=brace(bibtext,opening)
    note_match=re.search(r'\bnote\s*=\s*\{',content,re.I)
    if not note_match:
        raise ValueError('Bibliography entry has no verification note: '+content[:60])
    note, note_stop=brace(content,note_match.end()-1)
    def protect_url(m):
        value=m[0]
        suffix=''
        while value and value[-1] in ',.;':
            suffix=value[-1]+suffix
            value=value[:-1]
        return '\\url{'+value+'}'+suffix
    note=re.sub(r'(?<!\{)https?://[^\s;{}]+',protect_url,note)
    url_match=re.search(r'\burl\s*=\s*\{',content,re.I)
    if url_match:
        source_url,_=brace(content,url_match.end()-1)
        if source_url not in note:
            note += ' Source: \\url{'+source_url+'}.'
    content=content[:note_match.end()]+note+content[note_stop-1:]
    bibtext=bibtext[:opening+1]+content+bibtext[stop-1:]
keys=re.findall(r'@\w+\s*\{\s*([^,\s]+)',bibtext)
assert len(keys)==len(set(keys)), 'duplicate bibliography keys'
(ROOT/'SECTION_GHOSTS_references.bib').write_text(bibtext)
print('bibliography entries:',len(keys))

main=(ROOT/'SECTION_GHOSTS_paper.tex').read_text()
parts=[ROOT/(p+'.tex') for p in re.findall(r'\\input\{([^}]+)\}',main)]
rows=[]
for path in parts:
    text=path.read_text()
    for sid,status,title,start,end in statements(text):
        nextstart=text.find('\\begin{result}',end)
        body=text[end:nextstart if nextstart>=0 else len(text)]
        title_clean=title.replace('\\_','_')
        checks=''
        if 'confirmed' in title_clean.lower(): checks=title_clean
        answers={
          'A.1':'A.1', 'A.2':'A.2; A.3; L.1', 'A.3':'A.3',
          'A.4':'A.5; D.1','A.5':'A.5; D.1','A.6':'A.4','A.7':'A.4; L.4',
          'A.8':'A.1; R.9; L.5','A.101':'A.4; L.2',
          'B.1':'B.1; A.4','B.2':'B.2','B.3':'B.3',
          'C.1':'C.2; L.5','C.2':'C.2','C.3':'C.1; C.2; L.3; L.5',
          'C.4':'C.3; L.5','C.5':'C.1; L.3; L.5','C.6':'C.4; L.6',
          'C.7':'C.1; C.2; C.3; C.4; L.3; L.5; L.6','C.8':'C.1; C.2; L.5',
          'E.1':'E.1','E.2':'E.2','E.20':'E.1; E.2; C.1; R.3; R.7',
          'E.101':'E.1; E.2; R.2','E.102':'E.1; E.2; R.1','E.103':'E.1; E.2; R.1'
        }.get(sid, 'P.1' if sid.startswith('P.') else
              'A.1; A.4; E.1; E.2' if sid.startswith('A.') else
              'B.1; A.4; E.1; E.2' if sid.startswith('B.') else
              'D.1' if sid.startswith('D.') else 'E.1; E.2')
        deps=sorted(set(re.findall(r'\b[A-E]\.\d+(?:\.\d+)?\b',body))-{sid})
        claim=body.split('\\end{result}',1)[0]
        claim=re.sub(r'\\label\{[^}]+\}', '', claim).strip()
        claim=re.sub(r'\s+', ' ', claim)
        rows.append([sid,title_clean+' '+claim,status,str(path.relative_to(ROOT))+'; '+sid,
                     '; '.join(deps),answers,checks,
                     'no', 'cote 149; scans 56,126-127' if sid.startswith('D.') else '',
                     'Incomplete task; see statement and report.' if status=='Open' else
                     'Status applies only to the exact numbered statement.'])
ids=[r[0] for r in rows]
assert len(ids)==len(set(ids)), 'duplicate numbered statements'
# Preserve the full statement and source status from TeX, while importing
# the more precise dependency/scope metadata recorded by each proof reader.
aliases={
  'depends_on':4, 'answers':5, 'answers (item or lead)':5,
  'checks':6, 'checks (the earlier statement it checks, and confirmed / repaired / refuted)':6,
  'uses_local_theorem':7, 'uses_local_theorem (yes or no, and where)':7,
  'manuscript_passages':8, 'manuscript_passages (cote; scan)':8, 'notes':9
}
by_id={r[0]:r for r in rows}
for metadata in sorted((ROOT/'notes').glob('*results.csv')):
    for record in csv.DictReader(metadata.open()):
        sid=record.get('id')
        if sid not in by_id: continue
        assert record.get('status',by_id[sid][2])==by_id[sid][2], (metadata,sid,'status mismatch')
        for key,index in aliases.items():
            if record.get(key): by_id[sid][index]=record[key]
historical=ROOT/'notes/historical_audit.csv'
if historical.exists():
    for record in csv.DictReader(historical.open()):
        for sid in record['current_statements'].split('; '):
            if sid not in by_id: continue
            scope=record['historical_id']+': '+record['audit_status']
            if record['audit_status']=='pending': scope+=' (only the scope stated in historical_audit.csv has been checked)'
            by_id[sid][6]+=('; ' if by_id[sid][6] else '')+scope
with (ROOT/'SECTION_GHOSTS_results.csv').open('w',newline='') as f:
    w=csv.writer(f)
    w.writerow(['id','statement','status','where_proved','depends_on',
                'answers (item or lead)','checks (the earlier statement it checks, and confirmed / repaired / refuted)',
                'uses_local_theorem (yes or no, and where)','manuscript_passages (cote; scan)','notes'])
    w.writerows(rows)
print('numbered result rows:',len(rows))
print('status counts:',{s:sum(r[2]==s for r in rows) for s in ['Proved','Refuted','Known','Open']})

# TeX source checks: bibliography and labelled references. This does not validate proofs.
combined='\n'.join(p.read_text() for p in parts)
cited=set()
for match in re.finditer(r'\\cite\w*(?:\[[^\]]*\])?\{([^}]+)\}',combined):
    cited.update(k.strip() for k in match[1].split(','))
missing=cited-set(keys)
assert not missing, 'missing bibliography keys: '+str(missing)
print('cited bibliography keys:',len(cited),'; missing: 0')
print('PASS: source assembly and register coverage (not proof certification).')
