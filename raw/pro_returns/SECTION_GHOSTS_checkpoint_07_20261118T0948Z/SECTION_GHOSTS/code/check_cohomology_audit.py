"""Exact finite checks supporting SECTION_GHOSTS's cohomology audit.

The polynomial identities are symbolic certificates.  The finite residue
tables illustrate, and do not replace, the infinite derived-limit proof.
"""
from math import gcd
from functools import reduce
import sympy as s

a, b, u, v, w = s.symbols("a b u v w")

def differential(f):
    return s.expand(u**2*f(b, v) - f(a+u*b, u*v) + f(a, u))

f_negative = lambda x, c: -(x*x+c*x)/2
f_right_boundary = lambda x, c: -x*c*w
f_left_boundary = lambda x, c: w*x
checks = {
    "negative valuation Steinberg primitive":
        differential(f_negative) - a*u*(b+(v-1)/2),
    "right Kummer coboundary primitive":
        differential(f_right_boundary) - a*u*(v-1)*w,
    "left Kummer coboundary primitive":
        differential(f_left_boundary) - (u-1)*w*u*b,
}
for name, expression in checks.items():
    result=s.simplify(expression)
    assert result == 0, (name, result)
    print(name + ": symbolic residual = 0")

print("\nIdeal generated by unit squares minus one:")
for p,k,expected in [(2,8,8),(3,5,3),(5,3,1),(7,3,1),(11,2,1)]:
    modulus=p**k
    result=reduce(gcd,[modulus]+[x*x-1 for x in range(modulus) if x%p])
    assert result==expected
    print(f"p={p}, modulus={modulus}, ideal divisor={result}")

def valuation(x,p):
    n=0
    while x and x%p==0:
        n+=1
        x//=p
    return n

print("\nPrimes q_j = 1+3^j modulo 3^(j+1):")
primes=[]
for j in range(1,11):
    step=3**(j+1)
    q=1+3**j
    while not s.isprime(q):
        q+=step
    assert valuation(q-1,3)==j
    primes.append(q)
    print(f"j={j}, q_j={q}, v_3(q_j-1)={valuation(q-1,3)}")

print("\nFinite reductions of z_j=q_j-1 have finite-support primitives:")
for n in range(1,9):
    modulus=3**n
    primitive=[int(j<n) for j in range(1,len(primes)+1)]
    residuals=[((q-1)*y-(q-1))%modulus for q,y in zip(primes,primitive)]
    assert residuals==[0]*len(primes)
    print(f"n={n}, primitive support={sum(primitive)}, all 10 residuals zero")
print("Infinite proof: z is in c_0, but its unique coordinatewise primitive is the constant sequence 1, outside c_0.")
print("No finite table alone establishes an infinite cohomology calculation.")
