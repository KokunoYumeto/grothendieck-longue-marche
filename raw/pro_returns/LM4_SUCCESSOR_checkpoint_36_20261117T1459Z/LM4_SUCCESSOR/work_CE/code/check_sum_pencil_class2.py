"""Exact class-two exponent-p comparison from all 82 sum-pencil relations.

This is an actual finite quotient of the full presented group.  The
source-kernel image is generated under the 19 actual source generators,
not under all 23 ambient generators.  No full-group conclusion is inferred
when this finite quotient fails to distinguish the two images.
"""
from pathlib import Path
from itertools import combinations
import hashlib, json, sys
import numpy as np

ROOT=Path(__file__).resolve().parents[2]
INFILE=ROOT/'work_DE/next_marginal_source/sum_pencil_presentation.json'
OUTFILE=ROOT/'work_CE/sum_pencil_class2.json'
D=json.loads(INFILE.read_text())
n=23
pairs=list(combinations(range(n),2))
index={ij:n+k for k,ij in enumerate(pairs)}
dim=n+len(pairs)

def basis(i):
    x=np.zeros(dim,dtype=np.int64);x[i]=1;return x

def wedge(a,b):
    z=np.zeros(dim,dtype=np.int64)
    for (i,j),k in index.items():z[k]=int(a[i])*int(b[j])-int(a[j])*int(b[i])
    return z

def word_log(w,p):
    # Coordinates (a,2c), with multiplication (a,z)(b,w)=(a+b,z+w+a^b).
    v=np.zeros(dim,dtype=np.int64)
    for letter in w:
        j=abs(letter)-1;s=1 if letter>0 else -1
        for i in range(j):v[index[i,j]]+=s*v[i]
        for k in range(j+1,n):v[index[j,k]]-=s*v[k]
        v[j]+=s;v%=p
    return v

class RowSpace:
    def __init__(self,p):self.p=p;self.rows={}
    def reduce(self,v):
        v=np.array(v,dtype=np.int64,copy=True)%self.p
        for k,r in self.rows.items():
            if v[k]:v=(v-v[k]*r)%self.p
        return v
    def add(self,v):
        v=self.reduce(v);nz=np.flatnonzero(v)
        if not len(nz):return False
        k=int(nz[0]);v=(v*pow(int(v[k]),-1,self.p))%self.p
        self.rows[k]=v;self.rows=dict(sorted(self.rows.items()));return True
    def copy(self):
        t=RowSpace(self.p);t.rows={k:r.copy() for k,r in self.rows.items()};return t
    def __len__(self):return len(self.rows)

results=[]
for p in (3,5,7):
    J=RowSpace(p)
    rel_logs=[word_log(r['word'],p) for r in D['relators']]
    for r in rel_logs:J.add(r)
    for r in rel_logs:
        if np.any(r[:n]):
            for j in range(n):J.add(2*wedge(r,basis(j)))
    assert all(not np.any(J.reduce(r)) for r in rel_logs)
    # Verify ideal closure of every retained relation-space row.
    for r in list(J.rows.values()):
        for j in range(n):assert not np.any(J.reduce(2*wedge(r,basis(j))))
    I=J.copy()
    for u in D['deleted_U_indices']:I.add(basis(u-1))
    for h in D['source_generators']:
        for u in D['deleted_U_indices']:I.add(2*wedge(basis(h-1),basis(u-1)))
    R=I.copy();outside=[]
    for h in range(1,n+1):
        for u in D['deleted_U_indices']:
            br=2*wedge(basis(h-1),basis(u-1))
            if np.any(I.reduce(br)):outside.append([h,u])
            R.add(br)
    # Separately compute the subgroup generated by the source, for context.
    H=J.copy()
    for h in D['source_generators']:H.add(basis(h-1))
    for h,k in combinations(D['source_generators'],2):H.add(2*wedge(basis(h-1),basis(k-1)))
    row={'prime':p,'ambient_Lie_dimension':dim-len(J),
         'relation_ideal_dimension':len(J),'source_image_dimension':len(H)-len(J),
         'source_kernel_image_dimension':len(I)-len(J),
         'ambient_deletion_kernel_dimension':len(R)-len(J),
         'separating_commutators':outside,
         'source_kernel_equals_deletion_kernel_in_this_quotient':len(I)==len(R)}
    results.append(row)
    print(json.dumps(row),flush=True)

OUTFILE.write_text(json.dumps({'scope':__doc__,'input_sha256':hashlib.sha256(INFILE.read_bytes()).hexdigest(),
                              'coordinate_convention':'V plus wedge^2 V, doubled central BCH coordinates',
                              'results':results},indent=2)+'\n')
print('PASS: all actual defining relations and ideal closure checked; no inference beyond these finite quotients.')
