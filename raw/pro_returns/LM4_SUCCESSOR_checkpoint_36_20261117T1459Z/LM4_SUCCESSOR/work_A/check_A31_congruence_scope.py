#!/usr/bin/env python3
"""Finite checks for the noncofinal scope of the relative congruence tower."""
from itertools import permutations
from collections import Counter

n=7;one=tuple(range(n))
def mul(a,b):return tuple(a[b[i]] for i in range(n))
def inv(a):return tuple(a.index(i) for i in range(n))
def cyc(*cs):
 a=list(one)
 for c in cs:
  for u,v in zip(c,c[1:]+c[:1]):a[u-1]=v-1
 return tuple(a)
def parity(a):return sum(a[i]>a[j] for i in range(n) for j in range(i+1,n))%2
def generated(gs):
 gs=tuple(gs)+tuple(map(inv,gs));seen={one};queue=[one]
 for a in queue:
  for g in gs:
   b=mul(a,g)
   if b not in seen:seen.add(b);queue.append(b)
 return frozenset(seen)
a=cyc((1,2,3,4,5,6,7));b=cyc((1,2,3));G=generated((a,b))
assert len(G)==2520 and all(parity(g)==0 for g in G)
# Representatives of all conjugacy classes, by conjugation under the two generators.
remaining=set(G);classes=[]
conjugators=(a,b,inv(a),inv(b))
while remaining:
 x=min(remaining);orb={x};queue=[x]
 for y in queue:
  for g in conjugators:
   z=mul(mul(g,y),inv(g))
   if z not in orb:orb.add(z);queue.append(z)
 classes.append((x,orb));remaining-=orb
# Normal closure of every nonidentity class representative is the whole group.
normal_orders=[]
for x,orb in classes:
 if x==one:continue
 gens=[x];K=generated(gens)
 while True:
  extra=[mul(mul(g,k),inv(g)) for g in conjugators for k in gens]
  new=[k for k in extra if k not in K]
  if not new:break
  gens+=new;K=generated(gens)
 assert len(K)==2520
 normal_orders.append(len(K))
# If A7 were PSL2(F_p), p divides |A7|, so p>=5 leaves only5,7.
assert 5*(5*5-1)//2==60 and 7*(7*7-1)//2==168
print('A7 generated by (1234567),(123):',len(G))
print('Conjugacy-class sizes:',sorted(len(o) for _,o in classes))
print('Nonidentity class normal-closure orders:',normal_orders)
print('Simple:',all(k==2520 for k in normal_orders))
print('Possible characteristic primes >=5 dividing2520: 5,7')
print('Corresponding PSL2(F_p) orders: 60,168, both different from2520')
# Finite representatives of the profinite exponent e2.
for m in (12,24,48,60,120,420):
 twopart=m & -m;odd=m//twopart
 e=next(k for k in range(m) if k%twopart==1%twopart and k%odd==0)
 assert e%2==1 and e*e%m==e
 print('e2 mod',m,'=',e)
