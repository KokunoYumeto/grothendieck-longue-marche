"""Exact source-based F7 actions and four meridians in the tangent-parabola bundle.

All automorphism, inverse, Birman convention and filling checks are literal.
No whole source-image normality is asserted.
"""
from pathlib import Path
import json,itertools,time
HERE=Path(__file__).resolve().parent
data=json.loads((HERE/'tangent_bundle_words.json').read_text())
def red(w):
    out=[]
    for a in w:
        if out and out[-1]==-a:out.pop()
        else:out.append(a)
    return tuple(out)
def inv(w):return tuple(-a for a in w[::-1])
def mul(*ws):return red(itertools.chain.from_iterable(ws))
def sub(w,images):return mul(*(images[a] if a>0 else inv(images[-a]) for a in w))
def artin(w,n=8):
    a=[(j+1,) for j in range(n)]
    for b in w:
        k=abs(b)-1;v,w=a[k:k+2]
        a[k:k+2]=[mul(v,w,inv(v)),v] if b>0 else [w,mul(inv(w),v,w)]
    return tuple(a)
def delete_last(w):
    state=list(range(8));out=[]
    for a in w:
        k=abs(a)-1
        if state[k]!=7 and state[k+1]!=7:
            j=sum(x!=7 for x in state[:k])+1
            out.append(j if a>0 else -j)
        state[k],state[k+1]=state[k+1],state[k]
    assert state[7]==7
    return red(out)
def conjugator(A):
    v=A[-1];i=0
    while len(v)-2*i>1:
        assert v[i]==-v[-1-i];i+=1
    assert v[i:i+1]==(8,)
    return red(a for a in v[:i] if abs(a)!=8)
def push(w):return conjugator(artin(w))
def action(w):
    A=artin(w);q=conjugator(A)
    return {i:mul(inv(q),red(a for a in A[i-1] if abs(a)!=8),q) for i in range(1,8)}
def cyclic_core(w):
    i=0
    while len(w)-2*i>1 and w[i]==-w[-1-i]:i+=1
    return w[i:len(w)-i] if i else w


def A_i(i):
 return tuple(range(7,i,-1))+(i,i)+tuple(range(-i-1,-8,-1))
standards=[A_i(i) for i in range(1,8)]
for w in standards:assert artin(delete_last(w),7)==tuple((i,) for i in range(1,8))
p,q=push(standards[0]),push(standards[1])
assert push(mul(standards[0],standards[1]))==mul(q,p)
assert push(mul(standards[0],standards[1]))!=mul(p,q)
print('Actual last-conjugator is anti; inverse gives fiber homomorphism: PASS')
source=[tuple(r['word']) for r in data['loops']]
actions={};inverse_actions={};fiber={};started=time.monotonic()
for k,w in enumerate(source):
 if k<6:
  A=action(w);Ai=action(inv(w))
  for i in range(1,8):
   assert sub(A[i],Ai)==(i,) and sub(Ai[i],A)==(i,)
   assert len(cyclic_core(A[i]))==1
  test=standards[k]
  assert push(mul(w,test,inv(w)))==sub(push(test),A)
  actions[k]=A;inverse_actions[k]=Ai
  print('Old',k,data['loops'][k]['name'],'action lengths',[len(A[i]) for i in range(1,8)])
 else:
  assert artin(delete_last(w),7)==tuple((i,) for i in range(1,8))
  w=inv(push(w));assert len(cyclic_core(w))==1
  fiber[k]=w
  print('New',k,data['loops'][k]['name'],'word',w,'core',cyclic_core(w))
initial=data['initial_order']
assert initial[-1]==5
keep={i+1 for i,j in enumerate(initial[:-1]) if j in (0,6,7)}
killed=set(range(1,8))-keep
filling={i:((sorted(keep).index(i)+1,) if i in keep else ()) for i in range(1,8)}
assert {abs(cyclic_core(w)[0]) for w in fiber.values()}==killed
assert all(not sub(w,filling) for w in fiber.values())
for A in list(actions.values())+list(inverse_actions.values()):
 assert all(not sub(A[i],filling) for i in killed)
 assert all(len(cyclic_core(sub(A[i],filling)))==1 for i in keep)
print('Retained',sorted(keep),'killed',sorted(killed),'actual filling PASS')
out={'description':__doc__,'initial_order':initial,'source_braids':source,'old_actions':actions,'old_inverse_actions':inverse_actions,'new_fiber_words':fiber,'retained_basis':sorted(keep),'killed_basis':sorted(killed),'filling':filling,'standard_pure_generators':standards,'convention':'push anti; inverse(push) is fiber hom; action verified on conjugated standard braid','source_image':'subgroup generated by all six-action orbits of the four displayed new words; completed actual compact image is its closure','not_proved':['whole marginal source image equals filling kernel','actual K=1']}
(HERE/'tangent_bundle_fiber_data.json').write_text(json.dumps(out,indent=2)+'\n')
print('PASS complete tangent-bundle source data; seconds',round(time.monotonic()-started,3))
