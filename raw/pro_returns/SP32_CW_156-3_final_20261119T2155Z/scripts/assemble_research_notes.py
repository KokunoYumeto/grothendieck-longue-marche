#!/usr/bin/env python3
"""Assemble authored research notes only; frozen transcription is read-only."""
from pathlib import Path
import csv
import datetime
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
STEM = 'SP32_CW_156-3'
for line in (ROOT/'records/frozen.sha256').read_text().splitlines():
    digest, rel = line.split(None, 1)
    assert hashlib.sha256((ROOT/rel.strip()).read_bytes()).hexdigest() == digest, rel

def items(filename):
    text = (ROOT/'research'/filename).read_text()
    text = text.split('\n## Appendix', 1)[0]
    found = {}
    matches = list(re.finditer(r'^### ((?:ALG|ORD|REC|ROOT|CTX)-\d+)\b.*$', text, re.M))
    for n, match in enumerate(matches):
        end = matches[n+1].start() if n+1 < len(matches) else len(text)
        piece = text[match.start():end].strip()
        piece = piece.split('\n## Relation to all nine', 1)[0].strip()
        found[match.group(1)] = piece
    return found

all_items = {}
for name in ['order_components.md','algebra.md','reconstruction_context.md',
             'root_additional_notes.md','root_context_and_standing.md']:
    all_items.update(items(name))

page_groups = [
('026–027 · Endpoints, relative frontier, and closed hulls', ['ORD-01','ORD-02']),
('028–029 · Intersection, precedence, and the interstice', ['ORD-03','ORD-04','ORD-05','ROOT-05']),
('030–032 · Components, complements, and the compatibility question', ['ORD-06','ORD-07','ORD-08','ORD-09','ORD-10']),
('033 · Compatible Boolean operations and closure', ['ALG-01','ALG-02','ALG-11','ALG-12','ALG-14']),
('034 · The dimension-one assertion and algebraic notation', ['ROOT-01','ROOT-02','ALG-03','ALG-04','ALG-05']),
('035–037 · Relativization and the clopen expectation', ['ALG-06','ALG-07','ALG-08','ALG-10','ALG-09','ALG-13']),
('038–039 · The component argument and its finite hypothesis', ['ROOT-03','ORD-11','ORD-12']),
('040 · Generated algebras and canonical subdivisions', ['ROOT-04','ORD-13','ORD-14','ORD-15']),
('041 · What the cut data reconstruct', [f'REC-{i:02}' for i in range(1,8)]),
]

context = (ROOT/'research/root_context_and_standing.md').read_text()
source = context.split('## Source key and limits\n',1)[1].split('## Standing question 1',1)[0].strip()
standing = '## Standing question 1' + context.split('## Standing question 1',1)[1].split('## Contextual notes beyond',1)[0].rstrip()
open_items = '## Relation to all nine' + context.split('## Relation to all nine',1)[1]
algebra = (ROOT/'research/algebra.md').read_text()
assumptions = algebra.split('## Assumptions and context locators\n',1)[1].split('## Item notes',1)[0].strip()

header = '''# Research notes — Alexander Grothendieck, cote 156-3, scans 026–041

## Findings and scope

The sixteen pages develop a finite-interval model, propose an abstract partially Boolean closure structure, prove a relative construction, and end with an unfinished reconstruction problem. These notes keep those four levels separate. **The transcription remains frozen; every mathematical repair below is a research statement only.**

The strongest findings are:

- **The total-order model is sound in the stated finite setting.** Separated interval components, complement counts, relative clopenness and connectedness have direct proofs; “connected” is not ordinary topological connectedness on every dense order (ORD-06–08, ORD-12, ROOT-02).
- **The reported non-total class is too broad for several concrete assertions.** The doubled rational order makes the closed-parent presentation ambiguous; a Hausdorff strict-coordinate model still lacks a least closed moderate hull and refutes the implications from pointwise precedence or inclusion to moderate position (ORD-02, ORD-04). These countermodels use the definition of the earlier scan 009 as reported in the supplied sweep, not newly inspected ink.
- **The interstitial proposition survives with its explicit hypotheses.** Actual suprema and infima are essential; boundedness alone does not supply them (ORD-05). The proposed meet-existence test for compatibility fails, but that does not settle the broader order-definability question (ORD-09).
- **The relative theorem is valid under the strengthened Boolean compatibility assumption.** Clopen centrality is a separate expectation and fails in a six-element model satisfying those assumptions (ALG-07–09). The doubtful double-prime branch is not silently substituted into that coherent axiom system (ALG-11).
- **The algebra generated by the given sets can be smaller than the endpoint-cell algebra.** A single open interval generates four Boolean elements, while its five endpoint cells generate thirty-two; even adding closure alone gives only eight in that example (ORD-13–14). This issue survives the index correction suggested for the literal interval on scan 040.
- **Pair cuts reconstruct the biorder in the specified dense model.** Explicit proofs check the two Hua mathematical claims conditionally, while recognizing arbitrary abstract cut data remains unfinished (REC-01–07). Two natural inverse-system interpretations of S14 need extra conditions, and no tame–PL, simple-homotopy, or general exit theorem follows here (REC-08–14).

Every catalogue item has its own ID, source position, kind, short quotation or formula, context relation, and applicable register IDs. Own deductions carry their scope and confidence. The longer proof files and reproducible finite certificates are listed at the end; they are part of this research deliverable.

## Sources and provenance

'''

out = [header,source,'\n\n## Algebra notation and the precise strengthened assumption\n\n',assumptions,
       '\n\n## Page-by-page research catalogue\n\n']
for title, ids in page_groups:
    out.append('## '+title+'\n\n')
    for key in ids:
        assert key in all_items,key
        out.append(all_items[key]+'\n\n')
out.append('## Connections, reconstruction limits, and the planning questions\n\n')
for key in ['ROOT-06']+[f'CTX-{i:02}' for i in range(1,7)]+[f'REC-{i:02}' for i in range(8,15)]:
    out.append(all_items[key]+'\n\n')
out.append(standing+'\n\n'+open_items.strip()+'\n\n')
out.append('''## Detailed proofs, certificates, and check-event interpretation

| File | Contents and scope |
|---|---|
| `research/order_components.md` | Endpoint and hull countermodels; the corrected actual-extrema interstice theorem; total-order component/count proofs; subdivision-algebra certificate. |
| `research/algebra.md` | Precise PB assumption; independent relative theorem; six-element clopen countermodel; closure-operation and arbitrary-family qualifications. |
| `research/reconstruction_context.md` | Explicit order-recovery formula; cut-to-betweenness calculation; finite discrete obstruction; inverse-system examples; context comparisons. |
| `research/peer_review.md` | Independent research review, including the correction that the quadrant example has no actual supremum and therefore does not refute the conditional scan-029 theorem. |
| `research/root_additional_notes.md` | Primary-reader checks of rarity, spectrum versus atoms, literal separator variables, and withdrawn formulations. |
| `research/algebra_checks.py` and `research/algebra_checks_output.json` | Exact finite verification of the logical models; the output labels the deliberately weak countermodel's scope. |
| `research/check_subdivision_algebra.py` and `research/subdivision_algebra_certificate.json` | Exact five-cell calculation giving Boolean generation sizes 4, 8, and 32 under the three specified operation sets. |
| `CHECK_EVENTS.tsv` | Mathematical proof, use, background and refutation events with actual UTC time and worker provenance; no transcription reading is counted as a proof. |

The research records are preserved with their authorship and proof-development provenance. This consolidated catalogue and the explicit final qualifications in the proof files control their interpretation. In particular, no general failure is inferred where a theorem assumes actual extrema or PB, and no background register claim is promoted to independently established status merely by being cited. The optional computations certify only their finite models; they do not certify manuscript readings or a universal theorem.
''')
(ROOT/f'{STEM}_notes.md').write_text(''.join(out))

fields = ['statement_id','date','who','type','outcome']
rows = []
for path in sorted((ROOT/'research').glob('*events.tsv')):
    with path.open(newline='') as f:
        reader=csv.DictReader(f,delimiter='\t')
        assert reader.fieldnames==fields,path
        rows.extend(reader)
with (ROOT/'CHECK_EVENTS.tsv').open('w',newline='') as f:
    w=csv.DictWriter(f,fieldnames=fields,delimiter='\t');w.writeheader();w.writerows(rows)
now=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')
with (ROOT/'progress.log').open('a') as f:
    f.write(f'research notes assembled {now}; {len(all_items)} catalogue items; {len(rows)} mathematical/background events; frozen hashes unchanged\n')
print(f'{len(all_items)} items; {len(rows)} check events; notes {len("".join(out).split())} words; {now}')
